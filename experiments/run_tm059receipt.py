def score_attempts(ag: NeuralCortex, attempts: list[dict[str, Any]]) -> dict[str, Any]:
    unused = unused_keyword()
    n_observer = 0
    n_missing = 0
    n_mismatch = 0
    n_append = 0
    n_evict = 0
    evicted: set[str] = set()
    unreported_stuck = 0
    for item in attempts:
        rec = item["receipt"]
        if str(rec.get("outcome") or "") != "evict_append":
            continue
        eid = rec.get("evicted_provenance_id")
        if eid is None:
            continue
        evicted.add(str(eid))
        if locate_by_receipt(ag, {"provenance_id": str(eid)}) is not None:
            unreported_stuck += 1
    for item in attempts:
        rec = item["receipt"]
        outcome = str(rec.get("outcome") or "")
        pid = rec.get("provenance_id")
        if pid is None or str(pid) == unused:
            n_observer += 1
            continue
        if outcome == "append":
            n_append += 1
        elif outcome == "evict_append":
            n_evict += 1
            if rec.get("evicted_provenance_id") is None:
                n_evict -= 1
        if outcome == "reject":
            continue
        if str(pid) in evicted:
            continue
        hit = locate_by_receipt(ag, rec)
        if hit is None:
            n_missing += 1
            continue
        if hit["key_hash"] != item["key_hash"] or hit["value_hash"] != item["value_hash"]:
            n_mismatch += 1
    rows = snapshot_rows(ag)
    live = {r["provenance_id"] for r in rows}
    unreported = 0
    for item in attempts:
        rec = item["receipt"]
        pid = rec.get("provenance_id")
        if pid is None or str(rec.get("outcome") or "") == "reject":
            continue
        sid = str(pid)
        if sid not in live and sid not in evicted:
            unreported += 1
    unreported += unreported_stuck
    return {
        "n_observer_provenance": int(n_observer),
        "n_resident_missing": int(n_missing),
        "n_attempted_hash_mismatch": int(n_mismatch),
        "n_unreported_loss": int(unreported),
        "n_append": int(n_append),
        "n_evict": int(n_evict),
        "n_residents": len(rows),
        "evicted": sorted(evicted),
    }


def run_probe(*, tmp: str, probe: str, wi: int) -> dict[str, Any]:
    p = load_prereg()
    ag = make_agent(tmp, f"rc_{probe}_w{wi}", int(wi))
    handles = list(
        capacity_world(int(wi), str(p["domains"]["DEV"]), n_cues=int(p["n_facts"]), n_handles=int(p["n_handles"]))[
            "handles"
        ]
    )
    getattr(ag, str(p["flag_setter"]))(True)
    n = int(ag.genome.n)
    seed = int(p["seed_registry"]) + 1000 * int(wi)
    h0, h1 = handles[0], handles[1]
    attempts: list[dict[str, Any]] = []

    def record(key: np.ndarray, value: np.ndarray, handle: str) -> dict[str, Any]:
        rec = emit(ag, key=key, value=value, handle=handle)
        item = {
            "receipt": rec,
            "key_hash": hvec(key),
            "value_hash": hvec(value),
            "handle": str(handle),
        }
        attempts.append(item)
        return rec

    if probe == "write":
        v0, v1 = near_pair(n, seed)
        record(distinct_unit(n, seed, 0), v0, h0)
        record(distinct_unit(n, seed, 1), v1, h1)
        shared = distinct_unit(n, seed, 2)
        record(distinct_unit(n, seed, 3), shared, h0)
        record(distinct_unit(n, seed, 4), shared.copy(), h0)
    elif probe == "capacity":
        for i in range(int(EPISODE_SLOTS) + 1):
            record(distinct_unit(n, seed, 20 + i), distinct_unit(n, seed, 40 + i), handles[i % len(handles)])
    elif probe == "checkpoint":
        for i in range(3):
            record(distinct_unit(n, seed, 60 + i), distinct_unit(n, seed, 80 + i), handles[i % len(handles)])
    else:
        raise RuntimeError(probe)
    stats = score_attempts(ag, attempts)
    n_cross_action = 0
    n_cross_cue = 0
    if probe == "write":
        if stats["n_residents"] < 4:
            n_cross_action = 1
            n_cross_cue = 1
    checkpoint_ok = True
    if probe == "checkpoint":
        snap = ag.checkpoint()
        twin = NeuralCortex(None, genome=copy.deepcopy(ag.genome), device=str(ag.device))
        twin.load_checkpoint(snap)
        flag_on = bool(getattr(twin, str(p["flag_attr"]), False))
        left = [(r["provenance_id"], r["key_hash"], r["value_hash"], r["when"]) for r in snapshot_rows(ag)]
        right = [(r["provenance_id"], r["key_hash"], r["value_hash"], r["when"]) for r in snapshot_rows(twin)]
        checkpoint_ok = bool(flag_on and left == right)
        for item in attempts:
            hit = locate_by_receipt(twin, item["receipt"])
            if hit is None:
                stats["n_resident_missing"] += 1
                checkpoint_ok = False
            elif hit["key_hash"] != item["key_hash"] or hit["value_hash"] != item["value_hash"]:
                stats["n_attempted_hash_mismatch"] += 1
                checkpoint_ok = False
    passed = bool(
        n_cross_action == 0
        and n_cross_cue == 0
        and stats["n_observer_provenance"] == 0
        and stats["n_resident_missing"] == 0
        and stats["n_attempted_hash_mismatch"] == 0
        and stats["n_unreported_loss"] == 0
        and checkpoint_ok
    )
    if probe == "write":
        passed = bool(passed and stats["n_residents"] == 4 and stats["n_append"] == 4)
    if probe == "capacity":
        passed = bool(
            passed
            and stats["n_evict"] == 1
            and stats["n_residents"] == int(EPISODE_SLOTS)
            and stats["n_append"] == int(EPISODE_SLOTS)
        )
    if probe == "checkpoint":
        passed = bool(passed and stats["n_residents"] == 3 and stats["n_append"] == 3)
    code = "probe_ok" if passed else "probe_fail"
    out = {
        "kind": "scored",
        "id": f"{probe}|w{wi}",
        "probe": probe,
        "world": int(wi),
        "passed": bool(passed),
        "cell_code": code,
        "not_exercised": False,
        "n_cross_action_refresh": int(n_cross_action),
        "n_cross_cue_merge": int(n_cross_cue),
        "n_observer_provenance": int(stats["n_observer_provenance"]),
        "n_resident_missing": int(stats["n_resident_missing"]),
        "n_attempted_hash_mismatch": int(stats["n_attempted_hash_mismatch"]),
        "n_unreported_loss": int(stats["n_unreported_loss"]),
        "n_evict": int(stats["n_evict"]),
        "n_append": int(stats["n_append"]),
        "n_residents": int(stats["n_residents"]),
        "checkpoint_ok": bool(checkpoint_ok),
        "receipts": [item["receipt"] for item in attempts],
        "candidate_v41_lock": False,
        "kqv_edited": False,
    }
    assert_finite_record(out, ctx=out["id"])
    return out


