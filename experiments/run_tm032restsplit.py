def freeze_runner_sha() -> None:
    p = load_prereg()
    if p.get("frozen_runner_sha"):
        raise RuntimeError("already frozen")
    p["frozen_runner_sha"] = sha_file(THIS)
    PREREG.write_text(json.dumps(p, indent=2) + "\n", encoding="utf-8")


