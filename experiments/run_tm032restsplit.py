def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def registry_seeds() -> list[int]:
    seeds = [int(s) for s in load_prereg()["registry_seeds"]]
    if len(seeds) != 4:
        raise RuntimeError("need four registry seeds")
    if DEFAULT_SEED_REGISTRY in seeds:
        raise RuntimeError("default seed_registry is not a replicate")
    return seeds


def _fresh(tmp: str, tag: str, world: dict[str, Any], *, seed_registry: int) -> NeuralCortex:
    ag = make_cortex(Path(tmp) / tag, genome=genome_for_registry(seed_registry), device="cpu")
    ag.genome.act_recall_mode = TREATMENT_MODE
    ag.genome.episodic_act_recall = False
    ag.bind_actuators(list(world["handles"]))
    if str(ag.genome.act_score_mode) != ACT_SCORE_QUERY:
        raise RuntimeError("scoring must remain query")
    return ag


def clone_plastic(snap: dict[str, Any], genome: GenomeConfig) -> NeuralCortex:
    twin = NeuralCortex(None, genome=copy.deepcopy(genome), device="cpu")
    twin.load_checkpoint(snap)
    twin.genome.act_recall_mode = TREATMENT_MODE
    twin.genome.episodic_act_recall = False
    return twin


def parent_fingerprint(ag: NeuralCortex) -> dict[str, Any]:
    return {
        "w_act": float(ag.W_act_query.detach().sum().item()),
        "w_slow_act": float(ag.W_slow["W_act_query"].detach().sum().item()),
        "n_episodes": len(ag._episodes),
        "episode_clock": int(ag._episode_clock),
        "n_inserts": int(ag._episode_n_inserts),
        "n_replaced": int(ag._episode_n_replaced),
        "n_rest_replay": int(ag._n_rest_replay),
        "dev_epoch": int(ag.dev_epoch),
        "rho_sum": float(ag.rho.detach().sum().item()),
    }


def eta_act(ag: NeuralCortex) -> float:
    return float(ag.genome.eta_act) * ag._age_scale("eta_act_scale", 1.0)


def gated_rehearsal(
    ag: NeuralCortex,
    *,
    max_updates: int | None = None,
) -> dict[str, Any]:
    total = 0
    first: int | None = None
    exhausted = True
    passes: list[dict[str, Any]] = []
    eta = eta_act(ag)
    for idx in range(1, EPISODE_REPLAY_EPOCHS + 1):
        if max_updates is not None and total >= int(max_updates):
            exhausted = False
            break
        ps = ag._gated_rehearsal_pass(eta, pass_index=idx)
        total += int(ps["n_updates"])
        passes.append(dict(ps))
        if int(ps["violations_after"]) == 0:
            first = idx
            exhausted = False
            break
    else:
        exhausted = True
    return {
        "n_updates": int(total),
        "first_converged_pass": first,
        "budget_exhausted": bool(exhausted),
        "n_passes": len(passes),
        "mix_slow": False,
        "rest_wrapper": False,
    }


def rest_idle_ticks(ag: NeuralCortex, n_ticks: int) -> dict[str, int]:
    n_ticks = int(max(0, n_ticks))
    body_arr = np.asarray(ag.last_body, dtype=np.float64)
    fatigued = body_arr.copy()
    if fatigued.shape[0] >= 4:
        fatigued[3] = min(1.0, float(fatigued[3]) + 0.3)
    ops: dict[str, int] = {}
    ag._resting = True
    try:
        for i in range(n_ticks):
            out = ag.observe(
                {
                    "interaction_token": f"rest_{ag._t}_{i}",
                    "source_token": "src_rest",
                    "ordered_symbols": [],
                    "observable_state": ["st_idle"],
                    "body_state": fatigued.tolist(),
                }
            )
            op = str((out.get("action") or {}).get("op") or "?")
            ops[op] = ops.get(op, 0) + 1
    finally:
        ag._resting = False
    return ops


def apply_arm(ag: NeuralCortex, arm: str, *, rest_n_replay: int | None, n_ticks: int) -> dict[str, Any]:
    if arm == "none":
        return {
            "n_updates": 0,
            "first_converged_pass": None,
            "budget_exhausted": False,
            "n_passes": 0,
            "mix_slow": False,
            "rest_wrapper": False,
        }
    if arm == "awake_only":
        cap = None if rest_n_replay is None else int(rest_n_replay)
        out = gated_rehearsal(ag, max_updates=cap)
        out["compute_matched_to_full_rest_n_replay"] = cap
        return out
    if arm == "replay_no_mix":
        ops = rest_idle_ticks(ag, n_ticks)
        out = gated_rehearsal(ag, max_updates=None)
        ag.reset_rho()
        ag._maybe_grow_prune()
        ag.dev_epoch += 1
        out["rest_wrapper"] = True
        out["idle_op_counts"] = ops
        return out
    if arm == "mix_only":
        before = int(ag._count_store_violations())
        ag._clip_and_consolidate({"W_act_query"}, mix_slow=True)
        return {
            "n_updates": 0,
            "first_converged_pass": None,
            "budget_exhausted": False,
            "n_passes": 0,
            "mix_slow": True,
            "rest_wrapper": False,
            "violations_before_mix": before,
            "violations_after_mix": int(ag._count_store_violations()),
        }
    if arm == "full_rest":
        rest_out = ag.rest_epoch(int(n_ticks))
        rh = rest_out.get("rehearsal") or {}
        return {
            "n_updates": int(rh.get("total_updates") or rh.get("n_replay") or 0),
            "first_converged_pass": rh.get("first_converged_epoch"),
            "budget_exhausted": bool(rh.get("budget_exhausted")),
            "n_passes": len(list(rh.get("epochs") or [])),
            "mix_slow": True,
            "rest_wrapper": True,
            "violations_pre_mix": rh.get("violations_pre_mix"),
            "violations_post_mix": rh.get("violations_post_mix"),
            "idle_op_counts": rest_out.get("op_counts"),
        }
    raise ValueError(arm)


def stored_rows(ag: NeuralCortex) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for i, ep in enumerate(ag._episodes):
        if not ep.get("valid"):
            continue
        p1 = np.asarray(ep["p1"], dtype=np.float64)
        handle = str(ep["handle"])
        kr = ep.get("key_rho")
        scores, addr, meta = ag.actuator_decision_scores(p1, key_rho=None if kr is None else np.asarray(kr, dtype=np.float64))
        winner = unique_winner(scores)
        g = probe_geometric_margin(ag, addr, scores, handle)
        rows.append(
            {
                "slot": int(i),
                "handle": handle,
                "store_violation": bool(ag._episode_rehearsal_violation(p1, handle, float(ep["adv"]))),
                "retrieved_slot": meta.get("slot"),
                "path": meta.get("path"),
                "familiar": meta.get("familiar"),
                "winner": winner,
                "ranking_ok": bool(winner == handle),
                "normalized_geometric_margin": float(g),
                "d1": meta.get("nearest_dist"),
                "d2": meta.get("second_nearest_dist"),
                "R": meta.get("R"),
            }
        )
    return rows


def live_probes(
    ag: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    taught: list[dict[str, Any]],
    *,
    tag: str,
) -> dict[str, Any]:
    teach_index = {str(t["cue"]): int(i) for i, t in enumerate(taught)}
    probes = []
    ranking_ok = True
    n_ok = 0
    gammas = []
    for i, (cue, handle) in enumerate(pairs):
        probe = clone_frozen(ag)
        observe_cue(probe, world, tag=f"{tag}_p{i}", body=list(MID_BODY), symbols=[cue])
        p1 = probe._last_p1
        if p1 is None:
            p1 = probe._from_t(probe.rho)
        scores, addr, meta = probe.actuator_decision_scores(p1)
        winner = unique_winner(scores)
        rank = bool(winner == handle)
        ranking_ok = ranking_ok and rank
        n_ok += int(rank)
        g = probe_geometric_margin(probe, addr, scores, handle)
        gammas.append(float(g))
        probes.append(
            {
                "cue": cue,
                "want": handle,
                "winner": winner,
                "ranking_ok": rank,
                "teach_index": int(teach_index[cue]),
                "slot": meta.get("slot"),
                "path": meta.get("path"),
                "familiar": meta.get("familiar"),
                "normalized_geometric_margin": float(g),
                "d1": meta.get("nearest_dist"),
                "d2": meta.get("second_nearest_dist"),
                "R": meta.get("R"),
            }
        )
    return {
        "probes": probes,
        "ranking_ok": bool(ranking_ok),
        "n_probe_correct": int(n_ok),
        "min_normalized_geometric_margin": float(min(gammas) if gammas else 0.0),
    }


def arm_fixes(rec: dict[str, Any]) -> bool:
    return bool(int(rec.get("n_store_violations") or 0) == 0 and rec.get("live_ranking_ok") and int(rec.get("n_probe_correct") or 0) == 8)


def route_split(arm_map: dict[str, dict[str, Any]]) -> str:
    if arm_fixes(arm_map["none"]):
        return "baseline_already_converged"
    awake = arm_fixes(arm_map["awake_only"])
    mix = arm_fixes(arm_map["mix_only"])
    replay = arm_fixes(arm_map["replay_no_mix"])
    full = arm_fixes(arm_map["full_rest"])
    if awake:
        return "awake_rehearsal_sufficient"
    if mix:
        return "slow_mix_sufficient"
    if replay:
        return "rest_replay_without_mix_sufficient"
    if full:
        return "full_rest_interaction_only"
    return "compute_matched_wall"


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = []
    for ri, _seed in enumerate(p["registry_seeds"]):
        for order in list(p["orders"]):
            for arm in list(p["arms"]):
                ids.append(f"split|c8|{order}|reg{ri}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "registry_seeds": list(p["registry_seeds"]),
        "arms": list(p["arms"]),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM032 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError(f"expected {EXPECTED_N_CELLS} cells, got {len(ids)}")
    return ids


def score_arm(
    ag: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    taught: list[dict[str, Any]],
    *,
    tag: str,
) -> dict[str, Any]:
    rows = stored_rows(ag)
    live = live_probes(ag, world, pairs, taught, tag=tag)
    rec = {
        "n_store_violations": int(ag._count_store_violations()),
        "n_episodes": len(ag._episodes),
        "stored_rows": rows,
        "stored_p1_ranking_ok": bool(rows) and all(bool(r.get("ranking_ok")) for r in rows),
        "live_ranking_ok": bool(live["ranking_ok"]),
        "n_probe_correct": int(live["n_probe_correct"]),
        "min_normalized_geometric_margin": float(live["min_normalized_geometric_margin"]),
        "probes": live["probes"],
    }
    rec["fixed"] = arm_fixes(rec)
    return rec


def eval_split(
    *,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    seed_registry: int,
    reg: int,
    n_ticks: int,
) -> tuple[list[dict[str, Any]], str]:
    seq = list(reversed(pairs)) if order == "B_then_A" else list(pairs)
    tmp = tempfile.TemporaryDirectory(prefix="rs_train_")
    try:
        ag = _fresh(tmp.name, "s", world, seed_registry=seed_registry)
        taught, _bursts = teach_pairs(ag, world, seq, tag=f"split_{order}_reg{reg}")
        snap = ag.checkpoint()
        genome = copy.deepcopy(ag.genome)
        parent_before = parent_fingerprint(ag)
        full_twin = clone_plastic(snap, genome)
        full_proc = apply_arm(full_twin, "full_rest", rest_n_replay=None, n_ticks=n_ticks)
        rest_n_replay = int(full_proc["n_updates"])
        cells: list[dict[str, Any]] = []
        arm_map: dict[str, dict[str, Any]] = {}
        for arm in ARMS:
            twin = clone_plastic(snap, genome)
            if arm == "full_rest":
                proc = dict(full_proc)
                scored = score_arm(full_twin, world, pairs, taught, tag=f"{order}_reg{reg}_{arm}")
            else:
                proc = apply_arm(twin, arm, rest_n_replay=rest_n_replay, n_ticks=n_ticks)
                scored = score_arm(twin, world, pairs, taught, tag=f"{order}_reg{reg}_{arm}")
            rec = {
                "kind": "split",
                "arm": arm,
                "id": f"split|c8|{order}|reg{reg}|{arm}",
                "order": order,
                "reg": int(reg),
                "seed_registry": int(seed_registry),
                "n_cues": 8,
                "act_recall_mode": TREATMENT_MODE,
                "taught": taught,
                "process": proc,
                **scored,
            }
            rec["passed"] = bool(rec["fixed"])
            rec["behavioral_pass"] = bool(rec["fixed"])
            assert_finite_record(rec, ctx=rec["id"])
            cells.append(rec)
            arm_map[arm] = rec
        parent_after = parent_fingerprint(ag)
        if parent_before != parent_after:
            raise RuntimeError(f"parent mutated during split {order} reg{reg}")
        route = route_split(arm_map)
        for rec in cells:
            rec["split_route"] = route
            rec["parent_unchanged"] = True
        return cells, route
    finally:
        tmp.cleanup()


def _decision(split_routes: list[str]) -> tuple[str, str, dict[str, Any]]:
    diagnostic = [r for r in split_routes if r != "baseline_already_converged"]
    flags = {
        "n_splits": len(split_routes),
        "n_diagnostic": len(diagnostic),
        "n_baseline_converged": sum(1 for r in split_routes if r == "baseline_already_converged"),
        "routes": list(split_routes),
    }
    if not diagnostic:
        return "restsplit_no_value_fail_on_fresh_domains", "restsplit_no_value_fail_on_fresh_domains", flags
    uniq = set(diagnostic)
    if uniq == {"awake_rehearsal_sufficient"}:
        code = "restsplit_awake_rehearsal_sufficient"
    elif uniq == {"slow_mix_sufficient"}:
        code = "restsplit_slow_mix_sufficient"
    elif uniq == {"rest_replay_without_mix_sufficient"}:
        code = "restsplit_replay_no_mix_sufficient"
    elif uniq == {"full_rest_interaction_only"}:
        code = "restsplit_full_rest_only"
    elif uniq == {"compute_matched_wall"}:
        code = "restsplit_compute_matched_wall"
    else:
        code = "restsplit_mixed_routes"
    return code, code, flags


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and sha_file(THIS) != frozen:
        raise RuntimeError("TM032 runner SHA drifted after freeze push")
    if sha_file(TM031_RUNNER) != p["tm031_runner_sha"]:
        raise RuntimeError("TM031 runner SHA drifted")
    if hashlib.sha256(TM031_FAILCLASS.read_bytes()).hexdigest() != p["tm031_failclass_sha"]:
        raise RuntimeError("TM031 failclass SHA drifted")
    if hashlib.sha256(TM031_DEC.read_bytes()).hexdigest() != p["tm031_decision_sha"]:
        raise RuntimeError("TM031 decision SHA drifted")
    if hashlib.sha256(TM031_DEV.read_bytes()).hexdigest() != p["tm031_dev_sha"]:
        raise RuntimeError("TM031 DEV SHA drifted")
    ids = expected_cell_ids()
    wi = int(p.get("world_index") or 0)
    n_ticks = int(p.get("n_rest_ticks") or 4)
    world = capacity_world(wi, DEV_DOMAIN, n_cues=8, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    cells: list[dict[str, Any]] = []
    split_routes: list[str] = []
    for ri, seed in enumerate(registry_seeds()):
        for order in list(p["orders"]):
            split_cells, route = eval_split(
                world=world,
                pairs=pairs,
                order=order,
                seed_registry=int(seed),
                reg=ri,
                n_ticks=n_ticks,
            )
            cells.extend(split_cells)
            split_routes.append(route)
    if len(split_routes) != EXPECTED_N_SPLITS:
        raise RuntimeError(f"expected {EXPECTED_N_SPLITS} splits")
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(split_routes)
    git_head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_splits": len(split_routes),
        "cells": cells,
        "split_routes": split_routes,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": git_head,
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "act_recall_mode_treatment": TREATMENT_MODE,
        "v38_route": (p.get("v38_route") or {}).get(code),
    }


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


