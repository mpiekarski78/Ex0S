def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "earned_kqv": False,
        "earned_learned_addressing": False,
        "episodic_loop_complete": False,
        "separate_candidate_review_open": False,
    }
    if any(f"decoder|w{wi}" not in by or not bool(by[f"decoder|w{wi}"].get("passed")) for wi in (0, 1)):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    def codes(arm: str) -> list[str]:
        return [str(by[f"{arm}|w{wi}"]["cell_code"]) for wi in (0, 1)]
    if any(c == "scalar_control_fail" for c in codes("scalar_only")):
        return "scalar_control_fail", "scalar_control_fail", flags
    fb = codes("action_feedback")
    for step in (
        "feedback_rho_absent",
        "feedback_not_decodable",
        "stored_value_loss",
        "reinstatement_fail",
        "canonical_only_fail",
    ):
        if any(c == step for c in fb):
            return step, step, flags
    if any(c == "no_memory_control_fail" for c in codes("feedback_no_memory")):
        return "no_memory_control_fail", "no_memory_control_fail", flags
    if all(c == "action_feedback_ok" for c in fb) and all(c == "scalar_ok" for c in codes("scalar_only")):
        flags["episodic_loop_complete"] = True
        return "action_feedback_pass", "action_feedback_pass", flags
    return "setup_precondition_fail", "setup_precondition_fail", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "canonical_cue_probe"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in ("_last_p1", "_last_key_rho"):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


