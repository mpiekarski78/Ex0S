def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    ids.extend(f"{arm}|w{wi}" for arm in list(p["arms"]) for wi in range(int(p["n_worlds"])))
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM049 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM049 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def require_feedback_api(ag: NeuralCortex) -> None:
    if not hasattr(ag, "set_action_feedback_enabled"):
        raise RuntimeError("action-feedback channel not implemented")
    if "action_feedback" in ACT_RECALL_MODES or "action_feedback_enabled" in ACT_RECALL_MODES:
        raise RuntimeError("action_feedback must not be an ACT_RECALL_MODE")
    if "action_feedback_enabled" in GenomeConfig().to_dict():
        raise RuntimeError("action_feedback must not be a GenomeConfig field")


def configure_arm(ag: NeuralCortex, arm: str) -> None:
    if arm not in ARMS:
        raise RuntimeError(arm)
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.genome.act_recall_mode = ACT_RECALL_OFF
    require_feedback_api(ag)
    ag.set_action_feedback_enabled(arm != "scalar_only")


def credit_tagged(
    ag: NeuralCortex,
    world: dict[str, Any],
    handle: str,
    cue: str,
    *,
    tag: str,
) -> dict[str, Any]:
    """Existing clamp path. Runner does not construct rho, k, or v."""
    body = list(MID_BODY)
    key_before = None if ag._last_key_rho is None else np.asarray(ag._last_key_rho, dtype=np.float64).copy()
    observe_cue(ag, world, tag=f"{tag}_sel", body=body, symbols=[cue])
    rho_cue = ag._from_t(ag.rho).copy()
    p1_cue = None if ag._last_p1 is None else np.asarray(ag._last_p1, dtype=np.float64).copy()
    key_cue = None if ag._last_key_rho is None else np.asarray(ag._last_key_rho, dtype=np.float64).copy()
    ag.clamp_action("ACT", handle)
    _state, body2 = physics(body, handle, world["latent"])
    observe_cue(ag, world, tag=f"{tag}_obs", body=list(body2), symbols=[cue])
    rho_fb = ag._from_t(ag.rho).copy()
    p1_fb = None if ag._last_p1 is None else np.asarray(ag._last_p1, dtype=np.float64).copy()
    key_after = None if ag._last_key_rho is None else np.asarray(ag._last_key_rho, dtype=np.float64).copy()
    ep = latest_episode(ag, handle)
    stored = None if ep is None else np.asarray(ep["p1"], dtype=np.float64).copy()
    stored_key = None if ep is None or ep.get("key_rho") is None else np.asarray(ep["key_rho"], dtype=np.float64).copy()
    motor = None if handle not in ag.motor_vocab else np.asarray(ag.motor_vocab[handle], dtype=np.float64).copy()
    return {
        "handle": handle,
        "cue": cue,
        "body2": [float(x) for x in body2],
        "rho_cue": rho_cue,
        "p1_cue": p1_cue,
        "key_cue": key_cue,
        "key_before_cue": key_before,
        "rho_feedback": rho_fb,
        "p1_feedback": p1_fb,
        "key_after": key_after,
        "projected": project_value(ag, rho_fb),
        "stored": stored,
        "stored_key": stored_key,
        "motor": motor,
    }


def _score_pack(ag: NeuralCortex, rec: dict[str, Any], handle: str, dev_p1: np.ndarray) -> dict[str, Any]:
    cred_vec = rec["p1_feedback"] if rec["p1_feedback"] is not None else rec["rho_feedback"]
    cred_sc = score_direct(ag, cred_vec)
    stored_sc = None if rec["stored"] is None else score_direct(ag, rec["stored"])
    ceil_sc = score_direct(ag, dev_p1)
    copied = bool(
        rec["stored"] is not None and rec["motor"] is not None and vec_hash(rec["stored"]) == vec_hash(rec["motor"])
    )
    return {
        "handle": handle,
        "cue": rec["cue"],
        "body2": rec["body2"],
        "rho_cue": {"hash": vec_hash(rec["rho_cue"]), "norm": vec_norm(rec["rho_cue"])},
        "rho_feedback": {"hash": vec_hash(rec["rho_feedback"]), "norm": vec_norm(rec["rho_feedback"])},
        "p1_cue": None if rec["p1_cue"] is None else {"hash": vec_hash(rec["p1_cue"]), "norm": vec_norm(rec["p1_cue"])},
        "p1_feedback": None
        if rec["p1_feedback"] is None
        else {"hash": vec_hash(rec["p1_feedback"]), "norm": vec_norm(rec["p1_feedback"])},
        "key_cue": None if rec["key_cue"] is None else {"hash": vec_hash(rec["key_cue"]), "norm": vec_norm(rec["key_cue"])},
        "stored_key": None
        if rec["stored_key"] is None
        else {"hash": vec_hash(rec["stored_key"]), "norm": vec_norm(rec["stored_key"])},
        "projected": {"hash": vec_hash(rec["projected"]), "norm": vec_norm(rec["projected"])},
        "stored": None if rec["stored"] is None else {"hash": vec_hash(rec["stored"]), "norm": vec_norm(rec["stored"])},
        "credit_score": cred_sc,
        "stored_score": stored_sc,
        "ceiling_score": ceil_sc,
        "credit_ok": bool(cred_sc["winner"] == handle),
        "stored_ok": bool(stored_sc is not None and stored_sc["winner"] == handle),
        "ceiling_ok": bool(ceil_sc["winner"] == handle),
        "copied_handle_into_s": copied,
        "key_from_cue": bool(
            rec["key_cue"] is not None
            and rec["stored_key"] is not None
            and vec_hash(rec["key_cue"]) == vec_hash(rec["stored_key"])
        ),
        "rel_feedback_to_cue": vec_rel(rec["rho_feedback"], rec["rho_cue"]),
        "rel_stored_to_feedback_p1": vec_rel(rec["stored"], rec["p1_feedback"]),
        "rel_stored_to_motor": vec_rel(rec["stored"], rec["motor"]),
        "_rho_fb": rec["rho_feedback"],
        "_p1_fb": rec["p1_feedback"],
        "_stored": rec["stored"],
    }


def eval_identity(common: dict[str, Any], *, arm: str, wi: int) -> dict[str, Any]:
    world = common["world"]
    cue = str(common["pairs"][0][0])
    handles = list(world["handles"])
    parent = load_common(common)
    freeze_plasticity(parent)
    configure_arm(parent, arm)
    reset_before_recall(parent)
    parent_h = w_act_hash(parent)
    kqv0 = parent.memproj_hashes()
    clones: list[dict[str, Any]] = []
    for handle in handles:
        ag = load_common(common)
        freeze_plasticity(ag)
        configure_arm(ag, arm)
        reset_before_recall(ag)
        rec = credit_tagged(ag, world, handle, cue, tag=CREDIT_TAG)
        if w_act_hash(ag) != parent_h:
            raise RuntimeError(f"W_act_query moved on identity {arm}|w{wi}")
        if ag.memproj_hashes() != kqv0:
            raise RuntimeError(f"K/Q/V moved on identity {arm}|w{wi}")
        clones.append(_score_pack(ag, rec, handle, common["dev_p1"][handle]))
    labels = [c["handle"] for c in clones]
    pair = pairwise([c["_rho_fb"] for c in clones], labels)
    for c in clones:
        for k in ("_rho_fb", "_p1_fb", "_stored"):
            c.pop(k, None)
    n_unique = len({c["rho_feedback"]["hash"] for c in clones})
    max_l2 = max((float(p["l2"] or 0.0) for p in pair), default=0.0)
    n_ok_credit = int(sum(1 for c in clones if c["credit_ok"]))
    n_ok_stored = int(sum(1 for c in clones if c["stored_ok"]))
    n_ok_ceil = int(sum(1 for c in clones if c["ceiling_ok"]))
    distinguishable = n_unique == len(handles) and max_l2 > float(EPISODE_MATCH_L2)
    if any(bool(c["copied_handle_into_s"]) for c in clones):
        raise RuntimeError("runner or organism copied handle/motor into S")
    return {
        "cue": cue,
        "n_unique_rho_feedback": int(n_unique),
        "max_pairwise_l2": float(max_l2),
        "distinguishable": bool(distinguishable),
        "n_ok_ceiling": n_ok_ceil,
        "n_ok_credit": n_ok_credit,
        "n_ok_stored": n_ok_stored,
        "copied_handle_into_s": False,
        "clones": clones,
        "pairwise_rho_feedback": pair,
    }


def eval_mapping(common: dict[str, Any], *, arm: str, wi: int) -> dict[str, Any]:
    world = common["world"]
    pairs = list(common["pairs"])
    ag = load_common(common)
    freeze_plasticity(ag)
    configure_arm(ag, arm)
    reset_before_recall(ag)
    parent_h = w_act_hash(ag)
    kqv0 = ag.memproj_hashes()
    writes: list[dict[str, Any]] = []
    for i, (cue, handle) in enumerate(pairs):
        rec = credit_tagged(ag, world, handle, cue, tag=f"af_map_{i}")
        writes.append(_score_pack(ag, rec, handle, common["dev_p1"][handle]))
        writes[-1]["_stored"] = rec["stored"]
        writes[-1]["_p1_fb"] = rec["p1_feedback"]
    if w_act_hash(ag) != parent_h:
        raise RuntimeError(f"W_act_query moved on mapping {arm}|w{wi}")
    if ag.memproj_hashes() != kqv0:
        raise RuntimeError(f"K/Q/V moved on mapping {arm}|w{wi}")
    if arm == "feedback_no_memory":
        ag._episodes = []
        ag.opaque.clear()
        reset_before_recall(ag)
    facts = []
    n_ok_stored = 0
    n_ok_reinst = 0
    n_ok_canonical = 0
    for wr, (cue, handle) in zip(writes, pairs):
        stored = wr.pop("_stored", None)
        p1_fb = wr.pop("_p1_fb", None)
        reinst = None if stored is None else score_direct(ag, stored)
        probe = clone_frozen(ag)
        if arm != "feedback_no_memory":
            probe.genome.act_recall_mode = ACT_RECALL_RAW_P1
        else:
            probe.genome.act_recall_mode = ACT_RECALL_OFF
        probe.set_memproj_arm(MEMPROJ_NONE)
        reset_before_recall(probe)
        observe_cue(probe, world, tag=f"af_can_{handle}", body=list(MID_BODY), symbols=[cue])
        scores, addr, meta = probe.event_memory_scores()
        winner = unique_winner(scores)
        can_ok = winner == handle
        st_ok = bool(wr["stored_ok"])
        ri_ok = bool(reinst is not None and reinst["winner"] == handle)
        if st_ok:
            n_ok_stored += 1
        if ri_ok:
            n_ok_reinst += 1
        if can_ok:
            n_ok_canonical += 1
        facts.append(
            {
                "cue": cue,
                "handle": handle,
                "stored_ok": st_ok,
                "reinstatement_ok": ri_ok,
                "canonical_ok": can_ok,
                "canonical_winner": winner,
                "addr_hash": vec_hash(addr),
                "telemetry": _brief_meta(meta),
                "reinstatement_score": reinst,
                "rel_addr_to_stored": vec_rel(addr, stored),
                "rel_addr_to_feedback_p1": vec_rel(addr, p1_fb),
                "credit_ok": wr["credit_ok"],
                "key_from_cue": wr["key_from_cue"],
            }
        )
    n_need = len(pairs)
    return {
        "n_facts": int(n_need),
        "n_ok_stored": int(n_ok_stored),
        "n_ok_reinstatement": int(n_ok_reinst),
        "n_ok_canonical": int(n_ok_canonical),
        "facts": facts,
        "w_act_query_frozen": True,
        "kqv_frozen": True,
    }


def classify_arm(arm: str, identity: dict[str, Any], mapping: dict[str, Any]) -> str:
    if arm == "scalar_only":
        collapsed = (
            int(identity["n_unique_rho_feedback"]) == 1
            and float(identity["max_pairwise_l2"]) <= float(EPISODE_MATCH_L2)
            and int(identity["n_ok_credit"]) == 1
        )
        return "scalar_ok" if collapsed else "scalar_control_fail"
    if arm == "feedback_no_memory":
        rho_ok = bool(identity["distinguishable"]) and int(identity["n_ok_credit"]) == 4
        mem_fail = int(mapping["n_ok_canonical"]) < int(mapping["n_facts"])
        if not rho_ok:
            return "feedback_rho_absent" if not identity["distinguishable"] else "feedback_not_decodable"
        return "no_memory_ok" if mem_fail else "no_memory_control_fail"
    # action_feedback
    if not identity["distinguishable"]:
        return "feedback_rho_absent"
    if int(identity["n_ok_credit"]) < 4:
        return "feedback_not_decodable"
    if int(identity["n_ok_stored"]) < 4 or int(mapping["n_ok_stored"]) < int(mapping["n_facts"]):
        return "stored_value_loss"
    if int(mapping["n_ok_reinstatement"]) < int(mapping["n_facts"]):
        return "reinstatement_fail"
    if int(mapping["n_ok_canonical"]) < int(mapping["n_facts"]):
        return "canonical_only_fail"
    return "action_feedback_ok"


def eval_arm_cell(common: dict[str, Any], *, arm: str, wi: int) -> dict[str, Any]:
    cell_id = f"{arm}|w{wi}"
    identity = eval_identity(common, arm=arm, wi=wi)
    mapping = eval_mapping(common, arm=arm, wi=wi)
    code = classify_arm(arm, identity, mapping)
    passed = code in ("scalar_ok", "action_feedback_ok", "no_memory_ok")
    out = {
        "kind": "arm",
        "id": cell_id,
        "arm": arm,
        "world": int(wi),
        "passed": bool(passed),
        "cell_code": code,
        "identity": identity,
        "mapping": mapping,
        "w_act_query_frozen": True,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
    }
    assert_finite_record(out, ctx=cell_id)
    return out


