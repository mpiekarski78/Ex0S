def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    ids.extend(f"split|{arm}|w{wi}" for arm in list(p["arms"]) for wi in range(int(p["n_worlds"])))
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
        "boundaries": list(p["boundaries"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM047 manifest drifted")
