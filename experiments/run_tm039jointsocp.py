def registry_seeds() -> list[int]:
    seeds = [int(s) for s in load_prereg()["registry_seeds"]]
    if len(seeds) != 4 or DEFAULT_SEED_REGISTRY in seeds:
        raise RuntimeError("bad registry seeds")
    return seeds


def neural_ready() -> bool:
    return hasattr(NeuralCortex, "set_act_socp_arm")


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for ri, _s in enumerate(p["registry_seeds"]):
        for order in list(p["orders"]):
            for arm in ARMS:
                ids.append(f"acquire|c8|{order}|reg{ri}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "registry_seeds": list(p["registry_seeds"]),
        "arms": list(ARMS),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM039 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def collect_socp_constraints(ag: NeuralCortex) -> list[dict[str, np.ndarray]]:
    rows: list[dict[str, np.ndarray]] = []
    rivals = sorted(str(h) for h in ag.motor_vocab)
    for slot, ep in enumerate(ag._episodes):
        if not ep.get("valid"):
            continue
        if float(ep["adv"]) <= ELIG_EPS:
            continue
        handle = str(ep["handle"])
        if handle not in ag.motor_vocab:
            continue
        x = ag._unit_or_zero(np.asarray(ep["p1"], dtype=np.float64))
        if float(np.max(np.abs(x))) <= ELIG_EPS:
            continue
        v_h = np.asarray(ag.motor_vocab[handle], dtype=np.float64).reshape(-1)
        for rival in rivals:
            if rival == handle:
                continue
            v_r = np.asarray(ag.motor_vocab[rival], dtype=np.float64).reshape(-1)
            d = v_h - v_r
            rows.append({"d": d, "x": x, "key": f"{int(slot)}|{handle}|{rival}"})
    return rows


def try_install_socp(ag: NeuralCortex) -> dict[str, Any]:
    if neural_ready() and str(getattr(ag, "_act_socp_arm", "") or "") in ("fallback_joint", "always_joint"):
        return ag._run_joint_socp_consolidation()
    w0 = ag._from_t(ag.W_act_query)
    w0_t = ag.W_act_query.detach().clone()
    cons = collect_socp_constraints(ag)
    solved = solve_min_change_socp(w0, cons, float(ACT_MARGIN_FLOOR), float(PROTO_EPS))
    rec = {k: v for k, v in solved.items() if k != "W"}
    rec["violations_before"] = int(ag._count_store_violations())
    rec["applied"] = False
    if solved.get("status") != "optimal" or solved.get("W") is None:
        rec["applied"] = False
        rec["violations_after"] = rec["violations_before"]
        rec["w_hash_after"] = weight_hash(w0)
        return rec
    ag.W_act_query = ag._to_t(np.asarray(solved["W"], dtype=np.float64))
    ag._clip_and_consolidate({"W_act_query"}, mix_slow=False)
    n_after = int(ag._count_store_violations())
    rec["violations_after"] = n_after
    rec["w_hash_after"] = weight_hash(ag._from_t(ag.W_act_query))
    rec["frobenius_delta_after_clip"] = float(np.linalg.norm(ag._from_t(ag.W_act_query) - w0))
    if n_after != 0:
        ag.W_act_query = w0_t
        rec["applied"] = False
        rec["reject_reason"] = "organism_violation_after_clip"
        rec["status"] = "reject"
        rec["violations_after"] = int(ag._count_store_violations())
        rec["w_hash_after"] = weight_hash(ag._from_t(ag.W_act_query))
        return rec
    rec["applied"] = True
    rec["reject_reason"] = None
    return rec


def apply_fallback(ag: NeuralCortex, *, new_ep: dict[str, Any], eta: float) -> dict[str, Any]:
    native = apply_native(ag, new_ep=new_ep, eta=eta)
    n_after_v37 = int(ag._count_store_violations())
    socp: dict[str, Any] | None = None
    if n_after_v37 > 0:
        socp = try_install_socp(ag)
    return {
        "v37": native,
        "violations_after_v37": n_after_v37,
        "socp_invoked": bool(n_after_v37 > 0),
        "socp": socp,
    }


def apply_always(ag: NeuralCortex) -> dict[str, Any]:
    socp = try_install_socp(ag)
    return {
        "v37": None,
        "violations_after_v37": None,
        "socp_invoked": True,
        "socp": socp,
    }


def classify_world(fixes: dict[str, bool]) -> str:
    if bool(fixes["v37"]):
        return "v37_already_converged"
    if bool(fixes["fallback_joint"]):
        return "fallback_sufficient"
    if bool(fixes["always_joint"]):
        return "always_required"
    return "solver_fail"


def _decision(world_routes: list[str]) -> tuple[str, str, dict[str, Any]]:
    diagnostic = [r for r in world_routes if r != "v37_already_converged"]
    flags = {
        "n_worlds": len(world_routes),
        "n_diagnostic": len(diagnostic),
        "n_v37_already": sum(1 for r in world_routes if r == "v37_already_converged"),
        "routes": list(world_routes),
        "diagnostic_routes": list(diagnostic),
        "candidate_v40_lock": False,
    }
    if not diagnostic:
        return "jointsocp_no_v37_fail", "jointsocp_no_v37_fail", flags
    uniq = set(diagnostic)
    if uniq == {"fallback_sufficient"}:
        code = "jointsocp_fallback_sufficient"
    elif uniq == {"always_required"}:
        code = "jointsocp_fallback_blocks"
    elif uniq == {"solver_fail"}:
        code = "jointsocp_solver_fail"
    else:
        code = "jointsocp_mixed_routes"
    # always_required in the per-world sense is "fallback failed, always passed".
    # If every diagnostic is always_required, v37 pre-step blocks SOCP.
    return code, code, flags


def _score(
    *,
    twin: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    taught: list[dict[str, Any]],
    protected: list[int],
    new_slot: int | None,
    tag: str,
) -> dict[str, Any]:
    rows = stored_rows(twin)
    broke, broke_slots = broke_protected(protected=protected, new_slot=new_slot, after_rows=rows)
    measured = clone_identity(twin)
    probe = clone_plastic(twin.checkpoint(), copy.deepcopy(twin.genome))
    live = live_probes(probe, world, pairs, taught, tag=tag)
    if not identities_match(measured, clone_identity(twin)):
        raise RuntimeError(f"measured arm mutated by probes {tag}")
    rec = {
        "new_slot": new_slot,
        "protected_slots": list(protected),
        "previously_correct_broke": bool(broke),
        "broke_slots": broke_slots,
        "n_store_violations": int(twin._count_store_violations()),
        "n_episodes": len(twin._episodes),
        "stored_rows": rows,
        "live_ranking_ok": bool(live["ranking_ok"]),
        "n_probe_correct": int(live["n_probe_correct"]),
        "min_normalized_geometric_margin": float(live["min_normalized_geometric_margin"]),
        "probes": live["probes"],
        "probes_on_another_clone": True,
        "measured_unchanged_after_probes": True,
        "w_hash": weight_hash(twin._from_t(twin.W_act_query)),
    }
    rec["fixed"] = arm_fixes(rec)
    return rec


def eval_world(
    *,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    seed_registry: int,
    reg: int,
    tmp: str,
) -> tuple[list[dict[str, Any]], str]:
    geo = geometry_parent(
        world=world,
        pairs=pairs,
        order=order,
        seed_registry=seed_registry,
        reg=reg,
        tmp=tmp,
    )
    ag0: NeuralCortex = geo["ag"]
    snap = ag0.checkpoint()
    genome = copy.deepcopy(ag0.genome)
    parent_id = clone_identity(ag0)
    eta = eta_act(ag0)
    cells: list[dict[str, Any]] = []
    fixes: dict[str, bool] = {}
    hashes: dict[str, str] = {}
    for arm in ARMS:
        twin = clone_plastic(snap, genome)
        if not identities_match(parent_id, clone_identity(twin)):
            raise RuntimeError(f"clone identity mismatch before {arm}")
        if neural_ready():
            if arm == "v37":
                twin.set_act_socp_arm("off")
            else:
                twin.set_act_socp_arm(arm)
        if arm == "v37":
            process = apply_native(twin, new_ep=geo["new_ep"], eta=eta)
        elif arm == "fallback_joint":
            process = apply_fallback(twin, new_ep=geo["new_ep"], eta=eta)
        elif arm == "always_joint":
            process = apply_always(twin)
        else:
            raise RuntimeError(arm)
        scored = _score(
            twin=twin,
            world=world,
            pairs=pairs,
            taught=geo["taught"],
            protected=list(geo["protected"]),
            new_slot=geo["new_slot"],
            tag=f"{arm}_{order}_reg{reg}",
        )
        rec = {
            "kind": "acquire",
            "arm": arm,
            "id": f"acquire|c8|{order}|reg{reg}|{arm}",
            "order": order,
            "reg": int(reg),
            "seed_registry": int(seed_registry),
            "n_cues": 8,
            "act_recall_mode": "early_raw_half_spacing",
            "taught": geo["taught"],
            "parent_store_zero": bool(geo["parent_store_zero"]),
            "write_n_violations": int(geo["write_n_violations"]),
            "parent_identity_sha": geo["identity_sha"],
            "clone_matched_parent": True,
            "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
            "not_an_exact_projector": True,
            "oracle_installed_in_organism": False,
            "candidate_v40_lock": False,
            "process": process,
            **scored,
        }
        rec["passed"] = bool(rec["fixed"])
        rec["behavioral_pass"] = bool(rec["passed"])
        assert_finite_record(rec, ctx=rec["id"])
        cells.append(rec)
        fixes[arm] = bool(rec["fixed"])
        hashes[arm] = str(rec["w_hash"])
    if not identities_match(parent_id, clone_identity(ag0)):
        raise RuntimeError(f"geometry parent mutated {order} reg{reg}")
    route = classify_world(fixes)
    hash_match = None
    if fixes.get("fallback_joint") and fixes.get("always_joint"):
        hash_match = hashes["fallback_joint"] == hashes["always_joint"]
    for rec in cells:
        rec["world_route"] = route
        rec["parent_unchanged"] = True
        rec["fallback_always_hash_match"] = hash_match
    return cells, route


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and sha_file(THIS) != frozen:
        raise RuntimeError("TM039 runner SHA drifted after freeze push")
    if sha_file(TM032_RUNNER) != p["tm032_runner_sha"]:
        raise RuntimeError("TM032 runner SHA drifted")
    if sha_file(TM036_RUNNER) != p["tm036_runner_sha"]:
        raise RuntimeError("TM036 runner SHA drifted")
    if sha_file(TM038_RUNNER) != p["tm038_runner_sha"]:
        raise RuntimeError("TM038 runner SHA drifted")
    if hashlib.sha256(TM032_DEV.read_bytes()).hexdigest() != p["tm032_dev_sha"]:
        raise RuntimeError("TM032 DEV SHA drifted")
    if hashlib.sha256(TM032_DEC.read_bytes()).hexdigest() != p["tm032_decision_sha"]:
        raise RuntimeError("TM032 decision SHA drifted")
    if hashlib.sha256(TM036_DEV.read_bytes()).hexdigest() != p["tm036_dev_sha"]:
        raise RuntimeError("TM036 DEV SHA drifted")
    if hashlib.sha256(TM036_DEC.read_bytes()).hexdigest() != p["tm036_decision_sha"]:
        raise RuntimeError("TM036 decision SHA drifted")
    if hashlib.sha256(TM038_DEV.read_bytes()).hexdigest() != p["tm038_dev_sha"]:
        raise RuntimeError("TM038 DEV SHA drifted")
    if hashlib.sha256(TM038_DEC.read_bytes()).hexdigest() != p["tm038_decision_sha"]:
        raise RuntimeError("TM038 decision SHA drifted")
    if int(EPISODE_REPLAY_EPOCHS) != int(p["hard_budget_passes"]):
        raise RuntimeError("hard budget must remain 16")
    if str(ACT_SCORE_QUERY) != "query":
        raise RuntimeError("scoring must remain query")
    ids = expected_cell_ids()
    wi = int(p.get("world_index") or 0)
    world = capacity_world(wi, DEV_DOMAIN, n_cues=8, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    cells: list[dict[str, Any]] = []
    world_routes: list[str] = []
    tmp = tempfile.TemporaryDirectory(prefix="js_dev_")
    try:
        for ri, seed in enumerate(registry_seeds()):
            for order in list(p["orders"]):
                recs, route = eval_world(
                    world=world,
                    pairs=pairs,
                    order=order,
                    seed_registry=int(seed),
                    reg=ri,
                    tmp=tmp.name,
                )
                cells.extend(recs)
                world_routes.append(str(route))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    if len(world_routes) != EXPECTED_N_WORLDS:
        raise RuntimeError("world count drifted")
    code, then, flags = _decision(world_routes)
    both = [c for c in cells if c["arm"] == "fallback_joint" and c.get("fallback_always_hash_match") is not None]
    flags["n_both_fixed"] = len(both)
    flags["n_both_fixed_hash_mismatch"] = sum(1 for c in both if c.get("fallback_always_hash_match") is False)
    clean, clean_status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_worlds": len(world_routes),
        "cells": cells,
        "world_routes": world_routes,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
        "not_an_exact_projector": True,
        "oracle_installed_in_organism": False,
        "candidate_v40_lock": False,
        "clean_tree": bool(clean),
        "clean_tree_status": clean_status,
    }


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, torch.Tensor):
        return o.detach().cpu().tolist()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.39.JOINTSOCP.DECISION",
        "product": "0.0.004",
        "manifest_sha": MANIFEST_SHA,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "hard_budget_passes": out.get("hard_budget_passes"),
        "not_an_exact_projector": True,
        "oracle_installed_in_organism": False,
        "candidate_v40_lock": False,
        "note": "TM039 joint SOCP decision. Product remains 0.0.004. No cortex.candidate.v40.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


def write_results_md(out: dict[str, Any]) -> None:
    flags = out["phase_flags"]
    lines = [
        "# TM.0.39.JOINTSOCP results",
        "",
        "Numerical joint min-change SOCP after TM038. Product **0.0.004**.",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        "Not an exact projector. No candidate v40 lock. Organism predicate is authoritative.",
        "",
        f"- worlds: {flags.get('n_worlds')} diagnostic {flags.get('n_diagnostic')} v37-already {flags.get('n_v37_already')}",
        f"- routes: {flags.get('routes')}",
        f"- diagnostic routes: {flags.get('diagnostic_routes')}",
        f"- both-fixed hash mismatch: {flags.get('n_both_fixed_hash_mismatch')}",
        "",
    ]
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def freeze_runner_sha() -> None:
    p = load_prereg()
    if p.get("frozen_runner_sha"):
        raise RuntimeError("already frozen")
    p["frozen_runner_sha"] = sha_file(THIS)
    PREREG.write_text(json.dumps(p, indent=2) + "\n", encoding="utf-8")


def smoke() -> dict[str, Any]:
    assert load_prereg()["manifest_sha"] == MANIFEST_SHA
    assert len(expected_cell_ids()) == EXPECTED_N_CELLS
    seed = registry_seeds()[0]
    world = capacity_world(0, DEV_DOMAIN, n_cues=2, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    with tempfile.TemporaryDirectory(prefix="js_smk_") as tmp:
        recs, route = eval_world(
            world=world,
            pairs=pairs,
            order="A_then_B",
            seed_registry=seed,
            reg=0,
            tmp=tmp,
        )
    return {
        "smoke_ok": True,
        "n_arms": len(recs),
        "arms": [c["arm"] for c in recs],
        "world_route": route,
        "clone_matched": all(bool(c["clone_matched_parent"]) for c in recs),
        "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
        "neural_ready": neural_ready(),
        "not_an_exact_projector": all(bool(c["not_an_exact_projector"]) for c in recs),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    ap.add_argument("--freeze-runner-sha", action="store_true")
    args = ap.parse_args()
    if args.freeze_runner_sha:
        freeze_runner_sha()
        print(json.dumps({"frozen_runner_sha": sha_file(THIS)}, indent=2))
        return
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "candidate_v40_lock": False,
                },
                indent=2,
            )
        )
        return
    ap.print_help()


if __name__ == "__main__":
    main()
