def aligned_stacks(
    prefix_rows: list[dict[str, Any]],
    later_rows: list[dict[str, Any]],
    handles: list[str],
    n: int,
) -> tuple[np.ndarray, np.ndarray]:
    p_by: dict[str, list[np.ndarray]] = defaultdict(list)
    l_by: dict[str, list[np.ndarray]] = defaultdict(list)
    for r in prefix_rows:
        p_by[str(r["handle"])].append(np.asarray(r["p1"], dtype=np.float64).reshape(-1))
    for r in later_rows:
        l_by[str(r["handle"])].append(np.asarray(r["p1"], dtype=np.float64).reshape(-1))
    a_rows: list[np.ndarray] = []
    b_rows: list[np.ndarray] = []
    for h in handles:
        k = min(len(p_by[h]), len(l_by[h]))
        if k < 1:
            raise RuntimeError("transport alignment missing an action role")
        for i in range(k):
            a_rows.append(unit_or_zero(p_by[h][i], n))
            b_rows.append(unit_or_zero(l_by[h][i], n))
    return np.stack(a_rows, axis=0), np.stack(b_rows, axis=0)


def fit_linear(A: np.ndarray, B: np.ndarray) -> np.ndarray:
    q, *_ = np.linalg.lstsq(A, B, rcond=None)
    return np.asarray(q, dtype=np.float64)


def fit_orthogonal(A: np.ndarray, B: np.ndarray) -> np.ndarray:
    m = A.T @ B
    u, _s, vt = np.linalg.svd(m, full_matrices=True)
    if np.linalg.det(u @ vt) < 0:
        u = u.copy()
        u[:, -1] *= -1
    return u @ vt


def map_later_to_prefix(x: np.ndarray, Q: np.ndarray, *, orthogonal: bool) -> np.ndarray:
    v = np.asarray(x, dtype=np.float64).reshape(-1)
    q = np.asarray(Q, dtype=np.float64)
    if orthogonal:
        y = q @ v
    else:
        y = np.linalg.pinv(q.T) @ v
    return unit_or_zero(y, int(v.size))


def map_prefix_to_later(x: np.ndarray, Q: np.ndarray, *, orthogonal: bool) -> np.ndarray:
    v = np.asarray(x, dtype=np.float64).reshape(-1)
    q = np.asarray(Q, dtype=np.float64)
    if orthogonal:
        y = q.T @ v
    else:
        y = q.T @ v
    return unit_or_zero(y, int(v.size))


