def expected_cell_ids() -> list[str]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"{arm}|n{n}|w{wi}" for arm in list(p["arms"]) for n in n_grid for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "n_grid": n_grid,
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM060 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM060 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS or len(setup) != N_SETUP_CELLS or len(scored) != N_SCORED_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def hvec(x: Any) -> str | None:
    if x is None:
        return None
    return vec_hash(np.asarray(x, dtype=np.float64))


def locate_by_receipt(ag: NeuralCortex, receipt: dict[str, Any]) -> Any | None:
    pid = receipt.get("provenance_id")
    if pid is None:
        return None
    want = str(pid)
    opaque = getattr(ag, "opaque", None)
    if opaque is None or not hasattr(opaque, "rows"):
        return None
    for row in opaque.rows():
        if str(row.provenance_id) == want:
            return row
    return None


class Receipts:
    def __init__(self) -> None:
        self.current_cue: str | None = None
        self.cue_by_pid: dict[str, str] = {}
        self.handle_by_pid: dict[str, str] = {}
        self.rows: list[dict[str, Any]] = []
        self.stores: list[list[dict[str, Any]]] = []
        self.attempts: list[dict[str, Any]] = []
        self.n_observer_provenance = 0

    def bind(self, ag: NeuralCortex) -> None:
        hist = ag._episode_write
        recs = self
        unused = unused_keyword()
        method = str(load_prereg()["write_method"])

        def _episode_write(p1: np.ndarray, handle: str, adv: float, *, event_key=None, key_rho=None) -> None:
            resting = bool(ag._resting)
            hist(p1, handle, adv, event_key=event_key, key_rho=key_rho)
            if resting:
                return
            if key_rho is None:
                recs.n_observer_provenance += 1
                return
            v = np.asarray(ag._unit_or_zero(np.asarray(p1, dtype=np.float64)), dtype=np.float64).copy()
            k = np.asarray(key_rho, dtype=np.float64).reshape(-1).copy()
            rec = getattr(ag, method)(k, v, handle=str(handle), provenance_id=unused)
            if not isinstance(rec, dict):
                recs.n_observer_provenance += 1
                return
            pid = rec.get("provenance_id")
            if pid is None or str(pid) == unused:
                recs.n_observer_provenance += 1
                return
            hit = locate_by_receipt(ag, rec)
            if hit is None:
                recs.n_observer_provenance += 1
                return
            recs.cue_by_pid[str(pid)] = str(recs.current_cue)
            recs.handle_by_pid[str(pid)] = str(handle)
            recs.attempts.append(
                {
                    "handle": str(handle),
                    "p1": v,
                    "cue": recs.current_cue,
                    "provenance_id": str(pid),
                    "receipt": {k2: rec.get(k2) for k2 in ("outcome", "provenance_id", "evicted_provenance_id")},
                }
            )
            recs.rows.append(
                {
                    "outcome": rec.get("outcome"),
                    "provenance_id": str(pid),
                    "evicted_provenance_id": rec.get("evicted_provenance_id"),
                    "handle": str(handle),
                    "cue": recs.current_cue,
                    "attempted_v_hash": hvec(v),
                    "resident_v_hash": hvec(hit.value),
                }
            )
            recs.stores.append(store_snapshot(ag, recs.cue_by_pid, recs.handle_by_pid))

        ag._episode_write = _episode_write  # type: ignore[method-assign]


def store_snapshot(
    ag: NeuralCortex,
    cue_by_pid: dict[str, str],
    handle_by_pid: dict[str, str],
) -> list[dict[str, Any]]:
    opaque = getattr(ag, "opaque", None)
    if opaque is None or not hasattr(opaque, "rows"):
        return []
    out: list[dict[str, Any]] = []
    for row in opaque.rows():
        pid = str(row.provenance_id)
        val = np.asarray(row.value, dtype=np.float64).copy()
        out.append(
            {
                "provenance_id": pid,
                "handle": str(handle_by_pid.get(pid) or ""),
                "p1": val,
                "p1_hash": hvec(val),
                "key_hash": hvec(row.key),
                "cue": cue_by_pid.get(pid),
            }
        )
    return out


def pairs_of(rows: list[dict[str, Any]]) -> list[tuple[str, np.ndarray]]:
    return [(str(r["handle"]), np.asarray(r["p1"], dtype=np.float64).copy()) for r in rows]


def opaque_live(
    *,
    tmp: str,
    tag: str,
    wi: int,
    seed: int,
    domain: str,
    n_repeats: int,
    cue_fn,
    tag_prefix: str,
    receipts: Receipts,
) -> dict[str, Any]:
    p46 = json.loads((REPO_ROOT / "docs" / "lineage_oneshot.prereg.lock").read_text(encoding="utf-8"))
    n_handles = int(p46["n_handles"])
    n_facts = int(p46["n_facts"])
    world = capacity_world(int(wi), str(domain), n_cues=int(n_facts), n_handles=int(n_handles))
    pairs = mapping_pairs(world, flip=False)
    handles = list(world["handles"])
    test_cues = [str(c) for c, _h in pairs]
    ag = _fresh(tmp, tag, world, seed_registry=int(seed))
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.set_action_feedback_enabled(True)
    getattr(ag, str(load_prereg()["flag_setter"]))(True)
    receipts.bind(ag)
    used: list[str] = []
    for rep in range(int(n_repeats)):
        for i, handle in enumerate(handles):
            cue = str(cue_fn(rep, i, handle))
            used.append(cue)
            if cue in test_cues:
                raise RuntimeError("trajectory cue collided with test facts")
            receipts.current_cue = cue
            ground_one(ag, world, handle, tag=f"{tag_prefix}_{rep}_{i}", symbols=[cue])
    if len(used) != len(set(used)):
        raise RuntimeError("online cues were not unique")
    ag.rest_epoch(int(p46["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    prep_eval(ag)
    last_p1: dict[str, np.ndarray] = {}
    for ep in ag._episodes:
        if not ep.get("valid"):
            continue
        last_p1[str(ep["handle"])] = np.asarray(ep["p1"], dtype=np.float64).copy()
    handle_hits = []
    all_ok = True
    for handle in handles:
        p1 = last_p1.get(handle)
        if p1 is None:
            all_ok = False
            handle_hits.append({"handle": handle, "ok": False, "winner": None, "reason": "missing_write"})
            continue
        sc = score_direct(ag, p1)
        ok = sc["winner"] == handle
        all_ok = all_ok and bool(ok)
        handle_hits.append({"handle": handle, "ok": bool(ok), "winner": sc["winner"], "p1_hash": vec_hash(p1)})
    reset_before_recall(ag)
    snap = ag.checkpoint()
    return {
        "snap": snap,
        "genome": copy.deepcopy(ag.genome),
        "world": world,
        "pairs": pairs,
        "handles": handles,
        "last_p1": last_p1,
        "handle_hits": handle_hits,
        "all_ok": bool(all_ok),
        "w_act_query_hash": w_act_hash(ag),
        "grounded": True,
        "n_repeats": int(n_repeats),
        "seed": int(seed),
        "opaque_enabled": bool(getattr(ag, "_opaque_store_enabled", False)),
    }


