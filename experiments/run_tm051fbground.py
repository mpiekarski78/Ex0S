def classify_arm(arm: str, wrap: dict[str, Any], mapping: dict[str, Any], ordinary: dict[str, Any] | None) -> str:
    n = int(wrap["n_need"])
    if arm == "reference_only":
        return "reference_ok" if int(wrap["n_ok_true"]) == 1 else "reference_control_changed"
    if arm == "shuffled_grounding":
        if int(wrap["n_ok_true"]) == n:
            return "shuffled_not_causal"
        if int(wrap["n_ok_perm"]) == n or int(wrap["n_ok_true"]) < n:
            return "shuffled_ok"
        return "shuffled_not_causal"
    if arm == "feedback_no_memory":
        if int(wrap["n_ok_true"]) < n:
            return "heldout_feedback_decode_fail"
        mem_fail = int(mapping["n_ok_canonical"]) < int(mapping["n_facts"])
        return "no_memory_ok" if mem_fail else "memory_not_necessary"
    if int(wrap["n_ok_true"]) < n:
        return "heldout_feedback_decode_fail"
    if ordinary is not None and int(ordinary["n_ok"]) < int(ordinary["n_need"]):
        return "shared_decoder_interference"
    if int(mapping["n_ok_stored"]) < int(mapping["n_facts"]):
        return "value_projection_fail"
    if int(mapping["n_ok_reinstatement"]) < int(mapping["n_facts"]):
        return "reinstatement_fail"
    if int(mapping["n_ok_canonical"]) < int(mapping["n_facts"]):
        return "canonical_fail"
    return "feedback_grounded_ok"


def eval_arm_cell(
    commons: dict[str, dict[str, Any]],
    *,
    arm: str,
    wi: int,
) -> dict[str, Any]:
    if arm == "feedback_no_memory":
        common = commons["feedback_grounded"]
        discard = True
    elif arm == "reference_only":
        common = commons["reference_only"]
        discard = False
    else:
        common = commons[arm]
        discard = False
    wrap = wrap_identity(common, tag=f"fg_hold_{arm}_w{wi}")
    mapping = fact_mapping(common, discard_memory=discard)
    ordinary = None
    if arm == "feedback_grounded":
        ordinary = ordinary_from_reference(common, commons["reference_only"])
    code = classify_arm(arm, wrap, mapping, ordinary)
    passed = code in ("reference_ok", "feedback_grounded_ok", "shuffled_ok", "no_memory_ok")
    out = {
        "kind": "scored",
        "id": f"{arm}|w{wi}",
        "arm": arm,
        "world": int(wi),
        "passed": bool(passed),
        "cell_code": code,
        "wrap": wrap,
        "mapping": mapping,
        "ordinary": ordinary,
        "w_act_query_frozen": True,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
    }
    assert_finite_record(out, ctx=out["id"])
    return out


