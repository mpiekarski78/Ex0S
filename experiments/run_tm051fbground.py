def expected_cell_ids() -> list[str]:
    p = load_prereg()
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"{arm}|w{wi}" for arm in list(p["arms"]) for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM051 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM051 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def permute_handle(handles: list[str], handle: str) -> str:
    i = list(handles).index(str(handle))
    return str(handles[(i + PERM_K) % len(handles)])


def require_credit_token_api() -> None:
    sig = inspect.signature(NeuralCortex.clamp_action)
    if "credit_token" not in sig.parameters:
        raise RuntimeError("clamp_action credit_token not implemented")
    param = sig.parameters["credit_token"]
    if param.kind is not inspect.Parameter.KEYWORD_ONLY:
        raise RuntimeError("credit_token must be keyword-only")
    if "credit_token" in GenomeConfig().to_dict():
        raise RuntimeError("credit_token must not be a GenomeConfig field")
    if "credit_token" in ACT_RECALL_MODES:
        raise RuntimeError("credit_token must not be an ACT_RECALL_MODE")


def clamp_exec(ag: NeuralCortex, handle: str, *, credit_token: str | None = None) -> dict[str, Any]:
    if credit_token is None:
        return ag.clamp_action("ACT", handle)
    return ag.clamp_action("ACT", handle, credit_token=credit_token)


def ground_one(
    ag: NeuralCortex,
    world: dict[str, Any],
    handle: str,
    *,
    tag: str,
    symbols: list[str],
    credit_token: str | None = None,
) -> dict[str, Any]:
    body = list(MID_BODY)
    observe_cue(ag, world, tag=f"{tag}_sel", body=body, symbols=list(symbols))
    clamped = clamp_exec(ag, handle, credit_token=credit_token)
    if not bool(clamped.get("ok")):
        raise RuntimeError(f"clamp failed: {clamped}")
    _state, body2 = physics(body, handle, world["latent"])
    out = observe_cue(ag, world, tag=f"{tag}_obs", body=list(body2), symbols=list(symbols))
    prep_eval(ag)
    return {"adv": float((out.get("metrics") or {}).get("adv") or 0.0), "body2": list(body2)}


def develop_protocol(*, wi: int, tmp: str, protocol: str) -> dict[str, Any]:
    if protocol not in PROTOCOLS:
        raise RuntimeError(protocol)
    p46 = json.loads(TM046_PREREG.read_text(encoding="utf-8"))
    seed = int(p46["seed_registry"])
    n_handles = int(p46["n_handles"])
    n_facts = int(p46["n_facts"])
    world = capacity_world(int(wi), str(p46["domains"]["DEV"]), n_cues=int(n_facts), n_handles=int(n_handles))
    pairs = mapping_pairs(world, flip=False)
    handles = list(world["handles"])
    dev_cues = [f"s_dev_{wi}_{i}" for i in range(n_handles)]
    hold_cue = f"s_hold_{wi}"
    test_cues = [str(c) for c, _h in pairs]
    if hold_cue in test_cues or hold_cue in dev_cues:
        raise RuntimeError("held-out cue collided")
    if set(dev_cues) & set(test_cues):
        raise RuntimeError("development cues collided with test facts")
    ag = _fresh(tmp, f"fg_{protocol}_w{wi}", world, seed_registry=seed)
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    grounded = protocol != "reference_only"
    ag.set_action_feedback_enabled(bool(grounded))
    for rep in range(int(p46["n_dev_repeats"])):
        for i, handle in enumerate(handles):
            credit = permute_handle(handles, handle) if protocol == "shuffled_grounding" else None
            ground_one(
                ag,
                world,
                handle,
                tag=f"fg_{protocol}_w{wi}_{rep}_{i}",
                symbols=[dev_cues[i]],
                credit_token=credit,
            )
    ag.rest_epoch(int(p46["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    prep_eval(ag)
    last_p1: dict[str, np.ndarray] = {}
    for ep in ag._episodes:
        if not ep.get("valid"):
            continue
        last_p1[str(ep["handle"])] = np.asarray(ep["p1"], dtype=np.float64).copy()
    handle_hits = []
    all_ok = True
    for handle in handles:
        p1 = last_p1.get(handle)
        if p1 is None:
            all_ok = False
            handle_hits.append({"handle": handle, "ok": False, "winner": None, "reason": "missing_episode"})
            continue
        sc = score_direct(ag, p1)
        ok = sc["winner"] == handle
        all_ok = all_ok and bool(ok)
        handle_hits.append({"handle": handle, "ok": bool(ok), "winner": sc["winner"], "p1_hash": vec_hash(p1)})
    n_ep = len(ag._episodes)
    ag._episodes = []
    ag.opaque.clear()
    reset_before_recall(ag)
    snap = ag.checkpoint()
    decoder = {
        "kind": "decoder" if protocol == "reference_only" else "protocol_decoder",
        "id": f"decoder|w{wi}" if protocol == "reference_only" else f"{protocol}_decoder|w{wi}",
        "arm": protocol,
        "world": int(wi),
        "passed": bool(all_ok) if protocol == "reference_only" else bool(all_ok),
        "n_ok": int(sum(1 for h in handle_hits if h["ok"])),
        "n_need": int(n_handles),
        "n_dev_episodes": int(n_ep),
        "handles": handle_hits,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "cell_code": "decoder_ok" if all_ok else "decoder_fail",
    }
    assert_finite_record(decoder, ctx=decoder["id"])
    return {
        "snap": snap,
        "genome": copy.deepcopy(ag.genome),
        "world": world,
        "pairs": pairs,
        "handles": handles,
        "dev_cues": dev_cues,
        "hold_cue": hold_cue,
        "protocol": protocol,
        "decoder": decoder,
        "w_act_query_hash": w_act_hash(ag),
        "dev_p1": last_p1,
    }


def wrap_identity(common: dict[str, Any], *, tag: str) -> dict[str, Any]:
    world = common["world"]
    cue = str(common["hold_cue"])
    handles = list(common["handles"])
    parent = load_common(common)
    freeze_plasticity(parent)
    parent.set_action_feedback_enabled(True)
    parent.set_memproj_arm(MEMPROJ_NONE)
    parent.genome.act_recall_mode = ACT_RECALL_OFF
    reset_before_recall(parent)
    parent_h = w_act_hash(parent)
    kqv0 = parent.memproj_hashes()
    clones = []
    for handle in handles:
        ag = load_common(common)
        freeze_plasticity(ag)
        ag.set_action_feedback_enabled(True)
        ag.set_memproj_arm(MEMPROJ_NONE)
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        reset_before_recall(ag)
        rec = credit_tagged(ag, world, handle, cue, tag=f"{tag}_{handle}")
        if w_act_hash(ag) != parent_h:
            raise RuntimeError("W_act_query moved on wrap identity")
        if ag.memproj_hashes() != kqv0:
            raise RuntimeError("K/Q/V moved on wrap identity")
        ceiling = common["dev_p1"].get(handle)
        if ceiling is None:
            ceiling = rec["p1_feedback"]
        clones.append(_score_pack(ag, rec, handle, ceiling))
    n_ok = int(sum(1 for c in clones if c["credit_ok"]))
    perm_ok = int(sum(1 for c in clones if c["credit_score"]["winner"] == permute_handle(handles, c["handle"])))
    return {
        "cue": cue,
        "n_ok_true": n_ok,
        "n_ok_perm": perm_ok,
        "n_need": len(handles),
        "winners": [c["credit_score"]["winner"] for c in clones],
        "handles": [c["handle"] for c in clones],
        "n_unique_p1": len({c["p1_feedback"]["hash"] for c in clones if c.get("p1_feedback")}),
        "clones": [
            {
                "handle": c["handle"],
                "winner": c["credit_score"]["winner"],
                "credit_ok": c["credit_ok"],
                "p1_hash": None if c.get("p1_feedback") is None else c["p1_feedback"]["hash"],
            }
            for c in clones
        ],
    }


def fact_mapping(common: dict[str, Any], *, discard_memory: bool) -> dict[str, Any]:
    world = common["world"]
    pairs = list(common["pairs"])
    ag = load_common(common)
    freeze_plasticity(ag)
    ag.set_action_feedback_enabled(True)
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.genome.act_recall_mode = ACT_RECALL_OFF
    reset_before_recall(ag)
    parent_h = w_act_hash(ag)
    kqv0 = ag.memproj_hashes()
    writes = []
    for i, (cue, handle) in enumerate(pairs):
        rec = credit_tagged(ag, world, handle, cue, tag=f"fg_map_{i}")
        ceiling = common["dev_p1"].get(handle)
        if ceiling is None:
            ceiling = rec["p1_feedback"]
        writes.append(_score_pack(ag, rec, handle, ceiling))
        writes[-1]["_stored"] = rec["stored"]
        writes[-1]["_p1_fb"] = rec["p1_feedback"]
    if w_act_hash(ag) != parent_h:
        raise RuntimeError("W_act_query moved on facts")
    if ag.memproj_hashes() != kqv0:
        raise RuntimeError("K/Q/V moved on facts")
    if discard_memory:
        ag._episodes = []
        ag.opaque.clear()
        reset_before_recall(ag)
    n_ok_stored = 0
    n_ok_reinst = 0
    n_ok_canonical = 0
    n_ok_credit = 0
    facts = []
    for wr, (cue, handle) in zip(writes, pairs):
        stored = wr.pop("_stored", None)
        p1_fb = wr.pop("_p1_fb", None)
        reinst = None if stored is None else score_direct(ag, stored)
        probe = clone_frozen(ag)
        if discard_memory:
            probe.genome.act_recall_mode = ACT_RECALL_OFF
        else:
            probe.genome.act_recall_mode = ACT_RECALL_RAW_P1
        probe.set_memproj_arm(MEMPROJ_NONE)
        reset_before_recall(probe)
        observe_cue(probe, world, tag=f"fg_can_{handle}", body=list(MID_BODY), symbols=[cue])
        scores, addr, meta = probe.event_memory_scores()
        winner = unique_winner(scores)
        can_ok = winner == handle
        st_ok = bool(wr["stored_ok"])
        ri_ok = bool(reinst is not None and reinst["winner"] == handle)
        cr_ok = bool(wr["credit_ok"])
        if st_ok:
            n_ok_stored += 1
        if ri_ok:
            n_ok_reinst += 1
        if can_ok:
            n_ok_canonical += 1
        if cr_ok:
            n_ok_credit += 1
        facts.append(
            {
                "cue": cue,
                "handle": handle,
                "stored_ok": st_ok,
                "reinstatement_ok": ri_ok,
                "canonical_ok": can_ok,
                "credit_ok": cr_ok,
                "canonical_winner": winner,
                "telemetry": _brief_meta(meta),
                "rel_addr_to_stored": vec_rel(addr, stored),
                "rel_addr_to_feedback_p1": vec_rel(addr, p1_fb),
            }
        )
    n_need = len(pairs)
    return {
        "n_facts": int(n_need),
        "n_ok_credit": int(n_ok_credit),
        "n_ok_stored": int(n_ok_stored),
        "n_ok_reinstatement": int(n_ok_reinst),
        "n_ok_canonical": int(n_ok_canonical),
        "facts": facts,
        "discard_memory": bool(discard_memory),
    }


def ordinary_from_reference(grounded: dict[str, Any], reference: dict[str, Any]) -> dict[str, Any]:
    ag = load_common(grounded)
    freeze_plasticity(ag)
    ag.set_action_feedback_enabled(False)
    reset_before_recall(ag)
    hits = []
    n_ok = 0
    for handle, p1 in reference["dev_p1"].items():
        sc = score_direct(ag, p1)
        ok = sc["winner"] == handle
