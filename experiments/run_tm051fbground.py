def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "earned_kqv": False,
        "earned_learned_addressing": False,
        "new_decoder": False,
        "episodic_loop_complete": False,
        "separate_candidate_review_open": False,
        "setup_excluded_from_behavioral_first_match": True,
    }
    if any(f"decoder|w{wi}" not in by or not bool(by[f"decoder|w{wi}"].get("passed")) for wi in (0, 1)):
        return "setup_precondition_fail", "setup_precondition_fail", flags

    def codes(arm: str) -> list[str]:
        return [str(by[f"{arm}|w{wi}"]["cell_code"]) for wi in (0, 1)]

    if any(c == "reference_control_changed" for c in codes("reference_only")):
        return "reference_control_changed", "reference_control_changed", flags
    g = codes("feedback_grounded")
    for step in ("heldout_feedback_decode_fail", "shared_decoder_interference"):
        if any(c == step for c in g):
            return step, step, flags
    if any(c == "shuffled_not_causal" for c in codes("shuffled_grounding")):
        return "shuffled_not_causal", "shuffled_not_causal", flags
    for step in ("value_projection_fail", "reinstatement_fail", "canonical_fail"):
        if any(c == step for c in g):
            return step, step, flags
    if any(c == "memory_not_necessary" for c in codes("feedback_no_memory")):
        return "memory_not_necessary", "memory_not_necessary", flags
    if (
        all(c == "feedback_grounded_ok" for c in g)
        and all(c == "reference_ok" for c in codes("reference_only"))
        and all(c == "shuffled_ok" for c in codes("shuffled_grounding"))
        and all(c == "no_memory_ok" for c in codes("feedback_no_memory"))
    ):
        flags["episodic_loop_complete"] = True
        return "feedback_grounding_pass", "feedback_grounding_pass", flags
    return "setup_precondition_fail", "setup_precondition_fail", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in ("_last_p1", "_last_key_rho", "W_k", "W_q", "W_v"):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM051 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if sha_file(TM050_RUNNER) != p["tm050_runner_sha"]:
        raise RuntimeError("TM050 runner must stay frozen")
    if hashlib.sha256(TM050_DEV.read_bytes()).hexdigest() != p["tm050_dev_sha"]:
        raise RuntimeError("TM050 DEV lock must stay frozen")
    if hashlib.sha256(TM050_DEC.read_bytes()).hexdigest() != p["tm050_decision_sha"]:
        raise RuntimeError("TM050 decision lock must stay frozen")
    if hashlib.sha256(TM050_ADD.read_bytes()).hexdigest() != p["tm050_addendum_sha"]:
        raise RuntimeError("TM050 addendum must stay frozen")
    if sha_file(TM049_RUNNER) != p["tm049_runner_sha"]:
        raise RuntimeError("TM049 runner must stay frozen")
    if hashlib.sha256(TM049_DEC.read_bytes()).hexdigest() != p["tm049_decision_sha"]:
        raise RuntimeError("TM049 decision lock must stay frozen")
    if sha_file(TM046_RUNNER) != p["tm046_runner_sha"]:
        raise RuntimeError("TM046 runner must stay frozen")
    if sha_file(TM047_RUNNER) != p["tm047_runner_sha"]:
        raise RuntimeError("TM047 runner must stay frozen")
    if hashlib.sha256(TM048_RUNNER.read_bytes()).hexdigest() != p["tm048_runner_sha"]:
        raise RuntimeError("TM048 runner must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("kqv_edit_authorized")) or bool(p.get("decoder_edit_authorized")):
        raise RuntimeError("TM051 must not tune K/Q/V or train a new decoder")
    if "action_feedback_enabled" in GenomeConfig().to_dict():
        raise RuntimeError("action_feedback must not be a GenomeConfig field")
    if "action_feedback" in ACT_RECALL_MODES:
        raise RuntimeError("action_feedback must not be an ACT_RECALL_MODE")
    if int(p["seed_registry"]) == int(p["reconstruction_seed_registry"]):
        raise RuntimeError("lab seed must not equal reconstruction seed")
    p46 = json.loads(TM046_PREREG.read_text(encoding="utf-8"))
    if int(p46["seed_registry"]) != int(p["reconstruction_seed_registry"]):
        raise RuntimeError("reconstruction seed must remain TM046")
    if str(p46["domains"]["DEV"]) != str(p["reconstruction_domain"]):
        raise RuntimeError("reconstruction domain must remain TM046")
    require_credit_token_api()
    add = json.loads(TM050_ADD.read_text(encoding="utf-8"))
    if add["historical_decision_code"] != "states_separate_never_decode":
        raise RuntimeError("TM050 first-match must stay frozen")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="fg_dev_")
    try:
        matched: dict[int, dict[str, dict[str, Any]]] = {}
        for wi in range(int(p["n_worlds"])):
            matched[int(wi)] = {
                proto: develop_protocol(wi=int(wi), tmp=tmp.name, protocol=str(proto)) for proto in PROTOCOLS
            }
            dec = dict(matched[int(wi)]["reference_only"]["decoder"])
            dec["kind"] = "setup"
            dec["excluded_from_behavioral_first_match"] = True
            cells.append(dec)
        for arm in list(p["arms"]):
            for wi in range(int(p["n_worlds"])):
                cells.append(eval_arm_cell(matched[int(wi)], arm=str(arm), wi=int(wi)))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    flags["kqv_edited"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "solver_edited": False,
        "tm050_runner_untouched": True,
        "tm049_runner_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


