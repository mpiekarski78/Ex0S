def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def _margin() -> dict[str, Any]:
    return load_prereg()["margin"]


def _probe_map(ag: Any, world: dict[str, Any], pairs: list[tuple[str, str]], *, tag: str) -> dict[str, Any]:
    m = _margin()
    return canonical_probe_map(
        ag,
        world,
        pairs,
        tag=tag,
        domain=str(world["domain"]),
        geometric_min=float(m["geometric_min"]),
        sigma=float(m["rho_perturb_sigma"]),
        perturb_n=int(m["perturb_n"]),
        perturb_need=int(m["perturb_stable_min"]),
    )


def _identity(probed: dict[str, Any]) -> dict[str, Any]:
    rows = []
    for r in list(probed.get("probes") or []):
        rows.append(
            {
                "cue": r.get("cue"),
                "live_p1_hash": r.get("live_p1_hash"),
                "scoring_address_hash": r.get("scoring_address_hash"),
                "retrieval_path": r.get("retrieval_path"),
                "retrieved_slot": r.get("retrieved_slot"),
            }
        )
    return {"probe_identity": rows, "behavioral_scorer": "actuator_decision_scores"}


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for wi in range(int(p["n_worlds"])):
        for order in list(p["orders"]):
            for tmpl in KIND_TEMPLATES:
                for arm in ARMS:
                    ids.append(tmpl.format(order=order, wi=wi, arm=arm))
    for wi in range(int(p["n_worlds"])):
        for arm in ARMS:
            ids.append(f"contradict|w{wi}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(ARMS),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM040 R2 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def eval_acquire_stable(
    *,
    kind: str,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    arm: str,
    tag: str,
    cell_id: str,
    seed_registry: int,
    rest: bool,
    tmp: str,
    wi: int,
) -> dict[str, Any]:
    p = load_prereg()
    seq = _seq(pairs, order)
    ag = _fresh(tmp, tag, world, seed_registry=seed_registry)
    set_arm(ag, arm)
    slog = bind_socp_logger(ag)
    taught, _b = teach_pairs(ag, world, seq, tag=tag)
    rest_out = ag.rest_epoch(int(p["n_rest_ticks"])) if rest else None
    probed = _probe_map(ag, world, pairs, tag=f"{tag}_q")
    n_cues = int(world["capacity"]["n_cues"])
    n_viol = int(ag._count_store_violations())
    ranking_ok = bool(probed["ranking_ok"]) and int(probed["n_probe_correct"]) == n_cues
    geometric_ok = bool(probed["geometric_ok"])
    pert_ok = bool(probed["perturbation_ok"])
    if kind == "acquire":
        passed = _semantic_pass(ranking_ok=ranking_ok, n_ok=int(probed["n_probe_correct"]), n_need=n_cues, n_viol=n_viol)
    else:
        passed = bool(ranking_ok and geometric_ok and pert_ok and n_viol == 0)
    out = {
        **_base_cell(kind, cell_id, arm, order, wi),
        "n_cues": n_cues,
        "n_handles": int(world["capacity"]["n_handles"]),
        "taught": taught,
        "rest": bool(rest),
        "n_store_violations": n_viol,
        "passed": passed,
        "behavioral_pass": passed,
        "w_hash": weight_hash(ag._from_t(ag.W_act_query)),
        **socp_summary(slog),
        **probed,
        **_identity(probed),
    }
    if rest_out is not None:
        out["n_rest_replay"] = int(rest_out.get("n_replay") or 0)
    assert_finite_record(out, ctx=cell_id)
    return out


