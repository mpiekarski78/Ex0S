def interference_matrix(ag: NeuralCortex, *, eta: float) -> dict[str, Any]:
    slots = [int(i) for i, _ep in valid_episodes(ag)]
    snap = ag.checkpoint()
    genome = copy.deepcopy(ag.genome)
    base_m = all_margins(ag)
    matrix: list[list[float]] = []
    targeted: list[dict[str, Any]] = []
    for i, ep in valid_episodes(ag):
        twin = clone_plastic(snap, genome)
        before = all_margins(twin)
        applied = twin._apply_act_query_update(
            np.asarray(ep["p1"], dtype=np.float64),
            str(ep["handle"]),
            float(ep["adv"]),
            eta,
            mix_slow=False,
        )
        after = all_margins(twin)
        row = [float(after.get(j, 0.0) - before.get(j, 0.0)) for j in slots]
        matrix.append(row)
        targeted.append(
            {
                "slot": int(i),
                "handle": str(ep["handle"]),
                "applied": bool(applied),
                "store_violation_before": bool(
                    ag._episode_rehearsal_violation(
                        np.asarray(ep["p1"], dtype=np.float64),
                        str(ep["handle"]),
                        float(ep["adv"]),
                    )
                ),
                "self_delta": float(after.get(int(i), 0.0) - before.get(int(i), 0.0)),
            }
        )
    off = [matrix[a][b] for a, si in enumerate(slots) for b, sj in enumerate(slots) if si != sj]
    return {
        "slots": slots,
        "base_margins": {str(k): float(v) for k, v in base_m.items()},
        "I": matrix,
        "targeted": targeted,
        "min_offdiag": float(min(off) if off else 0.0),
        "max_offdiag": float(max(off) if off else 0.0),
        "n_negative_offdiag": int(sum(1 for x in off if x < 0.0)),
    }


