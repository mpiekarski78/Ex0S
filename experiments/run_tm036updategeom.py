def candidate_delta(
    ag: NeuralCortex,
    p1: np.ndarray,
    handle: str,
    adv: float,
    eta_a: float,
) -> torch.Tensor | None:
    if handle not in ag.motor_vocab or abs(float(adv)) <= ELIG_EPS:
        return None
    rho = ag._unit_or_zero(p1)
    if float(np.max(np.abs(rho))) <= ELIG_EPS:
        return None
    m_h = np.asarray(ag.motor_vocab[handle], dtype=np.float64).reshape(-1)
    if float(adv) > 0.0:
        m_r = ag._rival_mean_vector(rho, handle)
        delta_m = m_h - m_r
    else:
        delta_m = m_h
    return float(eta_a) * float(adv) * torch.outer(ag._to_t(delta_m), ag._to_t(rho))


def apply_delta(ag: NeuralCortex, delta: torch.Tensor, *, mix_slow: bool) -> None:
    ag.W_act_query = ag.W_act_query + delta
    ag._clip_and_consolidate({"W_act_query"}, mix_slow=mix_slow)


