def smoke() -> dict[str, Any]:
    ids = expected_cell_ids()
    leak = refuse_runner_leaks(THIS)
    steps = {}
    code_setup, _, _ = _decision(synthetic_grid(decoder_ok=False))
    steps["setup"] = code_setup
    for step in BEHAVIORAL_LADDER:
        c, _, _ = _decision(synthetic_grid(code=step))
        steps[step] = c
    return {
        "smoke_ok": True,
        "n_cells": len(ids),
        "retrieve_leak": leak,
        "ladder": steps,
        "candidate_exists": CANDIDATE.exists(),
        "floor": float(EPISODE_MATCH_L2),
        "slots": int(EPISODE_SLOTS),
        "behavioral_ladder": list(BEHAVIORAL_LADDER),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "install_W_star": False,
                    "socp_scored": False,
                    "canonical_state_generator": "write_time_last_p1",
                },
                indent=2,
                default=_json_default,
            )
        )
        return
    raise SystemExit("use --smoke or --dev")


if __name__ == "__main__":
    main()
