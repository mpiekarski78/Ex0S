def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "install_W_star": False,
        "socp_scored": False,
        "episode_match_l2_retuned": False,
        "canonical_law_reconsidered": False,
        "setup_excluded_from_behavioral_first_match": True,
        "target_is_write_provenance": True,
        "drift_curve_earned": False,
    }
    for wi in (0, 1):
        dec = by.get(f"decoder|w{wi}")
        if dec is None or not bool(dec.get("passed")):
            return "setup_precondition_fail", "setup_precondition_fail", flags
    order = list(BEHAVIORAL_LADDER)
    codes = [str(by[f"provenance|w{wi}"]["cell_code"]) for wi in (0, 1)]
    for step in order:
        if any(c == step for c in codes):
            if step == "tm052_measured_wrong_record" and all(c == step for c in codes):
                return step, step, flags
            if step != "tm052_measured_wrong_record":
                return step, step, flags
    if all(c == "tm052_measured_wrong_record" for c in codes):
        return "tm052_measured_wrong_record", "tm052_measured_wrong_record", flags
    return codes[0], codes[0], flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "_run_joint_socp_consolidation", "solve_min_change_socp", "credit_tagged", "latest_episode"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in (
                    "_last_p1",
                    "_last_key_rho",
                    "W_k",
                    "W_q",
                    "W_v",
                    "W_act_query",
                    "_episodes",
                ):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM056 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py must stay frozen")
    if sha_file(TM055_RUNNER) != p["tm055_runner_sha"]:
        raise RuntimeError("TM055 runner must stay frozen")
    if hashlib.sha256(TM055_DEV.read_bytes()).hexdigest() != p["tm055_dev_sha"]:
        raise RuntimeError("TM055 DEV lock must stay frozen")
    if hashlib.sha256(TM055_DEC.read_bytes()).hexdigest() != p["tm055_decision_sha"]:
        raise RuntimeError("TM055 decision lock must stay frozen")
    if hashlib.sha256(TM055_PREREG.read_bytes()).hexdigest() != p["tm055_prereg_sha"]:
        raise RuntimeError("TM055 prereg must stay frozen")
    if hashlib.sha256(TM055_ADD.read_bytes()).hexdigest() != p["tm055_addendum_sha"]:
        raise RuntimeError("TM055 addendum must stay frozen")
    if hashlib.sha256(LAW.read_bytes()).hexdigest() != p["write_time_law_sha"]:
        raise RuntimeError("write-time law must stay frozen")
    if sha_file(TM052_RUNNER) != p["tm052_runner_sha"]:
        raise RuntimeError("TM052 runner must stay frozen")
    if hashlib.sha256(TM052_DEV.read_bytes()).hexdigest() != p["tm052_dev_sha"]:
        raise RuntimeError("TM052 DEV lock must stay frozen")
    if sha_file(TM051_RUNNER) != p["tm051_runner_sha"]:
        raise RuntimeError("TM051 runner must stay frozen")
    if sha_file(TM046_RUNNER) != p["tm046_runner_sha"]:
        raise RuntimeError("TM046 runner must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if int(p["n_dev_repeats"]) != 4:
        raise RuntimeError("n_dev_repeats must stay 4")
    if float(EPISODE_MATCH_L2) != 0.05:
        raise RuntimeError("do not retune EPISODE_MATCH_L2")
    add = json.loads(TM055_ADD.read_text(encoding="utf-8"))
    if add["historical_decision_code"] != "setup_precondition_fail":
        raise RuntimeError("TM055 first-match must stay frozen")
    if add["canonical_law_reconsidered"] is not False:
        raise RuntimeError("canonical law must not be reconsidered")
    law = json.loads(LAW.read_text(encoding="utf-8"))
    if law["canonical_state_generator"] != "write_time_last_p1":
        raise RuntimeError("write-time law drifted")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="ep_dev_")
    try:
        bundles = [collect_world(wi=int(wi), tmp=tmp.name) for wi in range(int(p["n_worlds"]))]
        for bundle in bundles:
            cells.append(bundle["decoder"])
        for bundle in bundles:
            cells.append(bundle["provenance"])
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["install_W_star"] = False
    flags["socp_scored"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "install_W_star": False,
        "socp_scored": False,
        "episode_match_l2_retuned": False,
        "canonical_law_reconsidered": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "tm055_runner_untouched": True,
        "neural_untouched": True,
        "canonical_state_generator": "write_time_last_p1",
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


