    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.set_action_feedback_enabled(True)
    journal = Journal()
    journal.bind(ag)
    orig_obs = ag.observe
    orig_replay = ag._replay_episodes
    orig_reset = ag.reset_rho
    orig_grow = ag._maybe_grow_prune

    def observe(payload: dict[str, Any]) -> dict[str, Any]:
        n0 = journal._seq
        out = orig_obs(payload)
        if not ag._resting:
            for w in journal.writes[n0:]:
                if w.get("cause") != "skipped":
                    w["after_ground_one"] = view_write(ag, w)
        else:
            journal.rest_store.append({"stage": "rest_tick", "token": payload.get("interaction_token"), "n_episodes": len(ag._episodes), "fingerprint": [record_hash(ep) for ep in ag._episodes]})
        return out

    def replay() -> dict[str, Any]:
        rec = orig_replay()
        journal.rest_store.append({"stage": "rest_replay", "n_replay": rec.get("n_replay"), "n_episodes": len(ag._episodes), "fingerprint": [record_hash(ep) for ep in ag._episodes]})
        return rec

