    after_ground = {h: dict(last_writes[h].get("after_ground_one") or {}) for h in last_writes}
    ag.rest_epoch(int(p46["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    after_rest = {h: view_write(ag, last_writes[h]) for h in last_writes}
    prep_eval(ag)
    after_prep = {h: view_write(ag, last_writes[h]) for h in last_writes}
    scan = tm051_handle_scan(ag, handles)
    live = live_p1(ag)
    pins = list(p["pinned_train_hashes"][f"w{wi}"])
    w0_pin = str(p["pinned_w0_hash"][f"w{wi}"])
    w0h = w_act_hash(ag)
    reset_before_recall(ag)
    w0_after_reset = w_act_hash(ag)
    decoder_ok = w0h == w0_pin or w0_after_reset == w0_pin
    w0_used = w0h if w0h == w0_pin else w0_after_reset
    code = classify_world(
        pins=pins,
        handles=handles,
        scan=scan,
        live=live,
        last_writes=last_writes,
        after_rest=after_rest,
        after_prep=after_prep,
    )
    if not decoder_ok:
        code = "setup_precondition_fail"
    causes = {}
    for h in handles:
        w = last_writes.get(h)
        causes[h] = None if w is None else w.get("cause")
    n_ground = sum(1 for w in journal.writes if (not w.get("resting")) and w.get("cause") != "skipped")
    n_rest_w = sum(1 for w in journal.writes if w.get("resting") and w.get("cause") != "skipped")
