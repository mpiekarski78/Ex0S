def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for wi in range(int(p["n_worlds"])):
        for arm in list(p["arms"]):
            ids.append(f"associate|{arm}|w{wi}")
        ids.append(f"revision|learned_projection|w{wi}")
        ids.append(f"revision|birth_projection|w{wi}")
    ids.extend(
        [
            "donor|A_to_host|w0",
            "donor|B_to_host|w0",
            "wipe|learned_projection|w0",
            "checkpoint|learned_projection|w0",
            "birth_restore|learned_projection|w0",
        ]
    )
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    frozen_manifest = str(p.get("manifest_sha") or "")
    if MANIFEST_SHA != "PLACEHOLDER_MANIFEST" and got != MANIFEST_SHA:
        raise RuntimeError("TM044 manifest drifted")
    if frozen_manifest not in ("PLACEHOLDER_MANIFEST", "", MANIFEST_SHA, got) and got != frozen_manifest:
        raise RuntimeError("TM044 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def clone_memproj(ag: NeuralCortex) -> NeuralCortex:
    twin = NeuralCortex(None, genome=copy.deepcopy(ag.genome), device="cpu")
    twin.load_checkpoint(ag.checkpoint())
    return twin


def _fresh(tmp: str, tag: str, world: dict[str, Any], *, seed_registry: int) -> NeuralCortex:
    ag = make_cortex(Path(tmp) / tag, genome=genome_for_registry(seed_registry), device="cpu")
    ag.genome.episodic_act_recall = False
    ag.genome.act_score_mode = ACT_SCORE_QUERY
    ag.bind_actuators(list(world["handles"]))
    ag.set_act_socp_arm("off")
    return ag


def _configure(ag: NeuralCortex, arm: str) -> None:
    if arm == "symbolic_oracle":
        ag.genome.act_recall_mode = ACT_RECALL_RAW_P1
        ag.set_memproj_arm(MEMPROJ_OFF)
    elif arm == "learned_projection":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_LEARNED)
    elif arm == "birth_projection":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_BIRTH)
    elif arm == "no_persistent_memory":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_NONE)
    else:
        raise RuntimeError(arm)


def _seq(pairs: list[tuple[str, str]], order: str) -> list[tuple[str, str]]:
    return list(reversed(pairs)) if order == "B_then_A" else list(pairs)


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    x = np.asarray(a, dtype=np.float64).reshape(-1)
    y = np.asarray(b, dtype=np.float64).reshape(-1)
    if x.shape != y.shape:
        return 0.0
    xn = float(np.linalg.norm(x))
    yn = float(np.linalg.norm(y))
    if xn <= 1e-12 or yn <= 1e-12:
        return 0.0
    return float(np.dot(x, y) / (xn * yn))


def ownership_fail_reasons(ag: NeuralCortex) -> list[str]:
    reasons: list[str] = []
    for row in ag.opaque_snapshot():
        extra = sorted(set(row.keys()) - ALLOWED_ROW_KEYS)
        if extra:
            reasons.append("schema:" + ",".join(extra))
        if any(k in row for k in ("handle", "cue", "relation", "kappa", "expected", "task")):
            reasons.append("semantic_field")
        val = np.asarray(row.get("value"), dtype=np.float64).reshape(-1)
        for handle, vec in ag.motor_vocab.items():
            if _cosine(val, vec) >= HANDLE_COSINE_FAIL:
                reasons.append(f"value_disguises_handle:{handle}")
    if "memproj_arm" in GenomeConfig().to_dict():
        reasons.append("memproj_in_genomeconfig")
    return reasons


def organism_probe(ag: NeuralCortex, world: dict[str, Any], cue: str, *, tag: str) -> dict[str, Any]:
    probe = clone_frozen(ag)
    observe_cue(probe, world, tag=tag, body=list(MID_BODY), symbols=[cue])
    scores, addr, meta = probe.event_memory_scores()
    winner = unique_winner(scores)
    return {
        "winner": winner,
        "scores": {k: float(v) for k, v in scores.items()},
        "meta": meta,
        "addr_hash": hashlib.sha256(np.ascontiguousarray(addr).tobytes()).hexdigest(),
    }


def _cross_context_probe(
    ag: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    *,
    tag: str,
) -> dict[str, Any]:
    distractor = "s_dist_" + hashlib.sha256(tag.encode()).hexdigest()[:8]
    hits = []
    for i, (cue, handle) in enumerate(pairs):
        probe = clone_frozen(ag)
        observe_cue(probe, world, tag=f"{tag}_dist{i}", body=list(MID_BODY), symbols=[distractor])
        probe.drop_actor_pending()
        hist = pairs[(i + 1) % len(pairs)][0]
        observe_cue(probe, world, tag=f"{tag}_hist{i}", body=list(MID_BODY), symbols=[hist])
        probe.drop_actor_pending()
        observe_cue(probe, world, tag=f"{tag}_p{i}", body=list(MID_BODY), symbols=[cue])
        scores, addr, meta = probe.event_memory_scores()
        winner = unique_winner(scores)
        rec = {
            "winner": winner,
            "want": handle,
            "ok": winner == handle,
            "scores": {k: float(v) for k, v in scores.items()},
            "meta": meta,
            "addr_hash": hashlib.sha256(np.ascontiguousarray(addr).tobytes()).hexdigest(),
        }
        hits.append(rec)
    n_ok = sum(1 for h in hits if h["ok"])
    return {"n_ok": n_ok, "n_need": len(pairs), "probes": hits, "ranking_ok": n_ok == len(pairs)}


def _mapping_probe(
    ag: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    *,
    tag: str,
) -> dict[str, Any]:
    hits = []
    for i, (cue, handle) in enumerate(pairs):
        rec = organism_probe(ag, world, cue, tag=f"{tag}_p{i}")
        rec["want"] = handle
        rec["ok"] = rec["winner"] == handle
        hits.append(rec)
    n_ok = sum(1 for h in hits if h["ok"])
    return {"n_ok": n_ok, "n_need": len(pairs), "probes": hits, "ranking_ok": n_ok == len(pairs)}


def _teach(ag: NeuralCortex, world: dict[str, Any], pairs: list[tuple[str, str]], *, tag: str) -> None:
    for i, (cue, handle) in enumerate(pairs):
        teach_one(ag, world, handle, tag=f"{tag}_{i}", symbols=[cue])


def eval_associate(*, arm: str, wi: int, seed_registry: int, tmp: str) -> dict[str, Any]:
    cell_id = f"associate|{arm}|w{wi}"
    world = capacity_world(wi, DEV_DOMAIN, n_cues=2, n_handles=2)
    pairs = _seq(mapping_pairs(world, flip=False), "A_then_B")
    ag = _fresh(tmp, cell_id, world, seed_registry=seed_registry)
    _configure(ag, arm)
    birth_h = ag.memproj_hashes()
    _teach(ag, world, pairs, tag=cell_id)
    final_h = ag.memproj_hashes()
    own = ownership_fail_reasons(ag)
    probed = _cross_context_probe(ag, world, pairs, tag=f"{cell_id}_x")
    out = {
        "kind": "associate",
        "id": cell_id,
        "arm": arm,
        "world": wi,
        "passed": bool(probed["ranking_ok"]) and not own,
        "ranking_ok": bool(probed["ranking_ok"]),
        "n_ok": probed["n_ok"],
        "birth_hashes": birth_h,
        "final_hashes": final_h,
        "kqv_delta": {k: birth_h[k] != final_h[k] for k in birth_h},
        "frobenius_delta": ag.memproj_deltas(),
        "n_opaque": len(ag.opaque.rows()),
        "ownership_fail": own,
        "candidate_v41_lock": False,
        "probes": probed["probes"],
    }
    if own:
        out["cell_code"] = "canonical_path_ownership_fail"
        out["passed"] = False
    else:
        out["cell_code"] = "associate_ok" if out["passed"] else "associate_fail"
    assert_finite_record(out, ctx=cell_id)
    return out


