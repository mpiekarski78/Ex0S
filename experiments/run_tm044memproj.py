def eval_birth_restore(*, seed_registry: int, tmp: str) -> dict[str, Any]:
    cell_id = "birth_restore|learned_projection|w0"
    world = capacity_world(0, DEV_DOMAIN, n_cues=2, n_handles=2)
    pairs = _seq(mapping_pairs(world, flip=False), "A_then_B")
    ag = _fresh(tmp, cell_id, world, seed_registry=seed_registry)
    _configure(ag, "learned_projection")
    _teach(ag, world, pairs, tag=cell_id)
    trained = _cross_context_probe(ag, world, pairs, tag=f"{cell_id}_t")
    trained_h = ag.memproj_hashes()
    snap = ag.checkpoint()
    ag.restore_birth_memproj()
    birth = _cross_context_probe(ag, world, pairs, tag=f"{cell_id}_b")
    ag.load_checkpoint(snap)
    restored = _cross_context_probe(ag, world, pairs, tag=f"{cell_id}_r")
    birth_also = bool(birth["ranking_ok"])
    out = {
        "kind": "birth_restore",
        "id": cell_id,
        "passed": bool(trained["ranking_ok"]) and not birth_also and bool(restored["ranking_ok"]),
        "trained_ok": bool(trained["ranking_ok"]),
        "birth_ok": birth_also,
        "restored_ok": bool(restored["ranking_ok"]),
        "trained_hashes": trained_h,
        "restored_hashes": ag.memproj_hashes(),
        "candidate_v41_lock": False,
    }
    if bool(trained["ranking_ok"]) and birth_also:
        out["cell_code"] = "projection_learning_not_causal"
        out["passed"] = False
    elif out["passed"]:
        out["cell_code"] = "birth_restore_ok"
    else:
        out["cell_code"] = "birth_restore_fail"
    assert_finite_record(out, ctx=cell_id)
    return out


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "candidate_v41_lock": False,
        "novelty_familiarity_in_claim": False,
        "separate_candidate_review_open": False,
    }
    oracle = [c for c in cells if c["id"].startswith("associate|symbolic_oracle|")]
    none = [c for c in cells if c["id"].startswith("associate|no_persistent_memory|")]
    learned_a = [c for c in cells if c["id"].startswith("associate|learned_projection|")]
    birth_a = [c for c in cells if c["id"].startswith("associate|birth_projection|")]
    learned_r = [c for c in cells if c["id"].startswith("revision|learned_projection|")]
    birth_r = [c for c in cells if c["id"].startswith("revision|birth_projection|")]
    donors = [c for c in cells if c["kind"] == "donor"]
    if not oracle or not all(bool(c.get("passed")) for c in oracle):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    if any(c.get("cell_code") == "canonical_path_ownership_fail" for c in cells):
        return "canonical_path_ownership_fail", "canonical_path_ownership_fail", flags
    if any(c.get("cell_code") == "donor_basis_mismatch" for c in donors):
        return "donor_basis_mismatch", "donor_basis_mismatch", flags
    if none and all(bool(c.get("passed")) for c in none):
        return "memory_not_necessary", "memory_not_necessary", flags
    wipe = by.get("wipe|learned_projection|w0")
    if wipe and wipe.get("cell_code") == "memory_not_necessary":
        return "memory_not_necessary", "memory_not_necessary", flags
    learned_ok = all(bool(c.get("passed")) for c in learned_a + learned_r)
    birth_ok = all(bool(c.get("passed")) for c in birth_a + birth_r)
    br = by.get("birth_restore|learned_projection|w0")
    if learned_ok and (birth_ok or (br and br.get("cell_code") == "projection_learning_not_causal")):
        return "projection_learning_not_causal", "projection_learning_not_causal", flags
    if any(c.get("cell_code") == "address_not_organism_owned" for c in donors):
        return "address_not_organism_owned", "address_not_organism_owned", flags
    chk = by.get("checkpoint|learned_projection|w0")
    if (
        not learned_ok
        or not all(bool(c.get("passed")) for c in donors)
        or (chk and not bool(chk.get("passed")))
        or (br and not bool(br.get("passed")) and br.get("cell_code") != "projection_learning_not_causal")
    ):
        return "projection_fail", "projection_fail", flags
    flags["separate_candidate_review_open"] = True
    return "projection_pass", "projection_pass", flags


def refuse_runner_retrieve(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "canonical_cue_probe"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM044 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(V40_CLOSE.read_bytes()).hexdigest() != p["v40_close_sha"]:
        raise RuntimeError("v40 close SHA drifted")
    if hashlib.sha256(BOUNDARY.read_bytes()).hexdigest() != p["boundary_sha"]:
        raise RuntimeError("boundary SHA drifted")
    leak = refuse_runner_retrieve(THIS)
    if leak:
        raise RuntimeError(f"runner retrieve leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    seed = int(p["seed_registry"])
    if seed in [int(x) for x in p["forbidden_seeds"]]:
        raise RuntimeError("seed collision")
    if "memproj_arm" in GenomeConfig().to_dict():
        raise RuntimeError("memproj must not be a GenomeConfig field")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="mp_dev_")
    try:
        t = tmp.name
        for wi in range(int(p["n_worlds"])):
            for arm in list(p["arms"]):
                cells.append(eval_associate(arm=str(arm), wi=int(wi), seed_registry=seed, tmp=t))
            cells.append(eval_revision(arm="learned_projection", wi=int(wi), seed_registry=seed, tmp=t))
            cells.append(eval_revision(arm="birth_projection", wi=int(wi), seed_registry=seed, tmp=t))
        cells.append(eval_donor(which="A_to_host", seed_registry=seed, tmp=t))
        cells.append(eval_donor(which="B_to_host", seed_registry=seed, tmp=t))
        cells.append(eval_wipe(seed_registry=seed, tmp=t))
        cells.append(eval_checkpoint(seed_registry=seed, tmp=t))
        cells.append(eval_birth_restore(seed_registry=seed, tmp=t))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "candidate_v41_lock": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "neural_edited": True,
        "solver_edited": False,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.44.MEMPROJ.DECISION",
        "product": "0.0.004",
        "earned_next": False,
        "eligible_for_000005": False,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "candidate_v41_lock": False,
        "note": "TM044 memory-projection wall. Product remains 0.0.004. No cortex.candidate.v41.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


def write_results_md(out: dict[str, Any]) -> None:
    lines = [
        "# TM.0.44.MEMPROJ results",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        "Product **0.0.004**. No v41 candidate lock.",
        "",
        f"Cells: {out['n_cells']}.",
        "",
    ]
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


