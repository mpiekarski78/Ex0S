def eval_donor(*, which: str, seed_registry: int, tmp: str) -> dict[str, Any]:
    cell_id = f"donor|{which}|w0"
    world = capacity_world(0, DEV_DOMAIN, n_cues=2, n_handles=2)
    pairs_a = _seq(mapping_pairs(world, flip=False), "A_then_B")
    pairs_b = [(c, pairs_a[1][1] if h == pairs_a[0][1] else pairs_a[0][1]) for c, h in pairs_a]
    base = _fresh(tmp, f"{cell_id}_base", world, seed_registry=seed_registry)
    _configure(base, "learned_projection")
    base.freeze_memproj_projection(True)
    h0 = base.memproj_hashes()
    donor = clone_memproj(base)
    host = clone_memproj(base)
    teach_pairs = pairs_a if which.startswith("A") else pairs_b
    _teach(donor, world, teach_pairs, tag=f"{cell_id}_d")
    hd = donor.memproj_hashes()
    hh = host.memproj_hashes()
    proj = ("W_k", "W_q", "W_v")
    if any(hd[k] != hh[k] or hd[k] != h0[k] for k in proj):
        out = {
            "kind": "donor",
            "id": cell_id,
            "passed": False,
            "cell_code": "donor_basis_mismatch",
            "donor_hashes": hd,
            "host_hashes": hh,
            "base_hashes": h0,
            "candidate_v41_lock": False,
        }
        assert_finite_record(out, ctx=cell_id)
        return out
    host.replace_opaque_rows(donor.opaque_snapshot())
    own = ownership_fail_reasons(host)
    probed = _mapping_probe(host, world, teach_pairs, tag=f"{cell_id}_x")
    out = {
        "kind": "donor",
        "id": cell_id,
        "passed": bool(probed["ranking_ok"]) and not own,
        "n_ok": probed["n_ok"],
        "n_opaque_host": len(host.opaque.rows()),
        "ownership_fail": own,
        "candidate_v41_lock": False,
    }
    if own:
        out["cell_code"] = "canonical_path_ownership_fail"
        out["passed"] = False
    elif probed["ranking_ok"]:
        out["cell_code"] = "donor_ok"
    else:
        out["cell_code"] = "address_not_organism_owned"
        out["passed"] = False
    assert_finite_record(out, ctx=cell_id)
    return out


