DEV_DOMAIN = "TM033.ADAPTREHEARSE.DEV."
EXPECTED_N_CELLS = 24
EXPECTED_N_TRIPLES = 8
MANIFEST_SHA = "5fa2dac5200a6944b0a31530d57983d7dd61cbe84d69ace45ac361a93079a3ad"
ARMS = ("v37_awake_cap", "adaptive_violation", "fixed_extra_replay")
DEFAULT_SEED_REGISTRY = 22222


def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def registry_seeds() -> list[int]:
    seeds = [int(s) for s in load_prereg()["registry_seeds"]]
    if len(seeds) != 4 or DEFAULT_SEED_REGISTRY in seeds:
        raise RuntimeError("bad registry seeds")
    return seeds


def neural_ready() -> bool:
    return hasattr(NeuralCortex, "set_act_rehearse_arm")


def bind_arm(ag: NeuralCortex, arm: str) -> None:
    if arm not in ARMS:
        raise ValueError(arm)
    ag.genome.act_recall_mode = TREATMENT_MODE
    ag.genome.episodic_act_recall = False
    if arm == "v37_awake_cap":
        if neural_ready():
            ag.set_act_rehearse_arm(arm)
        return
    if not neural_ready():
        raise RuntimeError("v38 neural controller not installed")
    ag.set_act_rehearse_arm(arm)


def _fresh(tmp: str, tag: str, world: dict[str, Any], *, seed_registry: int, arm: str) -> NeuralCortex:
    ag = make_cortex(Path(tmp) / tag, genome=genome_for_registry(seed_registry), device="cpu")
    if str(ag.genome.act_score_mode) != ACT_SCORE_QUERY:
        raise RuntimeError("scoring must remain query")
    ag.bind_actuators(list(world["handles"]))
    bind_arm(ag, arm)
    return ag


def cell_fixes(rec: dict[str, Any]) -> bool:
    return bool(int(rec.get("n_store_violations") or 0) == 0 and rec.get("live_ranking_ok") and int(rec.get("n_probe_correct") or 0) == 8)


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = []
    for ri, _s in enumerate(p["registry_seeds"]):
        for order in list(p["orders"]):
            for arm in list(p["arms"]):
                ids.append(f"acquire|c8|{order}|reg{ri}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "registry_seeds": list(p["registry_seeds"]),
        "arms": list(p["arms"]),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM033 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def sum_awake_updates(bursts: list[dict[str, Any] | None]) -> int:
    n = 0
    for b in bursts:
        if not b:
            continue
        n += int(b.get("total_updates") or 0)
    return n


def sum_awake_passes(bursts: list[dict[str, Any] | None]) -> int:
    n = 0
    for b in bursts:
        if not b:
            continue
        n += int(b.get("n_passes") or len(list(b.get("passes") or [])))
    return n


def any_budget_exhausted(bursts: list[dict[str, Any] | None]) -> bool:
    return any(bool((b or {}).get("budget_exhausted")) for b in bursts)


def debt_snapshot(ag: NeuralCortex) -> dict[str, int]:
    return {
        "rehearsal_pass_debt": int(getattr(ag, "_rehearsal_pass_debt", 0) or 0),
        "rehearsal_update_debt": int(getattr(ag, "_rehearsal_update_debt", 0) or 0),
    }


def eval_cell(
    *,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    seed_registry: int,
    reg: int,
    arm: str,
    n_ticks: int,
) -> dict[str, Any]:
    seq = list(reversed(pairs)) if order == "B_then_A" else list(pairs)
    tmp = tempfile.TemporaryDirectory(prefix="ar_train_")
    try:
        ag = _fresh(tmp.name, "s", world, seed_registry=seed_registry, arm=arm)
        taught, bursts = teach_pairs(ag, world, seq, tag=f"{arm}_{order}_reg{reg}")
        n_awake = sum_awake_updates(bursts)
        n_passes = sum_awake_passes(bursts)
        debt_before = debt_snapshot(ag)
        rows = stored_rows(ag)
        live = live_probes(ag, world, pairs, taught, tag=f"{arm}_{order}_reg{reg}")
        rest_out = ag.rest_epoch(int(n_ticks))
        rh = rest_out.get("rehearsal") or {}
        debt_after = debt_snapshot(ag)
        targeting = str(getattr(ag, "_rehearse_targeting", "violation_rows") or "violation_rows")
        rec = {
            "kind": "acquire",
            "arm": arm,
            "id": f"acquire|c8|{order}|reg{reg}|{arm}",
            "order": order,
            "reg": int(reg),
            "seed_registry": int(seed_registry),
            "n_cues": 8,
            "act_recall_mode": TREATMENT_MODE,
            "taught": taught,
            "n_awake_updates": int(n_awake),
            "n_awake_passes": int(n_passes),
            "awake_budget_exhausted": bool(any_budget_exhausted(bursts)),
            "targeting": targeting,
            "n_store_violations": int(sum(1 for r in rows if r.get("store_violation"))),
            "n_episodes": len(ag._episodes),
            "stored_rows": rows,
            "live_ranking_ok": bool(live["ranking_ok"]),
            "n_probe_correct": int(live["n_probe_correct"]),
            "min_normalized_geometric_margin": float(live["min_normalized_geometric_margin"]),
            "probes": live["probes"],
            "rest_n_replay": int(rh.get("total_updates") or rh.get("n_replay") or 0),
            "rest_first_converged_epoch": rh.get("first_converged_epoch"),
            "rest_n_epochs": len(list(rh.get("epochs") or [])),
            "rest_pass_budget_used": int(rh.get("pass_budget") or len(list(rh.get("epochs") or []))),
            "rehearsal_pass_debt_before_rest": debt_before["rehearsal_pass_debt"],
            "rehearsal_update_debt_before_rest": debt_before["rehearsal_update_debt"],
            "rehearsal_pass_debt_after_rest": debt_after["rehearsal_pass_debt"],
            "rehearsal_update_debt_after_rest": debt_after["rehearsal_update_debt"],
            "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
        }
        rec["fixed"] = cell_fixes(rec)
        rec["passed"] = bool(rec["fixed"])
        rec["behavioral_pass"] = bool(rec["fixed"])
        assert_finite_record(rec, ctx=rec["id"])
        return rec
    finally:
        tmp.cleanup()


def targeting_matched(adaptive: dict[str, Any], fixed: dict[str, Any]) -> bool:
    return str(adaptive.get("targeting") or "") == "violation_rows" and str(fixed.get("targeting") or "") == "violation_rows"


def route_triple(v37: dict[str, Any], adaptive: dict[str, Any], fixed: dict[str, Any]) -> str:
    if cell_fixes(v37):
        return "v37_already_converged"
    a_ok = cell_fixes(adaptive)
    f_ok = cell_fixes(fixed)
    matched = targeting_matched(adaptive, fixed)
    if a_ok and not f_ok:
        return "adaptive_control" if matched else "controller_bundle"
    if a_ok and f_ok:
        if int(adaptive["n_awake_updates"]) < int(fixed["n_awake_updates"]):
            return "efficient_scheduling"
        return "both_pass_compute_tied"
    if f_ok and not a_ok:
        return "extra_compute_not_scheduler"
    return "both_fail"


def _decision(
    triple_routes: list[str],
    cells: list[dict[str, Any]],
) -> tuple[str, str, dict[str, Any]]:
    diagnostic = [r for r in triple_routes if r != "v37_already_converged"]
    adaptive_cells = [c for c in cells if c.get("arm") == "adaptive_violation"]
    debt_left = [
        c["id"]
        for c in adaptive_cells
        if int(c.get("rehearsal_pass_debt_after_rest") or 0) != 0
        or int(c.get("rehearsal_update_debt_after_rest") or 0) != 0
    ]
    flags = {
        "n_triples": len(triple_routes),
        "n_diagnostic": len(diagnostic),
        "n_v37_already_converged": sum(1 for r in triple_routes if r == "v37_already_converged"),
        "n_budget_exhausted": sum(1 for c in cells if c.get("awake_budget_exhausted")),
        "n_debt_remaining_after_rest": len(debt_left),
        "debt_remaining_ids": debt_left,
        "routes": list(triple_routes),
    }
    if debt_left:
        return "adaptrehearse_debt_integrity_fail", "adaptrehearse_debt_integrity_fail", flags
    if not diagnostic:
        return "adaptrehearse_no_v37_acquire_fail", "adaptrehearse_no_v37_acquire_fail", flags
    uniq = set(diagnostic)
    mapping = {
        "adaptive_control": "adaptrehearse_adaptive_control",
        "controller_bundle": "adaptrehearse_controller_bundle",
        "efficient_scheduling": "adaptrehearse_efficient_scheduling",
        "extra_compute_not_scheduler": "adaptrehearse_extra_compute_not_scheduler",
        "both_pass_compute_tied": "adaptrehearse_both_pass_compute_tied",
        "both_fail": "adaptrehearse_core_acquire_fail",
    }
    if len(uniq) == 1:
        only = next(iter(uniq))
        code = mapping[only]
        return code, code, flags
    return "adaptrehearse_mixed_routes", "adaptrehearse_mixed_routes", flags


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and sha_file(THIS) != frozen:
        raise RuntimeError("TM033 runner SHA drifted after freeze push")
    if sha_file(TM032_RUNNER) != p["tm032_runner_sha"]:
        raise RuntimeError("TM032 runner SHA drifted")
    if hashlib.sha256(TM032_DEC.read_bytes()).hexdigest() != p["tm032_decision_sha"]:
        raise RuntimeError("TM032 decision SHA drifted")
    if hashlib.sha256(TM032_DEV.read_bytes()).hexdigest() != p["tm032_dev_sha"]:
        raise RuntimeError("TM032 DEV SHA drifted")
    if int(EPISODE_REPLAY_EPOCHS) != int(p["hard_budget_passes"]):
        raise RuntimeError("hard budget must remain EPISODE_REPLAY_EPOCHS")
    if not neural_ready():
        raise RuntimeError("v38 neural controller not installed; freeze holds")
    ids = expected_cell_ids()
    wi = int(p.get("world_index") or 0)
    n_ticks = int(p.get("n_rest_ticks") or 4)
    world = capacity_world(wi, DEV_DOMAIN, n_cues=8, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    cells: list[dict[str, Any]] = []
    triple_routes: list[str] = []
    for ri, seed in enumerate(registry_seeds()):
        for order in list(p["orders"]):
            by_arm: dict[str, dict[str, Any]] = {}
            for arm in ARMS:
                rec = eval_cell(
                    world=world,
                    pairs=pairs,
                    order=order,
                    seed_registry=int(seed),
                    reg=ri,
                    arm=arm,
                    n_ticks=n_ticks,
                )
                by_arm[arm] = rec
                cells.append(rec)
            route = route_triple(by_arm["v37_awake_cap"], by_arm["adaptive_violation"], by_arm["fixed_extra_replay"])
            triple_routes.append(route)
            for rec in by_arm.values():
                rec["triple_route"] = route
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    if len(triple_routes) != EXPECTED_N_TRIPLES:
        raise RuntimeError("triple count drifted")
    code, then, flags = _decision(triple_routes, cells)
    git_head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_triples": len(triple_routes),
        "cells": cells,
        "triple_routes": triple_routes,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": git_head,
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
        "fit_44_row_updates": False,
        "tm032_n_informative_splits": 2,
        "limitation": "two_tm032_reg1_splits",
    }


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.33.ADAPTREHEARSE.DECISION",
        "product": "0.0.004",
        "manifest_sha": MANIFEST_SHA,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "hard_budget_passes": out.get("hard_budget_passes"),
        "fit_44_row_updates": False,
        "limitation": out.get("limitation"),
        "modify_R": False,
        "act_recall_modes_tuple_untouched": True,
        "note": "TM033 adaptive-rehearsal decision. Product remains 0.0.004.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


def write_results_md(out: dict[str, Any]) -> None:
    flags = out["phase_flags"]
    lines = [
        "# TM.0.33.ADAPTREHEARSE results",
        "",
        "v38 adaptive violation-driven rehearsal. Product **0.0.004**.",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        "Limitation: TM032 evidence was two `reg1` splits. Hard budget is REST `EPISODE_REPLAY_EPOCHS` passes, not 44 updates.",
        "",
        f"- triples: {flags.get('n_triples')} diagnostic {flags.get('n_diagnostic')} v37-already {flags.get('n_v37_already_converged')}",
        f"- routes: {flags.get('routes')}",
        "",
    ]
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def freeze_runner_sha() -> None:
    p = load_prereg()
    if p.get("frozen_runner_sha"):
        raise RuntimeError("already frozen")
    p["frozen_runner_sha"] = sha_file(THIS)
    PREREG.write_text(json.dumps(p, indent=2) + "\n", encoding="utf-8")


def smoke() -> dict[str, Any]:
    assert load_prereg()["manifest_sha"] == MANIFEST_SHA
    assert len(expected_cell_ids()) == EXPECTED_N_CELLS
    assert int(EPISODE_REPLAY_EPOCHS) == 16
    seed = registry_seeds()[0]
    world = capacity_world(0, DEV_DOMAIN, n_cues=2, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    with tempfile.TemporaryDirectory(prefix="ar_smk_") as tmp:
        ag = _fresh(tmp, "s", world, seed_registry=seed, arm="v37_awake_cap")
        taught, bursts = teach_pairs(ag, world, pairs, tag="smk")
        live = live_probes(ag, world, pairs, taught, tag="smk")
    return {
        "smoke_ok": True,
        "arm": "v37_awake_cap",
        "n_awake_updates": sum_awake_updates(bursts),
        "n_probe": live["n_probe_correct"],
        "neural_ready": neural_ready(),
        "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    ap.add_argument("--freeze-runner-sha", action="store_true")
    args = ap.parse_args()
    if args.freeze_runner_sha:
        freeze_runner_sha()
        print(json.dumps({"frozen_runner_sha": sha_file(THIS)}, indent=2))
        return
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(json.dumps({"decision_code": out["decision_code"], "n_cells": out["n_cells"]}, indent=2))
        return
    ap.print_help()


if __name__ == "__main__":
    main()
