REPO_ROOT = Path(__file__).resolve().parents[1]
THIS = Path(__file__).resolve()
LAB = "TM.0.33.ADAPTREHEARSE"
PREREG = REPO_ROOT / "docs" / "lineage_adaptrehearse.prereg.lock"
DEV_LOCK = REPO_ROOT / "docs" / "lineage_adaptrehearse.dev.lock"
DECISION = REPO_ROOT / "docs" / "lineage_adaptrehearse.decision.lock"
