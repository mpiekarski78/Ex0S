def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for wi in range(int(p["n_worlds"])):
        for order in list(p["orders"]):
            for arm in ARMS:
                ids.append(f"acquire|c8|{order}|w{wi}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(ARMS),
        "reconstruct_domain": RECONSTRUCT_DOMAIN,
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM041 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def _rank(ag: NeuralCortex, addr: np.ndarray, want: str) -> dict[str, Any]:
    scores = ag.actuator_scores(addr)
    winner = unique_winner(scores)
    g = float(ag._act_geometric_margin(addr, want))
    return {
        "scores": {k: float(v) for k, v in scores.items()},
        "winner": winner,
        "ranking_ok": bool(winner == want),
        "normalized_geometric_margin": g,
        "pairwise_score_gap": float(ranking_margin(scores, winner)) if winner else 0.0,
        "addr_hash": arr_sha(addr),
    }


def classify_failed_cue(row: dict[str, Any]) -> str:
    path = str(row["canonical"]["path"] or "")
    familiar = bool(row["canonical"].get("familiar"))
    slot = row["canonical"].get("slot")
    teach = row.get("teach_index")
    stored_ok = bool(row["counterfactual_stored"]["ranking_ok"])
    addr_ok = bool(row["counterfactual_live"]["ranking_ok"])
    live_ok = bool(row["live_tm040"].get("ranking_ok"))
    store_viol = bool(row["store"]["violation"])
    addr_h = str(row["canonical"].get("scoring_address_hash") or "")
    stored_h = str(row["store"].get("p1_hash") or "")
    if store_viol or not stored_ok:
        return "stored_p1_fails"
    if path in ("cortical_fallback", "cortical") and not familiar:
        return "cortical_fallback_unfamiliar"
    if path == "episodic_completed" and slot is not None and int(slot) != int(teach):
        return "wrong_slot"
    if stored_ok and not live_ok and addr_h == stored_h:
        return "canonical_path_inconsistency"
    if stored_ok and not addr_ok:
        return "store_pass_live_addr_fail"
    if stored_ok and not live_ok:
        return "canonical_path_inconsistency"
    return "unclassified_live_fail"


def diagnose_cue(
    ag: NeuralCortex,
    world: dict[str, Any],
    cue: str,
    want: str,
    teach_index: int,
    *,
    tag: str,
) -> dict[str, Any]:
    probe = clone_frozen(ag)
    observe_cue(probe, world, tag=tag, body=list(MID_BODY), symbols=[cue])
    live_p1 = probe._last_p1
    if live_p1 is None:
        live_p1 = probe._from_t(probe.rho)
    live_p1 = np.asarray(live_p1, dtype=np.float64)
    scores, score_addr, meta = probe.actuator_decision_scores(live_p1)
    score_addr = np.asarray(score_addr, dtype=np.float64)
    winner = unique_winner(scores)
    ep = ag._episodes[int(teach_index)] if teach_index < len(ag._episodes) else None
    stored_p1 = None if ep is None else np.asarray(ep["p1"], dtype=np.float64)
    store_viol = True
    store_rank: dict[str, Any] | None = None
    if stored_p1 is not None:
        store_viol = bool(ag._episode_rehearsal_violation(stored_p1, str(ep["handle"]), float(ep["adv"])))
        store_rank = _rank(ag, stored_p1, want)
    live_rank = _rank(probe, live_p1, want)
    stored_cf = (
        _rank(probe, stored_p1, want)
        if stored_p1 is not None
        else {"ranking_ok": False, "winner": None, "scores": {}, "normalized_geometric_margin": None}
    )
    live_cf = _rank(probe, score_addr, want)
    canon_g = probe_geometric_margin(probe, score_addr, scores, want)
    row = {
        "cue": cue,
        "want": want,
        "teach_index": int(teach_index),
        "store": {
            "slot_expected": int(teach_index),
            "handle": None if ep is None else str(ep["handle"]),
            "violation": bool(store_viol),
            "p1_hash": arr_sha(stored_p1),
            **(
                {}
                if store_rank is None
                else {k: store_rank[k] for k in ("winner", "ranking_ok", "normalized_geometric_margin", "scores")}
            ),
        },
        "live_tm040": {
            "p1_hash": arr_sha(live_p1),
            "winner": live_rank["winner"],
            "ranking_ok": live_rank["ranking_ok"],
            "normalized_geometric_margin": live_rank["normalized_geometric_margin"],
            "scores": live_rank["scores"],
        },
        "canonical": {
            "path": meta.get("path"),
            "familiar": meta.get("familiar"),
            "reason": meta.get("reason"),
            "slot": meta.get("slot"),
            "d1": meta.get("nearest_dist"),
            "d2": meta.get("second_nearest_dist"),
            "R": meta.get("R"),
            "B": meta.get("B"),
            "winner": winner,
            "ranking_ok": bool(winner == want),
            "normalized_geometric_margin": float(canon_g),
            "scoring_address_hash": arr_sha(score_addr),
            "act_recall_mode": meta.get("act_recall_mode"),
            "scores": {k: float(v) for k, v in scores.items()},
        },
        "counterfactual_stored": stored_cf,
        "counterfactual_live": live_cf,
        "addr_equals_stored_p1": bool(arr_sha(score_addr) == arr_sha(stored_p1)) if stored_p1 is not None else False,
        "addr_equals_live_p1": bool(arr_sha(score_addr) == arr_sha(live_p1)),
        "key_rho_hash": arr_sha(probe._last_key_rho),
    }
    row["tm040_live_fail"] = not bool(live_rank["ranking_ok"])
    if row["tm040_live_fail"]:
        row["fail_class"] = classify_failed_cue(row)
    else:
        row["fail_class"] = "live_ok"
    return row


def eval_cell(
    *,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    arm: str,
    wi: int,
    seed_registry: int,
    tmp: str,
) -> dict[str, Any]:
    cell_id = f"acquire|c8|{order}|w{wi}|{arm}"
    seq = _seq(pairs, order)
    ag = _fresh(tmp, f"{cell_id}", world, seed_registry=seed_registry)
    set_arm(ag, arm)
    taught, _b = teach_pairs(ag, world, seq, tag=cell_id)
    n_viol = int(ag._count_store_violations())
    teach_index = {str(t["cue"]): int(i) for i, t in enumerate(taught)}
    cues = []
    for i, (cue, handle) in enumerate(pairs):
        cues.append(
            diagnose_cue(
                ag,
                world,
                cue,
                handle,
                int(teach_index[cue]),
                tag=f"{cell_id}_p{i}",
            )
        )
    failed = [r for r in cues if r["fail_class"] != "live_ok"]
    n_ok = sum(1 for r in cues if r["live_tm040"]["ranking_ok"])
    out = {
        "kind": "acquire",
        "id": cell_id,
        "arm": arm,
        "order": order,
        "world": int(wi),
        "stem": f"acquire|c8|{order}|w{wi}",
        "n_store_violations": n_viol,
        "n_replaced": int(ag._episode_n_replaced),
        "n_episodes": len(ag._episodes),
        "n_probe_correct_tm040": int(n_ok),
        "passed_tm040_live": bool(n_ok == len(pairs) and n_viol == 0),
        "w_hash": weight_hash(ag._from_t(ag.W_act_query)),
        "cues": cues,
        "failed_cues": [r["cue"] for r in failed],
        "failed_classes": [r["fail_class"] for r in failed],
        "candidate_v40_lock": False,
        "not_an_exact_projector": True,
    }
    assert_finite_record(out, ctx=cell_id)
    return out


def _retrieval_identity(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    keys = ("path", "familiar", "slot", "d1", "d2", "R", "reason")
    same_meta = True
    per_cue: list[dict[str, Any]] = []
    by_b = {str(r["cue"]): r for r in b["cues"]}
    for ra in a["cues"]:
        rb = by_b[str(ra["cue"])]
        meta_ok = all(ra["canonical"].get(k) == rb["canonical"].get(k) for k in keys)
        hash_ok = (
            ra["canonical"]["scoring_address_hash"] == rb["canonical"]["scoring_address_hash"]
            and ra["live_tm040"]["p1_hash"] == rb["live_tm040"]["p1_hash"]
            and ra["store"]["p1_hash"] == rb["store"]["p1_hash"]
            and ra["key_rho_hash"] == rb["key_rho_hash"]
        )
        same_meta = same_meta and meta_ok and hash_ok
        per_cue.append(
            {
                "cue": ra["cue"],
                "retrieval_identical": bool(meta_ok and hash_ok),
                "fallback_live_ok": ra["live_tm040"]["ranking_ok"],
                "always_live_ok": rb["live_tm040"]["ranking_ok"],
                "fallback_class": ra["fail_class"],
                "always_class": rb["fail_class"],
            }
        )
    return {
        "retrieval_identical": bool(same_meta),
        "w_hash_equal": a["w_hash"] == b["w_hash"],
        "cues": per_cue,
    }


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    fb = [c for c in cells if c["arm"] == "fallback_joint"]
    classes: list[str] = []
    for c in fb:
        classes.extend(c["failed_classes"])
    uniq = sorted(set(classes))
    compares: list[dict[str, Any]] = []
    by_stem: dict[str, dict[str, dict[str, Any]]] = {}
    for c in cells:
        by_stem.setdefault(c["stem"], {})[c["arm"]] = c
    n_retr_same = 0
    n_w_flip = 0
    for stem, arms in by_stem.items():
        if "fallback_joint" in arms and "always_joint" in arms:
            cmp_ = _retrieval_identity(arms["fallback_joint"], arms["always_joint"])
            cmp_["stem"] = stem
            compares.append(cmp_)
            if cmp_["retrieval_identical"]:
                n_retr_same += 1
            if cmp_["retrieval_identical"] and (not arms["fallback_joint"]["passed_tm040_live"]) and arms["always_joint"]["passed_tm040_live"]:
                n_w_flip += 1
    n_v37_fb_w_eq = 0
    for stem, arms in by_stem.items():
        if "v37" in arms and "fallback_joint" in arms and arms["v37"]["w_hash"] == arms["fallback_joint"]["w_hash"]:
            n_v37_fb_w_eq += 1
    flags = {
        "n_cells": len(cells),
        "n_fallback_failed_cues": len(classes),
        "failed_classes": classes,
        "unique_failed_classes": uniq,
        "n_stems_retrieval_identical_fallback_vs_always": int(n_retr_same),
        "n_stems_always_joint_W_flip_same_retrieval": int(n_w_flip),
        "n_stems_v37_fallback_w_equal": int(n_v37_fb_w_eq),
        "always_joint_retrieval_unchanged": bool(n_retr_same == len(compares) and compares),
        "later_learning": "not_exercised",
        "contradict": "jointly_feasible_atomic_apply",
        "candidate_v40_lock": False,
        "compares": compares,
    }
    if not classes:
        code = "liveaddr_no_tm040_live_fail"
    elif uniq == ["cortical_fallback_unfamiliar"]:
        code = "liveaddr_cortical_fallback_unfamiliar"
    elif uniq == ["wrong_slot"]:
        code = "liveaddr_wrong_slot"
    elif uniq == ["canonical_path_inconsistency"]:
        code = "liveaddr_canonical_path_inconsistency"
    elif uniq == ["store_pass_live_addr_fail"]:
        code = "liveaddr_store_pass_live_addr_fail"
    elif uniq == ["stored_p1_fails"]:
        code = "liveaddr_stored_p1_fails"
    else:
        code = "liveaddr_mixed_routes"
    if flags["always_joint_retrieval_unchanged"] and n_w_flip:
        flags["always_joint_read"] = "same_retrieval_W_covers_live_address"
    elif not flags["always_joint_retrieval_unchanged"]:
        flags["always_joint_read"] = "retrieval_differed_unexpected"
    else:
        flags["always_joint_read"] = "observational"
    return code, code, flags


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and sha_file(THIS) != frozen:
        raise RuntimeError("TM041 runner SHA drifted after freeze push")
    if sha_file(NEURAL) != p["frozen_neural_sha"]:
        raise RuntimeError("neural_cortex.py must not change")
    if sha_file(SOLVER) != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(TM040_DEC.read_bytes()).hexdigest() != p["tm040_decision_sha"]:
        raise RuntimeError("TM040 decision SHA drifted")
    if hashlib.sha256(TM040_DEV.read_bytes()).hexdigest() != p["tm040_dev_sha"]:
        raise RuntimeError("TM040 DEV SHA drifted")
    if hashlib.sha256(TM040_ADD.read_bytes()).hexdigest() != p["tm040_addendum_sha"]:
        raise RuntimeError("TM040 addendum SHA drifted")
    if sha_file(TM040_RUNNER) != p["tm040_runner_sha"]:
        raise RuntimeError("TM040 runner SHA drifted")
    seed = int(p["seed_registry"])
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="la_dev_")
    try:
        for wi in range(int(p["n_worlds"])):
            world = capacity_world(wi, RECONSTRUCT_DOMAIN, n_cues=8, n_handles=2)
            pairs = mapping_pairs(world, flip=False)
            for order in list(p["orders"]):
                for arm in ARMS:
                    cells.append(
                        eval_cell(
                            world=world,
                            pairs=pairs,
                            order=order,
                            arm=arm,
                            wi=wi,
                            seed_registry=seed,
                            tmp=tmp.name,
                        )
                    )
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "reconstruct_domain": RECONSTRUCT_DOMAIN,
        "candidate_v40_lock": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "neural_edited": False,
        "solver_edited": False,
        "later_learning": "not_exercised",
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.41.LIVEADDR.DECISION",
        "product": "0.0.004",
        "manifest_sha": MANIFEST_SHA,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "candidate_v40_lock": False,
        "later_learning": "not_exercised",
        "note": "TM041 live-address classification. Product remains 0.0.004. No cortex.candidate.v40.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


def write_results_md(out: dict[str, Any]) -> None:
    flags = out["phase_flags"]
    lines = [
        "# TM.0.41.LIVEADDR results",
        "",
        "Live-address classification of TM040 failed acquire cues. Product **0.0.004**.",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        f"- failed classes: {flags.get('unique_failed_classes')}",
        f"- always_joint retrieval unchanged: {flags.get('always_joint_retrieval_unchanged')}",
        f"- always_joint read: {flags.get('always_joint_read')}",
        "- later learning: not_exercised",
        "- contradict: jointly_feasible_atomic_apply",
        "",
    ]
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def smoke() -> dict[str, Any]:
    assert load_prereg()["manifest_sha"] == MANIFEST_SHA
    assert len(expected_cell_ids()) == EXPECTED_N_CELLS
    p = load_prereg()
    world = capacity_world(0, RECONSTRUCT_DOMAIN, n_cues=2, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    with tempfile.TemporaryDirectory(prefix="la_smk_") as tmp:
        rec = eval_cell(
            world=world,
            pairs=pairs,
            order="A_then_B",
            arm="fallback_joint",
            wi=0,
            seed_registry=int(p["seed_registry"]),
            tmp=tmp,
        )
    return {"smoke_ok": True, "n_cues": len(rec["cues"]), "id": rec["id"]}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "unique_failed_classes": out["phase_flags"]["unique_failed_classes"],
                    "always_joint_read": out["phase_flags"]["always_joint_read"],
                    "candidate_v40_lock": False,
                },
                indent=2,
            )
        )
        return
    ap.print_help()


if __name__ == "__main__":
    main()
