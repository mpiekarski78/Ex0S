def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "install_W_star": False,
        "episode_match_l2_retuned": False,
        "canonical_law_reconsidered": False,
        "setup_excluded_from_behavioral_first_match": True,
        "opaque_store_law_compatible": None,
        "historical_episode_storage_unchanged": True,
    }
    for wi in (0, 1):
        cell = by.get(f"flag|w{wi}")
        if cell is None or not bool(cell.get("passed")):
            return "setup_precondition_fail", "setup_precondition_fail", flags
    scored = [c for c in cells if c.get("kind") == "scored"]
    if any(int(c.get("n_cross_action_refresh") or 0) > 0 for c in scored):
        flags["opaque_store_law_compatible"] = False
        return "cross_action_refresh", "cross_action_refresh", flags
    if any(int(c.get("n_cross_cue_merge") or 0) > 0 for c in scored):
        flags["opaque_store_law_compatible"] = False
        return "cross_cue_merge", "cross_cue_merge", flags
    if any(int(c.get("n_attempted_ne_resident") or 0) > 0 for c in scored):
        flags["opaque_store_law_compatible"] = False
        return "attempted_not_resident", "attempted_not_resident", flags
    if any(int(c.get("n_unreported_loss") or 0) > 0 for c in scored):
        flags["opaque_store_law_compatible"] = False
        return "unreported_capacity_loss", "unreported_capacity_loss", flags
    if any(c.get("probe") == "checkpoint" and not bool(c.get("checkpoint_ok")) for c in scored):
        flags["opaque_store_law_compatible"] = False
        return "checkpoint_not_byte_identical", "checkpoint_not_byte_identical", flags
    flags["opaque_store_law_compatible"] = True
    return "storage_integrity_holds", "storage_integrity_holds", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "_run_joint_socp_consolidation", "credit_tagged", "latest_episode", "solve_ceiling"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in (
                    "_last_p1",
                    "_last_key_rho",
                    "W_k",
                    "W_q",
                    "W_v",
                    "W_act_query",
                    "_episodes",
                ):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


