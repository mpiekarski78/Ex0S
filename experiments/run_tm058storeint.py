def hvec(x: Any) -> str | None:
    if x is None:
        return None
    return vec_hash(np.asarray(x, dtype=np.float64))


def unit(v: np.ndarray) -> np.ndarray:
    x = np.asarray(v, dtype=np.float64).reshape(-1)
    nrm = float(np.linalg.norm(x))
    if nrm <= 1e-12:
        raise RuntimeError("zero vector")
    return x / nrm


def near_pair(n: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(int(seed))
    a = unit(rng.normal(size=int(n)))
    delta = rng.normal(size=int(n))
    delta = delta - a * float(np.dot(delta, a))
    delta = unit(delta)
    b = unit(a + 0.01 * delta)
    return a, b


def distinct_unit(n: int, seed: int, k: int) -> np.ndarray:
    rng = np.random.default_rng(int(seed) + 17 * int(k) + 1)
    return unit(rng.normal(size=int(n)))


class Receipts:
    def __init__(self) -> None:
        self.rows: list[dict[str, Any]] = []

    def bind(self, ag: NeuralCortex) -> None:
        p = load_prereg()
        method = str(p["write_method"])
        orig = getattr(ag, method)
        recs = self

        def write_opaque_kv(key, value, *, handle: str, provenance_id: str) -> None:
            before = snapshot_rows(ag)
            ids_b = [r["provenance_id"] for r in before]
            hashes_b = {r["provenance_id"]: r["value_hash"] for r in before}
            orig(key, value, handle=str(handle), provenance_id=str(provenance_id))
            after = snapshot_rows(ag)
            ids_a = [r["provenance_id"] for r in after]
            added = [i for i in ids_a if i not in ids_b]
            removed = [i for i in ids_b if i not in ids_a]
            changed = [
                i
                for i in ids_a
                if i in hashes_b and hashes_b[i] != next(r["value_hash"] for r in after if r["provenance_id"] == i)
            ]
            if len(added) == 1 and not removed:
                outcome = "append"
            elif len(added) == 1 and len(removed) == 1:
                outcome = "evict"
            elif removed and not added:
                outcome = "drop"
            elif changed:
                outcome = "refresh"
            elif added or removed:
                outcome = "replace"
            else:
                outcome = "reject"
            recs.rows.append(
                {
                    "outcome": outcome,
                    "handle": str(handle),
                    "provenance_id": str(provenance_id),
                    "attempted_v_hash": hvec(value),
                    "attempted_k_hash": hvec(key),
                    "n_before": len(before),
                    "n_after": len(after),
                    "added": added,
                    "removed": removed,
                    "changed": changed,
                    "residents_after": [
                        {k: r[k] for k in ("provenance_id", "when", "key_hash", "value_hash")} for r in after
                    ],
                }
            )

        setattr(ag, method, write_opaque_kv)


def snapshot_rows(ag: NeuralCortex) -> list[dict[str, Any]]:
    opaque = getattr(ag, "opaque", None)
    if opaque is None or not hasattr(opaque, "rows"):
        return []
    out: list[dict[str, Any]] = []
    for row in opaque.rows():
        val = np.asarray(row.value, dtype=np.float64).copy()
        key = np.asarray(row.key, dtype=np.float64).copy()
        out.append(
            {
                "provenance_id": str(row.provenance_id),
                "when": int(row.when),
                "key_hash": hvec(key),
                "value_hash": hvec(val),
                "key": key,
                "value": val,
            }
        )
    return out


def emit(ag: NeuralCortex, *, key: np.ndarray, value: np.ndarray, handle: str, provenance_id: str) -> None:
    getattr(ag, load_prereg()["write_method"])(key, value, handle=str(handle), provenance_id=str(provenance_id))


