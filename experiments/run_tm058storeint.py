def tally(receipts: list[dict[str, Any]], rows: list[dict[str, Any]], *, n_expected: int | None = None) -> dict[str, Any]:
    n_refresh = int(sum(1 for r in receipts if r["outcome"] in ("refresh", "replace")))
    n_drop = int(sum(1 for r in receipts if r["outcome"] == "drop"))
    n_evict = int(sum(1 for r in receipts if r["outcome"] == "evict"))
    n_append = int(sum(1 for r in receipts if r["outcome"] == "append"))
    attempted_ok = 0
    attempted_bad = 0
    for rec in receipts:
        if rec["outcome"] in ("reject", "drop"):
            continue
        target = rec["provenance_id"]
        hit = next((r for r in rec["residents_after"] if r["provenance_id"] == target), None)
        if rec["outcome"] == "evict":
            added = rec["added"][0] if rec["added"] else target
            hit = next((r for r in rec["residents_after"] if r["provenance_id"] == added), None)
        if hit is not None and hit["value_hash"] == rec["attempted_v_hash"]:
            attempted_ok += 1
        else:
            attempted_bad += 1
    unreported = n_drop
    if n_expected is not None and len(rows) < int(n_expected) and n_evict == 0:
        unreported += 1
    return {
        "n_refresh": n_refresh,
        "n_drop": n_drop,
        "n_evict": n_evict,
        "n_append": n_append,
        "n_residents": len(rows),
        "n_attempted_ne_resident": int(attempted_bad),
        "n_unreported_loss": int(unreported),
    }


def run_probe(*, tmp: str, probe: str, wi: int) -> dict[str, Any]:
    p = load_prereg()
    ag = make_agent(tmp, f"si_{probe}_w{wi}", int(wi))
    handles = list(capacity_world(int(wi), str(p["domains"]["DEV"]), n_cues=int(p["n_facts"]), n_handles=int(p["n_handles"]))["handles"])
    getattr(ag, str(p["flag_setter"]))(True)
    recs = Receipts()
    recs.bind(ag)
    n = int(ag.genome.n)
    seed = int(p["seed_registry"]) + 1000 * int(wi)
    h0, h1 = handles[0], handles[1]
    if probe == "near_action":
        v0, v1 = near_pair(n, seed)
        emit(ag, key=distinct_unit(n, seed, 0), value=v0, handle=h0, provenance_id=f"na0_{wi}")
        emit(ag, key=distinct_unit(n, seed, 1), value=v1, handle=h1, provenance_id=f"na1_{wi}")
    elif probe == "cue_key":
        val = distinct_unit(n, seed, 2)
        emit(ag, key=distinct_unit(n, seed, 3), value=val, handle=h0, provenance_id=f"ck0_{wi}")
        emit(ag, key=distinct_unit(n, seed, 4), value=val.copy(), handle=h0, provenance_id=f"ck1_{wi}")
    elif probe == "repeat":
        key = distinct_unit(n, seed, 5)
        val = distinct_unit(n, seed, 6)
        emit(ag, key=key, value=val, handle=h0, provenance_id=f"rp0_{wi}")
        emit(ag, key=key.copy(), value=val.copy(), handle=h0, provenance_id=f"rp1_{wi}")
    elif probe == "capacity":
        for i in range(int(EPISODE_SLOTS) + 1):
            emit(
                ag,
                key=distinct_unit(n, seed, 20 + i),
                value=distinct_unit(n, seed, 40 + i),
                handle=handles[i % len(handles)],
                provenance_id=f"cap{i}_{wi}",
            )
    elif probe == "checkpoint":
        for i in range(3):
            emit(
                ag,
                key=distinct_unit(n, seed, 60 + i),
                value=distinct_unit(n, seed, 80 + i),
                handle=handles[i % len(handles)],
                provenance_id=f"cp{i}_{wi}",
            )
    else:
        raise RuntimeError(probe)
    rows = snapshot_rows(ag)
    stats = tally(recs.rows, rows, n_expected=None if probe == "capacity" else len(recs.rows))
    if probe == "capacity":
        stats = tally(recs.rows, rows, n_expected=int(EPISODE_SLOTS) + 1)
    n_cross_action = 0
    n_cross_cue = 0
    if probe == "near_action":
        if stats["n_residents"] < 2 or stats["n_refresh"] > 0:
            n_cross_action = 1
    if probe == "cue_key":
        if stats["n_residents"] < 2 or stats["n_refresh"] > 0:
            n_cross_cue = 1
    if probe == "repeat" and (stats["n_residents"] < 2 or stats["n_refresh"] > 0):
        n_cross_cue = 1
    checkpoint_ok = True
    if probe == "checkpoint":
        snap = ag.checkpoint()
        twin = NeuralCortex(None, genome=copy.deepcopy(ag.genome), device=str(ag.device))
        twin.load_checkpoint(snap)
        restored = snapshot_rows(twin)
        flag_on = bool(getattr(twin, str(p["flag_attr"]), False))
        left = [(r["provenance_id"], r["key_hash"], r["value_hash"], r["when"]) for r in rows]
        right = [(r["provenance_id"], r["key_hash"], r["value_hash"], r["when"]) for r in restored]
        checkpoint_ok = bool(flag_on and left == right)
    passed = bool(
        n_cross_action == 0
        and n_cross_cue == 0
        and stats["n_attempted_ne_resident"] == 0
        and stats["n_unreported_loss"] == 0
        and checkpoint_ok
    )
    if probe == "capacity":
        passed = bool(passed and stats["n_evict"] >= 1 and stats["n_residents"] == int(EPISODE_SLOTS))
    if probe in ("near_action", "cue_key", "repeat"):
        passed = bool(passed and stats["n_residents"] == 2 and stats["n_append"] == 2)
    if probe == "checkpoint":
        passed = bool(passed and stats["n_residents"] == 3)
    code = "probe_ok" if passed else "probe_fail"
    out = {
        "kind": "scored",
        "id": f"{probe}|w{wi}",
        "probe": probe,
        "world": int(wi),
        "passed": bool(passed),
        "cell_code": code,
        "not_exercised": False,
        "n_cross_action_refresh": int(n_cross_action),
        "n_cross_cue_merge": int(n_cross_cue),
        "n_attempted_ne_resident": int(stats["n_attempted_ne_resident"]),
        "n_unreported_loss": int(stats["n_unreported_loss"]),
        "n_evict": int(stats["n_evict"]),
        "n_append": int(stats["n_append"]),
        "n_residents": int(stats["n_residents"]),
        "checkpoint_ok": bool(checkpoint_ok),
        "receipts": recs.rows,
        "candidate_v41_lock": False,
        "kqv_edited": False,
    }
    assert_finite_record(out, ctx=out["id"])
    return out


