def flag_report(ag: NeuralCortex) -> dict[str, Any]:
    p = load_prereg()
    genome = ag.genome.to_dict()
    setter = str(p["flag_setter"])
    attr = str(p["flag_attr"])
    method = str(p["write_method"])
    name = str(p["flag_name"])
    default_off = not bool(getattr(ag, attr, False))
    setter_present = hasattr(ag, setter)
    write_present = hasattr(ag, method)
    not_genome = name not in genome and attr not in genome and "opaque_store" not in genome
    not_mode = name not in ACT_RECALL_MODES and attr not in ACT_RECALL_MODES
    floor_ok = float(EPISODE_MATCH_L2) == 0.05
    enabled = False
    checkpoint_ok = False
    if setter_present:
        getattr(ag, setter)(True)
        enabled = bool(getattr(ag, attr, False))
        if enabled:
            snap = ag.checkpoint()
            ck_key = str(p["flag_checkpoint_key"])
            if ck_key in snap and bool(snap[ck_key]) is True:
                twin = NeuralCortex(None, genome=copy.deepcopy(ag.genome), device=str(ag.device))
                twin.load_checkpoint(snap)
                checkpoint_ok = bool(getattr(twin, attr, False)) is True
    return {
        "setter_present": bool(setter_present),
        "write_present": bool(write_present),
        "default_off": bool(default_off),
        "not_genome": bool(not_genome),
        "not_act_recall_mode": bool(not_mode),
        "floor_ok": bool(floor_ok),
        "enabled": bool(enabled),
        "checkpoint_ok": bool(checkpoint_ok),
        "passed": bool(
            setter_present
            and write_present
            and default_off
            and not_genome
            and not_mode
            and floor_ok
            and enabled
            and checkpoint_ok
        ),
    }


