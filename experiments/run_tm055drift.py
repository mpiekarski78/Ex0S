def last_per_handle(writes: list[dict[str, Any]], handles: list[str]) -> list[dict[str, Any]]:
    last: dict[str, dict[str, Any]] = {}
    for row in writes:
        last[str(row["handle"])] = row
    return [last[h] for h in handles]


def pairs_of(rows: list[dict[str, Any]]) -> list[tuple[str, np.ndarray]]:
    return [(str(r["handle"]), np.asarray(r["p1"], dtype=np.float64).copy()) for r in rows]


def live_trajectory(
    *,
    tmp: str,
    tag: str,
    wi: int,
    seed: int,
    domain: str,
    n_repeats: int,
    cues: list[str],
    tag_prefix: str,
    grounded: bool,
) -> dict[str, Any]:
    p46 = json.loads((REPO_ROOT / "docs" / "lineage_oneshot.prereg.lock").read_text(encoding="utf-8"))
    n_handles = int(p46["n_handles"])
    n_facts = int(p46["n_facts"])
    world = capacity_world(int(wi), str(domain), n_cues=int(n_facts), n_handles=int(n_handles))
    pairs = mapping_pairs(world, flip=False)
    handles = list(world["handles"])
    if len(cues) != len(handles):
        raise RuntimeError("cue/handle mismatch")
    test_cues = [str(c) for c, _h in pairs]
    if set(cues) & set(test_cues):
        raise RuntimeError("trajectory cues collided with test facts")
    ag = _fresh(tmp, tag, world, seed_registry=int(seed))
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.set_action_feedback_enabled(bool(grounded))
    writes: list[dict[str, Any]] = []
    idx = 0
    for rep in range(int(n_repeats)):
        for i, handle in enumerate(handles):
            ground_one(
                ag,
                world,
                handle,
                tag=f"{tag_prefix}_{rep}_{i}",
                symbols=[cues[i]],
            )
            writes.append(snapshot_write(ag, handle, cues[i], idx, int(rep)))
            idx += 1
    ag.rest_epoch(int(p46["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    prep_eval(ag)
    last_p1 = {str(r["handle"]): np.asarray(r["p1"], dtype=np.float64).copy() for r in last_per_handle(writes, handles)}
    handle_hits = []
    all_ok = True
    for handle in handles:
        p1 = last_p1.get(handle)
        if p1 is None:
            all_ok = False
            handle_hits.append({"handle": handle, "ok": False, "winner": None, "reason": "missing_write"})
            continue
        sc = score_direct(ag, p1)
        ok = sc["winner"] == handle
        all_ok = all_ok and bool(ok)
        handle_hits.append({"handle": handle, "ok": bool(ok), "winner": sc["winner"], "p1_hash": vec_hash(p1)})
    n_ep = len(ag._episodes)
    ag.opaque.clear()
    reset_before_recall(ag)
    snap = ag.checkpoint()
    return {
        "snap": snap,
        "genome": copy.deepcopy(ag.genome),
        "world": world,
        "pairs": pairs,
        "handles": handles,
        "cues": list(cues),
        "writes": writes,
        "last_p1": last_p1,
        "handle_hits": handle_hits,
        "all_ok": bool(all_ok),
        "n_dev_episodes": int(n_ep),
        "w_act_query_hash": w_act_hash(ag),
        "grounded": bool(grounded),
        "n_repeats": int(n_repeats),
        "seed": int(seed),
        "domain": str(domain),
    }


def reconstruct_pin(*, wi: int, tmp: str) -> dict[str, Any]:
    p = load_prereg()
    p46 = json.loads((REPO_ROOT / "docs" / "lineage_oneshot.prereg.lock").read_text(encoding="utf-8"))
    n_handles = int(p["n_handles"])
    cues = [f"s_dev_{wi}_{i}" for i in range(n_handles)]
    rec = live_trajectory(
        tmp=tmp,
        tag=f"dr_pin_w{wi}",
        wi=int(wi),
        seed=int(p["reconstruction_seed_registry"]),
        domain=str(p["reconstruction_domain"]),
        n_repeats=int(p["n_dev_repeats"]),
        cues=cues,
        tag_prefix=f"fg_feedback_grounded_w{wi}",
        grounded=True,
    )
    last = last_per_handle(rec["writes"], list(rec["handles"]))
    hashes = [str(r["p1_hash"]) for r in last]
    pinned = list(p["pinned_train_hashes"][f"w{wi}"])
    w0_pin = str(p["pinned_w0_hash"][f"w{wi}"])
    rec["pin_hashes"] = hashes
    rec["pin_match"] = hashes == pinned
    rec["w0_match"] = str(rec["w_act_query_hash"]) == w0_pin
    rec["live_match"] = all(bool(r["stored_matches_live_last_p1"]) for r in rec["writes"])
    rec["n_pin_repeats"] = int(p46["n_dev_repeats"])
    return rec


def collect_bundle(*, wi: int, tmp: str) -> dict[str, Any]:
    p = load_prereg()
    pin = reconstruct_pin(wi=int(wi), tmp=tmp)
    n_handles = int(p["n_handles"])
    ref_cues = [f"s_ref_{wi}_{i}" for i in range(n_handles)]
    on_cues = [f"s_on_{wi}_{i}" for i in range(n_handles)]
    ref = live_trajectory(
        tmp=tmp,
        tag=f"dr_ref_w{wi}",
        wi=int(wi),
        seed=int(p["seed_registry"]),
        domain=str(p["domains"]["DEV"]),
        n_repeats=int(p["n_dev_repeats"]),
        cues=ref_cues,
        tag_prefix=f"dr_ref_w{wi}",
        grounded=False,
    )
    online = live_trajectory(
        tmp=tmp,
        tag=f"dr_on_w{wi}",
        wi=int(wi),
        seed=int(p["seed_registry"]),
        domain=str(p["domains"]["DEV"]),
        n_repeats=int(p["n_online_repeats"]),
        cues=on_cues,
        tag_prefix=f"dr_on_w{wi}",
        grounded=True,
    )
    if list(ref["handles"]) != list(online["handles"]):
        raise RuntimeError("handle order drifted")
    handles = list(online["handles"])
    ag = load_common(online)
    freeze_plasticity(ag)
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.genome.act_recall_mode = ACT_RECALL_OFF
    w0_hash = w_act_hash(ag)
    if w0_hash != str(online["w_act_query_hash"]):
        raise RuntimeError("W_act_query moved after online trajectory")
    W0 = np.asarray(ag._from_t(ag.W_act_query), dtype=np.float64).copy()
    vocab = vocab_of(ag)
    ref_pairs = [(h, np.asarray(ref["last_p1"][h], dtype=np.float64).copy()) for h in handles]
    writes = list(online["writes"])
    n_writes = len(writes)
    if n_writes != int(p["n_online_repeats"]) * n_handles:
        raise RuntimeError("write count drifted")
    geom = action_geometry(pairs_of(writes))
    action_joint = []
    action_feasible = True
    for h in handles:
        rows = [r for r in writes if r["handle"] == h]
        rec, W_star = solve_ceiling(W0, list(ref_pairs) + pairs_of(rows), vocab)
        if w_act_hash(ag) != w0_hash:
            raise RuntimeError("W_act_query installed during action-joint SOCP")
        ok = bool(rec.get("feasible"))
        action_feasible = action_feasible and ok
        action_joint.append({"handle": h, "n_writes": len(rows), "feasible": ok, "status": rec.get("status")})
        del W_star
    full_rec, W_full = solve_ceiling(W0, list(ref_pairs) + pairs_of(writes), vocab)
    if w_act_hash(ag) != w0_hash:
        raise RuntimeError("W_act_query installed during full-tape SOCP")
    del W_full
    suffix_n = int(p["suffix_writes"])
    suffix_rows = writes[-suffix_n:]
    prefix_rows = writes[:-suffix_n]
    half = n_writes // 2
    suf_rec, W_suf = solve_ceiling(W0, list(ref_pairs) + pairs_of(suffix_rows), vocab)
    if w_act_hash(ag) != w0_hash:
        raise RuntimeError("W_act_query installed during suffix SOCP")
    if W_suf is None:
        suf_on_pre = score_eval(W0, pairs_of(prefix_rows), vocab)
        suf_on_first = score_eval(W0, pairs_of(writes[:suffix_n]), vocab)
        suf_self = score_eval(W0, pairs_of(suffix_rows), vocab)
    else:
        suf_on_pre = score_eval(W_suf, pairs_of(prefix_rows), vocab)
        suf_on_first = score_eval(W_suf, pairs_of(writes[:suffix_n]), vocab)
        suf_self = score_eval(W_suf, pairs_of(suffix_rows), vocab)
    del W_suf
    half_rec, W_half = solve_ceiling(W0, list(ref_pairs) + pairs_of(writes[:half]), vocab)
    if w_act_hash(ag) != w0_hash:
        raise RuntimeError("W_act_query installed during half SOCP")
    if W_half is None:
        half_on_late = score_eval(W0, pairs_of(writes[half:]), vocab)
        half_self = score_eval(W0, pairs_of(writes[:half]), vocab)
    else:
        half_on_late = score_eval(W_half, pairs_of(writes[half:]), vocab)
        half_self = score_eval(W_half, pairs_of(writes[:half]), vocab)
    del W_half
    if w_act_hash(ag) != w0_hash:
        raise RuntimeError("W_act_query moved after diagnostic SOCP")
    unique_v = sorted({str(r["p1_hash"]) for r in writes})
    unique_k = sorted({str(r["key_hash"]) for r in writes if r.get("key_hash")})
    decoder = {
        "kind": "setup",
        "id": f"decoder|w{wi}",
        "arm": "decoder",
        "world": int(wi),
        "passed": bool(pin["pin_match"] and pin["w0_match"] and pin["live_match"] and ref["all_ok"]),
        "excluded_from_behavioral_first_match": True,
        "cell_code": "decoder_ok" if pin["pin_match"] and pin["w0_match"] and pin["live_match"] and ref["all_ok"] else "decoder_fail",
        "pin_match": bool(pin["pin_match"]),
        "w0_match": bool(pin["w0_match"]),
        "live_match": bool(pin["live_match"]),
        "ref_ok": bool(ref["all_ok"]),
        "ref_n_ok": int(sum(1 for h in ref["handle_hits"] if h["ok"])),
        "ref_n_need": int(n_handles),
        "n_online_writes": int(n_writes),
        "n_unique_v": len(unique_v),
        "n_unique_k": len(unique_k),
        "geometry": geom,
        "action_joint": action_joint,
        "action_joint_feasible": bool(action_feasible),
        "full_tape_feasible": bool(full_rec.get("feasible")),
        "suffix_feasible": bool(suf_rec.get("feasible")),
        "suffix_self": suf_self,
        "suffix_on_prefix": suf_on_pre,
        "suffix_on_first": suf_on_first,
        "half_feasible": bool(half_rec.get("feasible")),
        "half_self": half_self,
        "half_on_late": half_on_late,
        "writes": [write_brief(r) for r in writes],
        "pin_hashes": list(pin["pin_hashes"]),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "W_installed": False,
        "applied": False,
    }
    assert_finite_record(decoder, ctx=decoder["id"])
    return {
        "pin": pin,
        "ref": ref,
        "online": online,
        "handles": handles,
        "W0": W0,
        "w0_hash": w0_hash,
        "vocab": vocab,
        "ref_pairs": ref_pairs,
        "writes": writes,
        "decoder": decoder,
        "ag": ag,
        "wi": int(wi),
    }


def eval_n(bundle: dict[str, Any], *, n: int) -> dict[str, Any]:
    p = load_prereg()
    n_handles = int(p["n_handles"])
    writes = list(bundle["writes"])
    if n >= len(writes):
        raise RuntimeError("N must be a strict prefix")
    train_rows = writes[:n]
    future_rows = writes[n:]
    next_rows = writes[n : n + n_handles]
    cons = list(bundle["ref_pairs"]) + pairs_of(train_rows)
    parent_h = str(bundle["w0_hash"])
    rec, W_star = solve_ceiling(bundle["W0"], cons, bundle["vocab"])
    if w_act_hash(bundle["ag"]) != parent_h:
        raise RuntimeError("W_act_query installed or moved")
    W_use = bundle["W0"] if W_star is None else W_star
    train_sc = score_eval(W_use, pairs_of(train_rows), bundle["vocab"])
    future_sc = score_eval(W_use, pairs_of(future_rows), bundle["vocab"])
    next_sc = score_eval(W_use, pairs_of(next_rows), bundle["vocab"])
    ref_sc = score_eval(W_use, list(bundle["ref_pairs"]), bundle["vocab"])
    if w_act_hash(bundle["ag"]) != parent_h:
        raise RuntimeError("W_act_query moved after W_star scoring")
    del W_star
    feasible = bool(rec.get("feasible"))
    train_ok = bool(train_sc["n_ok"] == train_sc["n_need"])
    ref_ok = bool(ref_sc["n_ok"] == ref_sc["n_need"])
    future_ok = bool(future_sc["n_ok"] == future_sc["n_need"])
    next_ok = bool(next_sc["n_ok"] == next_sc["n_need"])
    if not feasible:
        code = "n_infeasible"
    elif not ref_ok:
        code = "n_ref_break"
    elif train_ok and future_ok:
        code = "n_generalizes"
    elif train_ok and next_ok:
        code = "n_next_only"
    elif train_ok:
        code = "n_prefix_only"
    else:
        code = "n_prefix_fail"
    out = {
        "kind": "scored",
        "id": f"n{n}|w{bundle['wi']}",
        "arm": f"n{n}",
        "n": int(n),
        "n_is_organism_constant": False,
        "world": int(bundle["wi"]),
        "passed": bool(feasible and ref_ok and train_ok),
        "cell_code": code,
        "feasible": bool(feasible),
        "solver_status": rec.get("status"),
        "reject_reason": rec.get("reject_reason"),
        "n_constraints": rec.get("n_constraints"),
        "min_slack": rec.get("min_slack"),
        "frobenius_delta": rec.get("frobenius_delta"),
        "w0_hash": parent_h,
        "w_star_hash": rec.get("w_star_hash"),
        "applied": False,
        "W_installed": False,
        "discarded": True,
        "train": train_sc,
        "future": future_sc,
        "next_cycle": next_sc,
        "reference": ref_sc,
        "train_ok": bool(train_ok),
        "future_ok": bool(future_ok),
        "next_ok": bool(next_ok),
        "ref_ok": bool(ref_ok),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
        "socp_extended": False,
        "regenerated_wraps": False,
    }
    assert_finite_record(out, ctx=out["id"])
    return out


def synthetic_grid(*, decoder_ok: bool = True, code: str = "grounding_consolidation_plausible") -> list[dict[str, Any]]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    n_worlds = int(p["n_worlds"])
    cells: list[dict[str, Any]] = []
    cluster_ok = code not in ("incompatible_action_clusters", "setup_precondition_fail")
    suffix_on_prefix_ok = code not in (
        "catastrophic_representational_migration",
        "setup_precondition_fail",
    )
    half_on_late_ok = code in ("grounding_consolidation_plausible", "write_must_be_included")
    next_ok_any = code in ("developmental_coordinate_drift", "grounding_consolidation_plausible")
    future_ok_any = code == "grounding_consolidation_plausible"
    prefix4_ok = code not in ("prefix_infeasible", "setup_precondition_fail")
    for wi in range(n_worlds):
        cells.append(
            {
                "id": f"decoder|w{wi}",
                "arm": "decoder",
                "kind": "setup",
                "passed": bool(decoder_ok),
                "excluded_from_behavioral_first_match": True,
                "action_joint_feasible": bool(cluster_ok),
                "suffix_on_prefix": {"n_ok": 24 if suffix_on_prefix_ok else 0, "n_need": 24},
                "half_on_late": {"n_ok": 16 if half_on_late_ok else 0, "n_need": 16},
                "half_self": {"n_ok": 16, "n_need": 16},
                "suffix_self": {"n_ok": 8, "n_need": 8},
            }
        )
    for n in n_grid:
        for wi in range(n_worlds):
            feasible = prefix4_ok or n != 4
            if code == "prefix_infeasible":
                feasible = False
            train_ok = bool(feasible)
            ref_ok = True
            next_ok = bool(next_ok_any and feasible)
            future_ok = bool(future_ok_any and feasible)
            if code == "write_must_be_included":
                next_ok = False
                future_ok = False
            if code == "developmental_coordinate_drift":
                future_ok = False
                next_ok = True
            if not feasible:
                cc = "n_infeasible"
            elif future_ok:
                cc = "n_generalizes"
            elif next_ok:
                cc = "n_next_only"
            elif train_ok:
                cc = "n_prefix_only"
            else:
                cc = "n_prefix_fail"
            cells.append(
                {
                    "id": f"n{n}|w{wi}",
                    "arm": f"n{n}",
                    "kind": "scored",
                    "n": int(n),
                    "passed": bool(feasible and ref_ok and train_ok),
                    "cell_code": cc,
                    "feasible": bool(feasible),
                    "train": {"n_ok": n if train_ok else 0, "n_need": n},
                    "future": {"n_ok": (32 - n) if future_ok else 0, "n_need": 32 - n},
                    "next_cycle": {"n_ok": 4 if next_ok else 0, "n_need": 4},
                    "reference": {"n_ok": 4 if ref_ok else 0, "n_need": 4},
                    "future_ok": bool(future_ok),
                    "next_ok": bool(next_ok),
                    "train_ok": bool(train_ok),
                    "ref_ok": bool(ref_ok),
                }
            )
    return cells


def _perfect(rec: dict[str, Any] | None) -> bool:
    if not rec:
        return False
    need = int(rec.get("n_need") or 0)
    return need > 0 and int(rec.get("n_ok") or 0) == need


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    n_worlds = int(p["n_worlds"])
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
        "install_W_star": False,
        "socp_extended": False,
        "n_dev_repeats_increased": False,
        "n_fitted_as_organism_constant": False,
        "episode_match_l2_retuned": False,
        "force_cue_into_value": False,
        "frozen_wrap_used_as_canonical": False,
        "regenerated_historical_values": False,
        "setup_excluded_from_behavioral_first_match": True,
        "discard_every_W_star": True,
        "learned_Wv_earned": False,
        "reconsolidation_required": False,
        "generic_consolidation_plausible": False,
    }
    for wi in range(n_worlds):
        dec = by.get(f"decoder|w{wi}")
        if dec is None or not bool(dec.get("passed")):
            return "setup_precondition_fail", "setup_precondition_fail", flags

    def scored(n: int) -> list[dict[str, Any]]:
        return [by[f"n{n}|w{wi}"] for wi in range(n_worlds)]

    n4 = scored(4)
    if any(not bool(c.get("feasible")) for c in n4):
        return "prefix_infeasible", "prefix_infeasible", flags
    if any(not bool(by[f"decoder|w{wi}"].get("action_joint_feasible")) for wi in range(n_worlds)):
        flags["learned_Wv_earned"] = False
        return "incompatible_action_clusters", "incompatible_action_clusters", flags
    if any(not _perfect(by[f"decoder|w{wi}"].get("suffix_on_prefix")) for wi in range(n_worlds)):
        flags["reconsolidation_required"] = True
        return "catastrophic_representational_migration", "catastrophic_representational_migration", flags
    any_future = any(bool(c.get("future_ok")) for n in n_grid for c in scored(n))
    any_next = any(bool(c.get("next_ok")) for n in n_grid for c in scored(n))
    both_future = all(any(bool(c.get("future_ok")) for c in scored(n)) for n in n_grid[-1:])
    # both worlds: some N with future_ok
    worlds_future = [
        any(bool(by[f"n{n}|w{wi}"].get("future_ok")) for n in n_grid) for wi in range(n_worlds)
    ]
    if all(worlds_future):
        flags["generic_consolidation_plausible"] = True
        return "grounding_consolidation_plausible", "grounding_consolidation_plausible", flags
    if not any_next:
        return "write_must_be_included", "write_must_be_included", flags
    return "developmental_coordinate_drift", "developmental_coordinate_drift", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "_run_joint_socp_consolidation", "credit_tagged", "collect_wraps"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in (
                    "_last_p1",
                    "_last_key_rho",
                    "W_k",
                    "W_q",
                    "W_v",
                    "W_act_query",
                    "_episodes",
                ):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


