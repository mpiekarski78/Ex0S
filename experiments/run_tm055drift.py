def expected_cell_ids() -> list[str]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"n{n}|w{wi}" for n in n_grid for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "n_grid": n_grid,
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM055 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM055 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS or len(setup) != N_SETUP_CELLS or len(scored) != N_SCORED_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def snapshot_write(ag: NeuralCortex, handle: str, cue: str, index: int, rep: int) -> dict[str, Any]:
    ep = latest_episode(ag, handle)
    if ep is None:
        raise RuntimeError(f"missing write-time episode for {handle} at {index}")
    p1 = np.asarray(ep["p1"], dtype=np.float64).copy()
    key = None if ep.get("key_rho") is None else np.asarray(ep["key_rho"], dtype=np.float64).copy()
    live = None if ag._last_p1 is None else np.asarray(ag._last_p1, dtype=np.float64).copy()
    return {
        "index": int(index),
        "rep": int(rep),
        "handle": str(handle),
        "cue": str(cue),
        "p1": p1,
        "key_rho": key,
        "p1_hash": vec_hash(p1),
        "key_hash": None if key is None else vec_hash(key),
        "stored_matches_live_last_p1": bool(live is not None and vec_hash(live) == vec_hash(p1)),
    }


