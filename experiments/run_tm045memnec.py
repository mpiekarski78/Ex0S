def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [
        f"{cond}|c{n}|{arm}|w{wi}"
        for n in list(p["n_cues_grid"])
        for cond in list(p["conditions"])
        for arm in list(p["arms"])
        for wi in range(int(p["n_worlds"]))
    ]
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
        "conditions": list(p["conditions"]),
        "n_cues_grid": list(p["n_cues_grid"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM045 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM045 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def reset_before_recall(ag: NeuralCortex) -> None:
    ag.reset_rho()
    ag._last_p1 = None
    ag.drop_actor_pending()


def _fresh(tmp: str, tag: str, world: dict[str, Any], *, seed_registry: int) -> NeuralCortex:
    ag = make_cortex(Path(tmp) / tag, genome=genome_for_registry(seed_registry), device="cpu")
    ag.genome.episodic_act_recall = False
    ag.genome.act_score_mode = ACT_SCORE_QUERY
    ag.bind_actuators(list(world["handles"]))
    ag.set_act_socp_arm("off")
    return ag


def _configure(ag: NeuralCortex, arm: str) -> None:
    if arm == "symbolic_oracle":
        ag.genome.act_recall_mode = ACT_RECALL_RAW_P1
        ag.set_memproj_arm(MEMPROJ_OFF)
    elif arm == "learned_projection":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_LEARNED)
    elif arm == "no_persistent_memory":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_NONE)
    else:
        raise RuntimeError(arm)


def _teach(ag: NeuralCortex, world: dict[str, Any], pairs: list[tuple[str, str]], *, tag: str) -> None:
    for i, (cue, handle) in enumerate(pairs):
        teach_one(ag, world, handle, tag=f"{tag}_{i}", symbols=[cue])


def _other_handle(pairs: list[tuple[str, str]], handle: str) -> str:
    seen: list[str] = []
    for _cue, h in pairs:
        if h not in seen:
            seen.append(h)
    for h in seen:
        if h != handle:
            return h
    return handle


def _brief_meta(meta: dict[str, Any]) -> dict[str, Any]:
    return {
        "memory_path": meta.get("memory_path"),
        "motor_path": meta.get("motor_path"),
        "scoring_address_source": meta.get("scoring_address_source"),
        "retrieved": meta.get("retrieved"),
        "reject_reason": meta.get("reject_reason"),
        "slot": meta.get("slot"),
        "familiar": meta.get("familiar"),
        "scores_before_reinstatement": meta.get("scores_before_reinstatement"),
        "scores_after_reinstatement": meta.get("scores_after_reinstatement"),
    }


def organism_probe(
    ag: NeuralCortex,
    world: dict[str, Any],
    cue: str,
    *,
    tag: str,
    cond: str,
    n_delay: int,
    distractor: str | None,
) -> dict[str, Any]:
    probe = clone_frozen(ag)
    reset_before_recall(probe)
    if cond == "delayed":
        for i in range(int(n_delay)):
            empty_tick(probe, tag=f"{tag}_d{i}")
    elif cond == "distractor" and distractor is not None:
        observe_cue(probe, world, tag=f"{tag}_dist", body=list(MID_BODY), symbols=[distractor])
        probe.drop_actor_pending()
    observe_cue(probe, world, tag=tag, body=list(MID_BODY), symbols=[cue])
    scores, addr, meta = probe.event_memory_scores()
    winner = unique_winner(scores)
    return {
        "winner": winner,
        "scores": {k: float(v) for k, v in scores.items()},
        "addr_hash": hashlib.sha256(np.ascontiguousarray(addr).tobytes()).hexdigest(),
        "telemetry": _brief_meta(meta),
    }


def eval_cell(
    *,
    cond: str,
    n_cues: int,
    arm: str,
    wi: int,
    seed_registry: int,
    tmp: str,
    n_delay: int,
) -> dict[str, Any]:
    cell_id = f"{cond}|c{n_cues}|{arm}|w{wi}"
    world = capacity_world(wi, DEV_DOMAIN, n_cues=int(n_cues), n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    ag = _fresh(tmp, cell_id, world, seed_registry=seed_registry)
    _configure(ag, arm)
    _teach(ag, world, pairs, tag=cell_id)
    want_pairs = list(pairs)
    if cond == "revision":
        cue0, h0 = pairs[0]
        h1 = _other_handle(pairs, h0)
        teach_one(ag, world, h1, tag=f"{cell_id}_rev", symbols=[cue0])
        want_pairs = [(cue0, h1)]
    dist = "s_dist_" + hashlib.sha256(cell_id.encode()).hexdigest()[:8]
    hits = []
    probe_cond = "immediate" if cond == "revision" else cond
    for i, (cue, handle) in enumerate(want_pairs):
        rec = organism_probe(
            ag,
            world,
            cue,
            tag=f"{cell_id}_p{i}",
            cond=probe_cond,
            n_delay=n_delay,
            distractor=dist if cond == "distractor" else None,
        )
        rec["want"] = handle
        rec["ok"] = rec["winner"] == handle
        hits.append(rec)
    n_ok = sum(1 for h in hits if h["ok"])
    passed = n_ok == len(want_pairs)
    out = {
        "kind": cond,
        "id": cell_id,
        "arm": arm,
        "n_cues": int(n_cues),
        "world": int(wi),
        "passed": bool(passed),
        "n_ok": int(n_ok),
        "n_need": len(want_pairs),
        "n_opaque": len(ag.opaque.rows()),
        "n_episodes": len(ag._episodes),
        "reset_rho_before_recall": True,
        "probes": hits,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "cell_code": f"{cond}_ok" if passed else f"{cond}_fail",
    }
    assert_finite_record(out, ctx=cell_id)
    return out


def synthetic_grid(*, oracle_c2_ok: bool = True, none_fail_id: str | None = None) -> list[dict[str, Any]]:
    cells: list[dict[str, Any]] = []
    for n in SCALES:
        for cond in CONDS:
            for arm in ARMS:
                for wi in (0, 1):
                    cid = f"{cond}|c{n}|{arm}|w{wi}"
                    passed = True
                    if arm == "symbolic_oracle" and n == 2 and cond == "immediate" and not oracle_c2_ok:
                        passed = False
                    if none_fail_id is not None and cid == none_fail_id:
                        passed = False
                    cells.append({"id": cid, "arm": arm, "kind": cond, "passed": passed})
    return cells


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "learned_arm_is_observational": True,
        "necessary_cell": None,
        "separate_candidate_review_open": False,
    }
    setup_ids = [f"immediate|c2|symbolic_oracle|w{wi}" for wi in (0, 1)]
    if any(sid not in by or not bool(by[sid].get("passed")) for sid in setup_ids):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    p = load_prereg()
    for n in list(p["n_cues_grid"]):
        for cond in list(p["conditions"]):
            for wi in range(int(p["n_worlds"])):
                oid = f"{cond}|c{n}|symbolic_oracle|w{wi}"
                nid = f"{cond}|c{n}|no_persistent_memory|w{wi}"
                o = by.get(oid)
                none = by.get(nid)
                if o is None or none is None:
                    return "setup_precondition_fail", "setup_precondition_fail", flags
                if bool(o.get("passed")) and not bool(none.get("passed")):
                    flags["necessary_cell"] = nid
                    flags["necessary_oracle_cell"] = oid
                    flags["n_cues"] = int(n)
                    flags["condition"] = str(cond)
                    flags["world"] = int(wi)
                    return "memory_necessary_at", "memory_necessary_at", flags
    return "memory_never_necessary", "memory_never_necessary", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "rest_epoch", "canonical_cue_probe"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM045 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py drifted; TM045 does not tune K/Q/V")
    if sha_file(TM044_RUNNER) != p["tm044_runner_sha"]:
        raise RuntimeError("TM044 runner must stay frozen")
    if hashlib.sha256(TM044_DEV.read_bytes()).hexdigest() != p["tm044_dev_sha"]:
        raise RuntimeError("TM044 DEV lock must stay frozen")
    if hashlib.sha256(TM044_DEC.read_bytes()).hexdigest() != p["tm044_decision_sha"]:
        raise RuntimeError("TM044 decision lock must stay frozen")
    if hashlib.sha256(TM044_ADD.read_bytes()).hexdigest() != p["tm044_addendum_sha"]:
        raise RuntimeError("TM044 addendum lock must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("kqv_edit_authorized")):
        raise RuntimeError("TM045 must not authorize K/Q/V edits")
    seed = int(p["seed_registry"])
    if seed in [int(x) for x in p["forbidden_seeds"]]:
        raise RuntimeError("seed collision")
    if "memproj_arm" in GenomeConfig().to_dict():
        raise RuntimeError("memproj must not be a GenomeConfig field")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="mn_dev_")
    try:
        t = tmp.name
        n_delay = int(p["n_delay_ticks"])
        for n in list(p["n_cues_grid"]):
            for cond in list(p["conditions"]):
                for arm in list(p["arms"]):
                    for wi in range(int(p["n_worlds"])):
                        cells.append(
                            eval_cell(
                                cond=str(cond),
                                n_cues=int(n),
                                arm=str(arm),
                                wi=int(wi),
                                seed_registry=seed,
                                tmp=t,
                                n_delay=n_delay,
                            )
                        )
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    flags["kqv_edited"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "learned_arm_is_observational": True,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "solver_edited": False,
        "tm044_runner_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.45.MEMNEC.DECISION",
        "product": "0.0.004",
        "earned_next": False,
        "eligible_for_000005": False,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "note": "TM045 memory-necessity wall. Product remains 0.0.004. No K/Q/V tuning. No cortex.candidate.v41.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


def write_results_md(out: dict[str, Any]) -> None:
    flags = out.get("phase_flags") or {}
    lines = [
        "# TM.0.45.MEMNEC results",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        f"Necessary cell: `{flags.get('necessary_cell')}`.",
        "",
        "Product **0.0.004**. No v41 candidate lock. K/Q/V not tuned.",
        "",
        f"Cells: {out['n_cells']}. Learned arm is observational.",
        "",
    ]
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def smoke() -> dict[str, Any]:
    ids = expected_cell_ids()
    leak = refuse_runner_leaks(THIS)
    code_setup, _, _ = _decision(synthetic_grid(oracle_c2_ok=False))
    code_need, _, flags_need = _decision(
        synthetic_grid(none_fail_id="immediate|c2|no_persistent_memory|w0")
    )
    code_never, _, _ = _decision(synthetic_grid())
    return {
        "smoke_ok": True,
        "n_cells": len(ids),
        "retrieve_leak": leak,
        "ladder_setup": code_setup,
        "ladder_necessary": code_need,
        "ladder_never": code_never,
        "necessary_cell": flags_need.get("necessary_cell"),
        "candidate_exists": CANDIDATE.exists(),
        "kqv_edit_authorized": False,
        "memproj_in_genome": "memproj_arm" in GenomeConfig().to_dict(),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "necessary_cell": (out.get("phase_flags") or {}).get("necessary_cell"),
                    "n_cells": out["n_cells"],
                    "candidate_v41_lock": False,
                    "kqv_edited": False,
                },
                indent=2,
            )
        )
        return
    ap.print_help()


if __name__ == "__main__":
    main()
