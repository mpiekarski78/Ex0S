def _pattern_flags(cells: list[dict[str, Any]]) -> dict[str, bool]:
    by = {c["id"]: c for c in cells}

    def cue(wi: int) -> dict[str, Any]:
        return by[f"cue|w{wi}"]

    def neu(wi: int) -> dict[str, Any]:
        return by[f"neutral|w{wi}"]

    collapse = any(str(cue(wi).get("cell_code")) == "collapse_before_recurrence" for wi in (0, 1))
    tanh_c = any(str(cue(wi).get("cell_code")) == "input_separates_tanh_compresses" for wi in (0, 1))
    later = False
    never_decode_sep = False
    for wi in (0, 1):
        ticks = cue(wi).get("ticks") or {}
        if not ticks:
            later = later or str(cue(wi).get("cell_code")) == "later_ticks_decode"
            never_decode_sep = never_decode_sep or str(cue(wi).get("cell_code")) == "states_separate_never_decode"
            continue
        d1 = bool((ticks.get("1") or {}).get("decode_4_of_4"))
        later = later or ((not d1) and any(bool((ticks.get(str(t)) or {}).get("decode_4_of_4")) for t in (2, 4, 8, 16)))
        any_sep = False
        any_dec = False
        for t in TICKS:
            row = ticks.get(str(t)) or {}
            stages = row.get("stages") or {}
            any_sep = any_sep or bool((stages.get("rho_t") or {}).get("separable")) or bool(
                (stages.get("p1") or {}).get("separable")
            )
            any_dec = any_dec or bool(row.get("decode_4_of_4"))
        never_decode_sep = never_decode_sep or (any_sep and not any_dec)
        if not any_sep and not any_dec:
            never_decode_sep = never_decode_sep or str(cue(wi).get("cell_code")) == "states_separate_never_decode"
    neu_pass_cue_fail = False
    for wi in (0, 1):
        ct = cue(wi).get("ticks") or {}
        nt = neu(wi).get("ticks") or {}
        cue_any = any(bool((ct.get(str(t)) or {}).get("decode_4_of_4")) for t in TICKS) if ct else False
        neu_any = any(bool((nt.get(str(t)) or {}).get("decode_4_of_4")) for t in TICKS) if nt else bool(
            str(neu(wi).get("cell_code")) == "neutral_decode"
        )
        if not ct:
            cue_any = str(cue(wi).get("cell_code")) in ("later_ticks_decode",)
        neu_pass_cue_fail = neu_pass_cue_fail or (neu_any and not cue_any)
    return {
        "collapse_before_recurrence": bool(collapse),
        "input_separates_tanh_compresses": bool(tanh_c),
        "later_ticks_decode": bool(later),
        "neutral_passes_cue_fails": bool(neu_pass_cue_fail),
        "states_separate_never_decode": bool(never_decode_sep),
    }


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "earned_kqv": False,
        "earned_learned_addressing": False,
        "tick_count_fitted": False,
        "episodic_loop_complete": False,
        "separate_candidate_review_open": False,
        "setup_excluded_from_behavioral_first_match": True,
    }
    if any(f"decoder|w{wi}" not in by or not bool(by[f"decoder|w{wi}"].get("passed")) for wi in (0, 1)):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    pf = _pattern_flags(cells)
    flags.update(pf)
    for step in BEHAVIORAL_LADDER:
        if step == "geometry_unresolved":
            continue
        if bool(pf.get(step)):
            return step, step, flags
    return "geometry_unresolved", "geometry_unresolved", flags


