def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "candidate_v41_lock": False,
                    "kqv_edited": False,
                    "tick_count_fitted": False,
                    "phase_flags": {
                        k: out["phase_flags"].get(k)
                        for k in (
                            "collapse_before_recurrence",
                            "input_separates_tanh_compresses",
                            "later_ticks_decode",
                            "neutral_passes_cue_fails",
                            "states_separate_never_decode",
                        )
                    },
                },
                indent=2,
                default=_json_default,
            )
        )
        return
    raise SystemExit("use --smoke or --dev")


if __name__ == "__main__":
    main()
