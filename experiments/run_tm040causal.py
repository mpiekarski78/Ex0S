def eval_contradict(
    world: dict[str, Any],
    *,
    arm: str,
    tag: str,
    cell_id: str,
    seed_registry: int,
    tmp: str,
    wi: int,
) -> dict[str, Any]:
    pairs = mapping_pairs(world, flip=False)
    ag = _fresh(tmp, tag, world, seed_registry=seed_registry)
    set_arm(ag, arm)
    slog = bind_socp_logger(ag)
    teach_pairs(ag, world, pairs, tag=tag)
    w_before = ag._from_t(ag.W_act_query).copy()
    h_before = weight_hash(w_before)
    bytes_before = np.ascontiguousarray(w_before).tobytes()
    h1, h2 = world["handles"][0], world["handles"][1]
    x0 = np.asarray(ag._episodes[0]["p1"], dtype=np.float64).reshape(-1)
    rng = np.random.default_rng(int(wi) + 17)
    far = rng.normal(size=x0.shape)
    far = far / (float(np.linalg.norm(far)) + 1e-12)
    if float(np.linalg.norm(far - x0)) <= 0.05 + 1e-12:
        far = -far
    other = h2 if str(ag._episodes[0]["handle"]) == str(h1) else h1
    ag._episodes.append(
        {
            "p1": far.copy(),
            "handle": str(other),
            "adv": 1.0,
            "age": int(ag._episode_clock) + 1,
            "version": 1,
            "valid": True,
            "key": None,
            "key_rho": None,
        }
    )
    rec = ag._run_joint_socp_consolidation() if arm != "v37" else {"status": "skipped_v37", "applied": False}
    w_after = ag._from_t(ag.W_act_query)
    bytes_after = np.ascontiguousarray(w_after).tobytes()
    identical = bytes_before == bytes_after
    rejected = str(rec.get("status") or "") not in ("optimal",) or not bool(rec.get("applied"))
    if arm == "v37":
        passed = True
        note = "v37_control_no_socp"
    elif rejected:
        passed = bool(identical)
        note = "reject_requires_byte_identical_W"
    else:
        passed = bool(int(ag._count_store_violations()) == 0)
        note = "jointly_feasible_not_a_reject_law_fail"
    out = {
        **_base_cell("contradict", cell_id, arm, None, wi),
        "passed": passed,
        "behavioral_pass": passed,
        "w_byte_identical": bool(identical),
        "w_hash_before": h_before,
        "w_hash_after": weight_hash(w_after),
        "injected_coexisting_opposite_episode": True,
        "reject_or_skip": bool(rejected),
        "contradict_note": note,
        "socp": {
            "status": rec.get("status"),
            "applied": rec.get("applied"),
            "reject_reason": rec.get("reject_reason"),
            "solver_status": rec.get("solver_status"),
        },
        **socp_summary(slog),
    }
    assert_finite_record(out, ctx=cell_id)
    return out


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    fb = [c for c in cells if c["arm"] == "fallback_joint"]
    v37 = [c for c in cells if c["arm"] == "v37"]
    aj = [c for c in cells if c["arm"] == "always_joint"]

    def kind(name: str, rows: list[dict[str, Any]] | None = None) -> list[dict[str, Any]]:
        src = fb if rows is None else rows
        return [c for c in src if c["kind"] == name]

    def all_pass(rows: list[dict[str, Any]]) -> bool:
        return bool(rows) and all(bool(c["passed"]) for c in rows)

    untouched = [c for c in fb if c["kind"] != "contradict"]
    n_activated = sum(1 for c in untouched if bool(c.get("socp_activated")))
    n_installed = sum(1 for c in untouched if bool(c.get("socp_installed")))
    rescues: list[str] = []
    by_stem: dict[str, dict[str, dict[str, Any]]] = {}
    for c in cells:
        if c["kind"] == "contradict":
            continue
        by_stem.setdefault(c["stem"], {})[c["arm"]] = c
    for stem, arms in by_stem.items():
        a = arms.get("v37")
        b = arms.get("fallback_joint")
        if a is not None and b is not None and (not a["passed"]) and b["passed"]:
            rescues.append(stem)

    later_fb = kind("later")
    later_after = [c for c in later_fb if bool(c.get("socp_installed_before_later_probes"))]
    flags = {
        "n_cells": len(cells),
        "fallback_acquire": all_pass(kind("acquire")),
        "fallback_stable": all_pass(kind("stable")),
        "fallback_hist": all_pass(kind("hist")),
        "fallback_novel": all_pass(kind("novel")),
        "fallback_eco": all_pass(kind("eco")),
        "fallback_spec": all_pass(kind("spec")),
        "fallback_scale": all_pass(kind("scale")),
        "fallback_later": all_pass(kind("later")),
        "fallback_contradict": all_pass(kind("contradict")),
        "n_untouched_fallback_cells": len(untouched),
        "n_untouched_socp_activated": int(n_activated),
        "n_untouched_socp_installed": int(n_installed),
        "n_causal_rescues": len(rescues),
        "causal_rescue_stems": list(rescues),
        "n_later_after_socp": len(later_after),
        "candidate_v40_lock": False,
        "always_joint_observational": True,
    }
    fb_pass = all(bool(c["passed"]) for c in fb)
    aj_pass = all(bool(c["passed"]) for c in aj if c["kind"] != "contradict")
    fb_move = float(sum(float(c.get("total_frobenius_applied") or 0.0) for c in fb))
    aj_move = float(sum(float(c.get("total_frobenius_applied") or 0.0) for c in aj))
    fb_runs = int(sum(int(c.get("n_socp_calls") or 0) for c in fb))
    aj_runs = int(sum(int(c.get("n_socp_calls") or 0) for c in aj))
    if fb_pass and aj_pass and (fb_move < aj_move or fb_runs < aj_runs):
        flags["always_joint_read"] = "scheduling_efficiency"
    elif fb_pass and not aj_pass:
        flags["always_joint_read"] = "scheduling_behaviorally_causal"
    elif (not fb_pass) and (not aj_pass):
        flags["always_joint_read"] = "optimizer_does_not_generalize"
    else:
        flags["always_joint_read"] = "observational_other"
    flags["fallback_total_frobenius"] = fb_move
    flags["always_total_frobenius"] = aj_move
    flags["fallback_n_socp_calls"] = fb_runs
    flags["always_n_socp_calls"] = aj_runs

    ladder = [
        ("jointsocp_fallback_acquire_fail", flags["fallback_acquire"]),
        ("jointsocp_fallback_stability_fail", flags["fallback_stable"]),
        ("jointsocp_fallback_history_fail", flags["fallback_hist"]),
        ("jointsocp_fallback_novelty_fail", flags["fallback_novel"]),
        ("jointsocp_fallback_reversal_fail", flags["fallback_eco"]),
        ("jointsocp_fallback_specificity_fail", flags["fallback_spec"]),
        ("jointsocp_fallback_scale_fail", flags["fallback_scale"]),
        ("jointsocp_fallback_contradict_fail", flags["fallback_contradict"]),
        ("jointsocp_fallback_later_learning_fail", flags["fallback_later"]),
    ]
    for code, ok in ladder:
        if not ok:
            return code, code, flags
    if n_activated == 0:
        return "jointsocp_generalization_not_exercised", "jointsocp_generalization_not_exercised", flags
    if len(later_after) == 0:
        return "jointsocp_later_learning_not_exercised", "jointsocp_later_learning_not_exercised", flags
    return "jointsocp_fallback_battery_pass", "jointsocp_fallback_battery_pass", flags


