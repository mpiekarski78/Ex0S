def bind_socp_logger(ag: NeuralCortex) -> list[dict[str, Any]]:
    log: list[dict[str, Any]] = []
    orig = ag._run_joint_socp_consolidation

    def wrapped() -> dict[str, Any]:
        w_before = weight_hash(ag._from_t(ag.W_act_query))
        n_cons = len(ag._socp_constraints())
        rec = orig()
        row = {k: rec.get(k) for k in SOCP_LOG_KEYS if k in rec or k in ("w_hash_before", "n_constraints_before")}
        row["w_hash_before"] = w_before
        row["n_constraints_before"] = int(n_cons)
        row["n_constraints_after"] = len(ag._socp_constraints())
        row["w_hash_after"] = weight_hash(ag._from_t(ag.W_act_query))
        row["applied"] = bool(rec.get("applied"))
        row["status"] = rec.get("status")
        row["reject_reason"] = rec.get("reject_reason")
        log.append(row)
        return rec

    ag._run_joint_socp_consolidation = wrapped  # type: ignore[method-assign]
    return log


def socp_summary(log: list[dict[str, Any]]) -> dict[str, Any]:
    applied = [r for r in log if bool(r.get("applied"))]
    return {
        "n_socp_calls": len(log),
        "n_socp_applied": len(applied),
        "n_socp_rejected": sum(1 for r in log if not bool(r.get("applied"))),
        "socp_activated": bool(log),
        "socp_installed": bool(applied),
        "calls": log,
        "total_frobenius_applied": float(sum(float(r.get("frobenius_delta") or 0.0) for r in applied)),
    }


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for wi in range(int(p["n_worlds"])):
        for order in list(p["orders"]):
            for tmpl in KIND_TEMPLATES:
                for arm in ARMS:
                    ids.append(tmpl.format(order=order, wi=wi, arm=arm))
    for wi in range(int(p["n_worlds"])):
        for arm in ARMS:
            ids.append(f"contradict|w{wi}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(ARMS),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM040 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def _seq(pairs: list[tuple[str, str]], order: str) -> list[tuple[str, str]]:
    return list(reversed(pairs)) if order == "B_then_A" else list(pairs)


def _semantic_pass(*, ranking_ok: bool, n_ok: int, n_need: int, n_viol: int) -> bool:
    return bool(ranking_ok) and int(n_ok) == int(n_need) and int(n_viol) == 0


