def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.40.CAUSALBATTERY.DECISION",
        "product": "0.0.004",
        "manifest_sha": MANIFEST_SHA,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "candidate_v40_lock": False,
        "note": "TM040 untouched causal battery. Product remains 0.0.004. No cortex.candidate.v40.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


