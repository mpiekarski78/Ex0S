def eval_arm(bundle: dict[str, Any], *, arm: str, n: int) -> dict[str, Any]:
    parent_h = str(bundle["w0_hash"])
    if arm == "attempts":
        tape = list(bundle["attempts"])
        if n >= len(tape):
            raise RuntimeError("N must be a strict attempt prefix")
        train_rows = tape[:n]
        future_rows = tape[n:]
    elif arm == "residents":
        if n < 1 or n > len(bundle["stores"]):
            raise RuntimeError("resident prefix out of range")
        train_rows = list(bundle["stores"][n - 1])
        future_rows = list(bundle["stores"][-1])
    else:
        raise RuntimeError(arm)
    cons = list(bundle["ref_pairs"]) + pairs_of(train_rows)
    rec, W_star = solve_ceiling(bundle["W0"], cons, bundle["vocab"])
    if w_act_hash(bundle["ag"]) != parent_h:
        raise RuntimeError("W_act_query installed or moved")
    W_use = bundle["W0"] if W_star is None else W_star
    train_sc = score_eval(W_use, pairs_of(train_rows), bundle["vocab"])
    future_sc = score_eval(W_use, pairs_of(future_rows), bundle["vocab"])
    ref_sc = score_eval(W_use, list(bundle["ref_pairs"]), bundle["vocab"])
    if w_act_hash(bundle["ag"]) != parent_h:
        raise RuntimeError("W_act_query moved after W_star scoring")
    del W_star
    feasible = bool(rec.get("feasible"))
    train_ok = bool(train_sc["n_ok"] == train_sc["n_need"])
    ref_ok = bool(ref_sc["n_ok"] == ref_sc["n_need"])
    future_ok = bool(future_sc["n_ok"] == future_sc["n_need"])
    if not feasible:
        code = "n_infeasible"
    elif not ref_ok:
        code = "n_ref_break"
    elif train_ok and future_ok:
        code = "n_generalizes"
    elif train_ok:
        code = "n_prefix_only"
    else:
        code = "n_prefix_fail"
    out = {
        "kind": "scored",
        "id": f"{arm}|n{n}|w{bundle['wi']}",
        "arm": arm,
        "n": int(n),
        "n_is_organism_constant": False,
        "world": int(bundle["wi"]),
        "passed": bool(feasible and ref_ok and train_ok),
        "cell_code": code,
        "feasible": bool(feasible),
        "solver_status": rec.get("status"),
        "n_constraints": rec.get("n_constraints"),
        "frobenius_delta": rec.get("frobenius_delta"),
        "w0_hash": parent_h,
        "w_star_hash": rec.get("w_star_hash"),
        "applied": False,
        "W_installed": False,
        "discarded": True,
        "train": train_sc,
        "future": future_sc,
        "reference": ref_sc,
        "train_ok": bool(train_ok),
        "future_ok": bool(future_ok),
        "ref_ok": bool(ref_ok),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "socp_extended": False,
        "floor_unchanged": True,
    }
    assert_finite_record(out, ctx=out["id"])
    return out


def synthetic_grid(*, decoder_ok: bool = True, code: str = "grounding_consolidation_plausible") -> list[dict[str, Any]]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    cells: list[dict[str, Any]] = []
    integrity = code not in ("storage_integrity_failure", "setup_precondition_fail")
    cue_ok = code not in ("cue_addressing_collapsed", "storage_integrity_failure", "setup_precondition_fail")
    for wi in (0, 1):
        cells.append(
            {
                "id": f"decoder|w{wi}",
                "arm": "decoder",
                "kind": "setup",
                "passed": bool(decoder_ok),
                "integrity_ok": bool(integrity),
                "cue_addressing_ok": bool(cue_ok),
                "counts": {
                    "n_refresh_diff_action": 0 if integrity else 1,
                    "n_refresh_diff_cue_same_action": 0 if cue_ok else 1,
                },
            }
        )
    att_future = code == "grounding_consolidation_plausible" or code == "storage_selection_capacity_wall"
    res_future = code == "grounding_consolidation_plausible"
    prefix_ok = code not in ("prefix_infeasible", "setup_precondition_fail")
    for arm in ARMS:
        for n in n_grid:
            for wi in (0, 1):
                feasible = prefix_ok or not (arm == "attempts" and n == 4)
                future_ok = bool(feasible and ((arm == "attempts" and att_future) or (arm == "residents" and res_future)))
                train_ok = bool(feasible)
                if not feasible:
                    cc = "n_infeasible"
                elif future_ok:
                    cc = "n_generalizes"
                elif train_ok:
                    cc = "n_prefix_only"
                else:
                    cc = "n_prefix_fail"
                cells.append(
                    {
                        "id": f"{arm}|n{n}|w{wi}",
                        "arm": arm,
                        "n": int(n),
                        "kind": "scored",
                        "passed": bool(feasible and train_ok),
                        "cell_code": cc,
                        "feasible": bool(feasible),
                        "future_ok": bool(future_ok),
                        "train_ok": bool(train_ok),
                        "ref_ok": True,
                    }
                )
    return cells


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "install_W_star": False,
        "episode_match_l2_retuned": False,
        "canonical_law_reconsidered": False,
        "setup_excluded_from_behavioral_first_match": True,
        "discard_every_W_star": True,
        "p1_replacement_law_compatible_with_opaque_kv": None,
        "generic_consolidation_plausible": False,
        "storage_capacity_wall": False,
        "representation_drift": False,
    }
    for wi in (0, 1):
        dec = by.get(f"decoder|w{wi}")
        if dec is None or not bool(dec.get("passed")):
            return "setup_precondition_fail", "setup_precondition_fail", flags
    if any(not bool(by[f"decoder|w{wi}"].get("integrity_ok")) for wi in (0, 1)):
        flags["p1_replacement_law_compatible_with_opaque_kv"] = False
        return "storage_integrity_failure", "storage_integrity_failure", flags
    if any(not bool(by[f"decoder|w{wi}"].get("cue_addressing_ok")) for wi in (0, 1)):
        flags["p1_replacement_law_compatible_with_opaque_kv"] = False
        return "cue_addressing_collapsed", "cue_addressing_collapsed", flags
    flags["p1_replacement_law_compatible_with_opaque_kv"] = True
    if any(not bool(by[f"attempts|n4|w{wi}"].get("feasible")) for wi in (0, 1)):
        return "prefix_infeasible", "prefix_infeasible", flags

    def any_future(arm: str) -> bool:
        return all(any(bool(by[f"{arm}|n{n}|w{wi}"].get("future_ok")) for n in n_grid) for wi in (0, 1))

    att = any_future("attempts")
    res = any_future("residents")
    if not att:
        flags["representation_drift"] = True
        return "representation_drift", "representation_drift", flags
    if att and not res:
        flags["storage_capacity_wall"] = True
        return "storage_selection_capacity_wall", "storage_selection_capacity_wall", flags
    flags["generic_consolidation_plausible"] = True
    return "grounding_consolidation_plausible", "grounding_consolidation_plausible", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "_run_joint_socp_consolidation", "credit_tagged", "latest_episode"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in (
                    "_last_p1",
                    "_last_key_rho",
                    "W_k",
                    "W_q",
                    "W_v",
                    "W_act_query",
                    "_episodes",
                ):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM057 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py must stay frozen")
    if sha_file(TM056_RUNNER) != p["tm056_runner_sha"]:
        raise RuntimeError("TM056 runner must stay frozen")
    if hashlib.sha256(TM056_DEV.read_bytes()).hexdigest() != p["tm056_dev_sha"]:
        raise RuntimeError("TM056 DEV lock must stay frozen")
    if hashlib.sha256(TM056_DEC.read_bytes()).hexdigest() != p["tm056_decision_sha"]:
        raise RuntimeError("TM056 decision lock must stay frozen")
    if hashlib.sha256(TM056_PREREG.read_bytes()).hexdigest() != p["tm056_prereg_sha"]:
        raise RuntimeError("TM056 prereg must stay frozen")
    if hashlib.sha256(TM056_ADD.read_bytes()).hexdigest() != p["tm056_addendum_sha"]:
        raise RuntimeError("TM056 addendum must stay frozen")
    if hashlib.sha256(LAW.read_bytes()).hexdigest() != p["write_time_law_sha"]:
        raise RuntimeError("write-time law must stay frozen")
    if sha_file(TM055_RUNNER) != p["tm055_runner_sha"]:
        raise RuntimeError("TM055 runner must stay frozen")
    if sha_file(TM052_RUNNER) != p["tm052_runner_sha"]:
        raise RuntimeError("TM052 runner must stay frozen")
    if sha_file(TM051_RUNNER) != p["tm051_runner_sha"]:
        raise RuntimeError("TM051 runner must stay frozen")
    if sha_file(TM046_RUNNER) != p["tm046_runner_sha"]:
        raise RuntimeError("TM046 runner must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if int(p["n_dev_repeats"]) != 4:
        raise RuntimeError("n_dev_repeats must stay 4")
    if float(EPISODE_MATCH_L2) != 0.05:
        raise RuntimeError("do not retune EPISODE_MATCH_L2")
    add = json.loads(TM056_ADD.read_text(encoding="utf-8"))
    if add["historical_decision_code"] != "replaced_under_write_law":
        raise RuntimeError("TM056 first-match must stay frozen")
    if add["canonical_law_reconsidered"] is not False:
        raise RuntimeError("canonical law must not be reconsidered")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="du_dev_")
    try:
        bundles = [collect_bundle(wi=int(wi), tmp=tmp.name) for wi in range(int(p["n_worlds"]))]
        for bundle in bundles:
            cells.append(bundle["decoder"])
        for arm in list(p["arms"]):
            for n in [int(x) for x in p["n_grid"]]:
                for bundle in bundles:
                    cells.append(eval_arm(bundle, arm=str(arm), n=int(n)))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["install_W_star"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "install_W_star": False,
        "discard_every_W_star": True,
        "episode_match_l2_retuned": False,
        "canonical_law_reconsidered": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "tm056_runner_untouched": True,
        "neural_untouched": True,
        "canonical_state_generator": "write_time_last_p1",
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


