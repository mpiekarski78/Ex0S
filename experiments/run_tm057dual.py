def expected_cell_ids() -> list[str]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"{arm}|n{n}|w{wi}" for arm in list(p["arms"]) for n in n_grid for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "n_grid": n_grid,
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM057 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM057 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS or len(setup) != N_SETUP_CELLS or len(scored) != N_SCORED_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def hvec(x: Any) -> str | None:
    if x is None:
        return None
    return vec_hash(np.asarray(x, dtype=np.float64))


class Receipts:
    def __init__(self) -> None:
        self.current_cue: str | None = None
        self.cue_by_id: dict[int, str] = {}
        self.rows: list[dict[str, Any]] = []
        self.stores: list[list[dict[str, Any]]] = []
        self.attempts: list[dict[str, Any]] = []
        self._seq = 0

    def bind(self, ag: NeuralCortex) -> None:
        orig = ag._episode_write
        recs = self

        def _episode_write(p1: np.ndarray, handle: str, adv: float, *, event_key=None, key_rho=None) -> None:
            before = [
                {
                    "object_id": id(ep),
                    "handle": str(ep.get("handle")),
                    "p1_hash": hvec(ep.get("p1")),
                    "key_hash": hvec(ep.get("key_rho")),
                    "cue": recs.cue_by_id.get(id(ep)),
                    "p1": np.asarray(ep["p1"], dtype=np.float64).copy(),
                }
                for ep in ag._episodes
            ]
            clock_b = int(ag._episode_clock)
            n_b = len(ag._episodes)
            ins_b = int(ag._episode_n_inserts)
            rep_b = int(ag._episode_n_replaced)
            ids_b = [id(ep) for ep in ag._episodes]
            orig(p1, handle, adv, event_key=event_key, key_rho=key_rho)
            clock_a = int(ag._episode_clock)
            n_a = len(ag._episodes)
            ins_a = int(ag._episode_n_inserts)
            rep_a = int(ag._episode_n_replaced)
            ids_a = [id(ep) for ep in ag._episodes]
            if clock_a == clock_b:
                outcome = "reject"
                slot = None
                obj = None
            elif rep_a > rep_b:
                outcome = "replace"
                slot = next((i for i, (a, b) in enumerate(zip(ids_a, ids_b)) if a != b), None)
                obj = None if slot is None else ids_a[int(slot)]
            elif ins_a > ins_b and n_a > n_b:
                outcome = "append"
                slot = n_a - 1
                obj = ids_a[int(slot)]
            elif ins_a > ins_b:
                outcome = "evict"
                slot = next((i for i, (a, b) in enumerate(zip(ids_a, ids_b)) if a != b), None)
                obj = None if slot is None else ids_a[int(slot)]
            else:
                outcome = "refresh"
                changed = [i for i, ep in enumerate(ag._episodes) if int(ep.get("age") or 0) == clock_a]
                slot = changed[-1] if changed else None
                obj = None if slot is None else ids_a[int(slot)]
            matched = None
            if slot is not None and slot < len(before):
                matched = before[int(slot)]
            elif outcome == "refresh" and slot is not None:
                matched = next((b for b in before if b["object_id"] == obj), None)
            stored = None if obj is None else next((ep for ep in ag._episodes if id(ep) == obj), None)
            cue = recs.current_cue
            arg_p1 = np.asarray(ag._unit_or_zero(np.asarray(p1, dtype=np.float64)), dtype=np.float64).copy()
            res_before_p1 = None if matched is None else matched["p1"]
            res_after_p1 = None if stored is None else np.asarray(stored["p1"], dtype=np.float64).copy()
            handle_before = None if matched is None else str(matched["handle"])
            cue_before = None if matched is None else matched.get("cue")
            key_before = None if matched is None else matched.get("key_hash")
            handle_after = None if stored is None else str(stored["handle"])
            key_after = None if stored is None else hvec(stored.get("key_rho"))
            if obj is not None and cue is not None:
                recs.cue_by_id[int(obj)] = str(cue)
            if outcome == "evict" and matched is not None:
                recs.cue_by_id.pop(int(matched["object_id"]), None)
            same_action = handle_before is None or handle_before == str(handle)
            same_cue = cue_before is None or cue_before == cue
            recs._seq += 1
            row = {
                "write_id": int(recs._seq),
                "resting": bool(ag._resting),
                "outcome": outcome,
                "handle": str(handle),
                "cue": cue,
                "record_id": obj,
                "slot": slot,
                "n_before": int(n_b),
                "n_after": int(n_a),
                "attempted_v_hash": hvec(arg_p1),
                "resident_p1_before": None if res_before_p1 is None else hvec(res_before_p1),
                "resident_p1_after": None if res_after_p1 is None else hvec(res_after_p1),
                "key_before": key_before,
                "key_after": key_after,
                "handle_before": handle_before,
                "handle_after": handle_after,
                "cue_before": cue_before,
                "same_action": bool(same_action),
                "same_cue": bool(same_cue),
                "refresh_crosses_cue": bool(outcome == "refresh" and not same_cue),
                "refresh_crosses_action": bool(outcome == "refresh" and not same_action),
                "replace_crosses_action": bool(outcome == "replace" and not same_action),
                "arg_p1": arg_p1,
                "resident_after_p1": res_after_p1,
            }
            recs.rows.append(row)
            if (not ag._resting) and outcome != "reject":
                recs.attempts.append({"handle": str(handle), "p1": arg_p1, "cue": cue, "write_id": int(recs._seq)})
                recs.stores.append(store_snapshot(ag, recs.cue_by_id))

        ag._episode_write = _episode_write  # type: ignore[method-assign]


def store_snapshot(ag: NeuralCortex, cue_by_id: dict[int, str]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for ep in ag._episodes:
        if not ep.get("valid"):
            continue
        oid = id(ep)
        p1 = np.asarray(ep["p1"], dtype=np.float64).copy()
        out.append(
            {
                "record_id": oid,
                "handle": str(ep["handle"]),
                "p1": p1,
                "p1_hash": hvec(p1),
                "key_hash": hvec(ep.get("key_rho")),
                "cue": cue_by_id.get(oid),
            }
        )
    return out


def pairs_of(rows: list[dict[str, Any]]) -> list[tuple[str, np.ndarray]]:
    return [(str(r["handle"]), np.asarray(r["p1"], dtype=np.float64).copy()) for r in rows]


