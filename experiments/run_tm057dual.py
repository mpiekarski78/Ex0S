def store_brief(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [{k: r[k] for k in ("record_id", "handle", "p1_hash", "key_hash", "cue")} for r in rows]


def live_trajectory(
    *,
    tmp: str,
    tag: str,
    wi: int,
    seed: int,
    domain: str,
    n_repeats: int,
    cue_fn,
    tag_prefix: str,
    grounded: bool,
    receipts: Receipts | None,
) -> dict[str, Any]:
    p46 = json.loads((REPO_ROOT / "docs" / "lineage_oneshot.prereg.lock").read_text(encoding="utf-8"))
    n_handles = int(p46["n_handles"])
    n_facts = int(p46["n_facts"])
    world = capacity_world(int(wi), str(domain), n_cues=int(n_facts), n_handles=int(n_handles))
    pairs = mapping_pairs(world, flip=False)
    handles = list(world["handles"])
    test_cues = [str(c) for c, _h in pairs]
    ag = _fresh(tmp, tag, world, seed_registry=int(seed))
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.set_action_feedback_enabled(bool(grounded))
    if receipts is not None:
        receipts.bind(ag)
    used: list[str] = []
    for rep in range(int(n_repeats)):
        for i, handle in enumerate(handles):
            cue = str(cue_fn(rep, i, handle))
            used.append(cue)
            if cue in test_cues:
                raise RuntimeError("trajectory cue collided with test facts")
            if receipts is not None:
                receipts.current_cue = cue
            ground_one(ag, world, handle, tag=f"{tag_prefix}_{rep}_{i}", symbols=[cue])
    if len(used) != len(set(used)) and grounded:
        raise RuntimeError("online cues were not unique")
    ag.rest_epoch(int(p46["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    prep_eval(ag)
    last_p1: dict[str, np.ndarray] = {}
    for ep in ag._episodes:
        if not ep.get("valid"):
            continue
        last_p1[str(ep["handle"])] = np.asarray(ep["p1"], dtype=np.float64).copy()
    handle_hits = []
    all_ok = True
    for handle in handles:
        p1 = last_p1.get(handle)
        if p1 is None:
            all_ok = False
            handle_hits.append({"handle": handle, "ok": False, "winner": None, "reason": "missing_write"})
            continue
        sc = score_direct(ag, p1)
        ok = sc["winner"] == handle
        all_ok = all_ok and bool(ok)
        handle_hits.append({"handle": handle, "ok": bool(ok), "winner": sc["winner"], "p1_hash": vec_hash(p1)})
    ag.opaque.clear()
    reset_before_recall(ag)
    snap = ag.checkpoint()
    return {
        "snap": snap,
        "genome": copy.deepcopy(ag.genome),
        "world": world,
        "pairs": pairs,
        "handles": handles,
        "last_p1": last_p1,
        "handle_hits": handle_hits,
        "all_ok": bool(all_ok),
        "w_act_query_hash": w_act_hash(ag),
        "grounded": bool(grounded),
        "n_repeats": int(n_repeats),
        "seed": int(seed),
    }


def tally(rows: list[dict[str, Any]]) -> dict[str, int]:
    g = [r for r in rows if not r.get("resting")]
    return {
        "n_append": int(sum(1 for r in g if r["outcome"] == "append")),
        "n_evict": int(sum(1 for r in g if r["outcome"] == "evict")),
        "n_refresh": int(sum(1 for r in g if r["outcome"] == "refresh")),
        "n_reject": int(sum(1 for r in g if r["outcome"] == "reject")),
        "n_replace": int(sum(1 for r in g if r["outcome"] == "replace")),
        "n_refresh_same_cue_same_action": int(sum(1 for r in g if r["outcome"] == "refresh" and r["same_cue"] and r["same_action"])),
        "n_refresh_diff_cue_same_action": int(sum(1 for r in g if r["refresh_crosses_cue"] and r["same_action"])),
        "n_refresh_diff_action": int(sum(1 for r in g if r["refresh_crosses_action"] or r["replace_crosses_action"])),
    }


