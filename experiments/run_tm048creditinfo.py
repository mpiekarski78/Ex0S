def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    ids.extend(f"credit|w{wi}" for wi in range(int(p["n_worlds"])))
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM048 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM048 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def unit(x: np.ndarray) -> np.ndarray:
    v = np.asarray(x, dtype=np.float64).reshape(-1)
    nrm = float(np.linalg.norm(v))
    if nrm <= 1e-12:
        return v
    return v / nrm


def pairwise(rows: list[np.ndarray], labels: list[str]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for i in range(len(rows)):
        for j in range(i + 1, len(rows)):
            rel = vec_rel(rows[i], rows[j])
            out.append({"i": int(i), "j": int(j), "a": labels[i], "b": labels[j], **rel})
    return out


def project_value(ag: NeuralCortex, rho: np.ndarray) -> np.ndarray:
    wv = ag._from_t(ag.W_v)
    return unit(wv @ np.asarray(rho, dtype=np.float64).reshape(-1))


def credit_one(
    ag: NeuralCortex,
    world: dict[str, Any],
    handle: str,
    cue: str,
) -> dict[str, Any]:
    """Existing teach path: observe cue, clamp action, observe outcome. Same tags for every clone."""
    body = list(MID_BODY)
    observe_cue(ag, world, tag=f"{CREDIT_TAG}_sel", body=body, symbols=[cue])
    rho_before = ag._from_t(ag.rho).copy()
    p1_before = None if ag._last_p1 is None else np.asarray(ag._last_p1, dtype=np.float64).copy()
    ag.clamp_action("ACT", handle)
    _state, body2 = physics(body, handle, world["latent"])
    observe_cue(ag, world, tag=f"{CREDIT_TAG}_obs", body=list(body2), symbols=[cue])
    rho_after = ag._from_t(ag.rho).copy()
    p1_after = None if ag._last_p1 is None else np.asarray(ag._last_p1, dtype=np.float64).copy()
    projected = project_value(ag, rho_after)
    ep = latest_episode(ag, handle)
    stored = None if ep is None else np.asarray(ep["p1"], dtype=np.float64).copy()
    motor = None if handle not in ag.motor_vocab else np.asarray(ag.motor_vocab[handle], dtype=np.float64).copy()
    return {
        "handle": handle,
        "cue": cue,
        "body2": [float(x) for x in body2],
        "rho_before": rho_before,
        "p1_before": p1_before,
        "rho_after": rho_after,
        "p1_after": p1_after,
        "projected": projected,
        "stored": stored,
        "motor": motor,
    }


def eval_credit_cell(common: dict[str, Any], *, wi: int) -> dict[str, Any]:
    cell_id = f"credit|w{wi}"
    world = common["world"]
    cue = str(common["pairs"][0][0])
    handles = list(world["handles"])
    parent = load_common(common)
    freeze_plasticity(parent)
    parent.genome.act_recall_mode = ACT_RECALL_OFF
    parent.set_memproj_arm(MEMPROJ_NONE)
    reset_before_recall(parent)
    parent_h = w_act_hash(parent)
    clones: list[dict[str, Any]] = []
    for handle in handles:
        ag = load_common(common)
        freeze_plasticity(ag)
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_NONE)
        reset_before_recall(ag)
        rec = credit_one(ag, world, handle, cue)
        if w_act_hash(ag) != parent_h:
            raise RuntimeError(f"W_act_query moved on {cell_id}")
        cred_vec = rec["p1_after"] if rec["p1_after"] is not None else rec["rho_after"]
        cred_sc = score_direct(ag, cred_vec)
        proj_sc = score_direct(ag, rec["projected"])
        stored_sc = None if rec["stored"] is None else score_direct(ag, rec["stored"])
        ceil_sc = score_direct(ag, common["dev_p1"][handle])
        clones.append(
            {
                "handle": handle,
                "cue": cue,
                "body2": rec["body2"],
                "rho_before": {
                    "hash": vec_hash(rec["rho_before"]),
                    "norm": vec_norm(rec["rho_before"]),
                },
                "p1_before": None
                if rec["p1_before"] is None
                else {"hash": vec_hash(rec["p1_before"]), "norm": vec_norm(rec["p1_before"])},
                "rho_after": {
                    "hash": vec_hash(rec["rho_after"]),
                    "norm": vec_norm(rec["rho_after"]),
                },
                "p1_after": None
                if rec["p1_after"] is None
                else {"hash": vec_hash(rec["p1_after"]), "norm": vec_norm(rec["p1_after"])},
                "projected": {"hash": vec_hash(rec["projected"]), "norm": vec_norm(rec["projected"])},
                "stored": None
                if rec["stored"] is None
                else {"hash": vec_hash(rec["stored"]), "norm": vec_norm(rec["stored"])},
                "credit_score": cred_sc,
                "projected_score": proj_sc,
                "stored_score": stored_sc,
                "ceiling_score": ceil_sc,
                "credit_ok": bool(cred_sc["winner"] == handle),
                "projected_ok": bool(proj_sc["winner"] == handle),
                "stored_ok": bool(stored_sc is not None and stored_sc["winner"] == handle),
                "ceiling_ok": bool(ceil_sc["winner"] == handle),
                "copied_action_into_s": bool(
                    rec["stored"] is not None
                    and rec["motor"] is not None
                    and vec_hash(rec["stored"]) == vec_hash(rec["motor"])
                ),
                "rel_credit_to_dev": vec_rel(cred_vec, common["dev_p1"][handle]),
                "rel_credit_to_projected": vec_rel(cred_vec, rec["projected"]),
                "rel_credit_to_stored": vec_rel(cred_vec, rec["stored"]),
                "rel_projected_to_stored": vec_rel(rec["projected"], rec["stored"]),
                "_rho_before": rec["rho_before"],
                "_rho_after": rec["rho_after"],
                "_p1_after": rec["p1_after"],
                "_projected": rec["projected"],
                "_stored": rec["stored"],
            }
        )
    labels = [c["handle"] for c in clones]
    pair_rho_b = pairwise([c["_rho_before"] for c in clones], labels)
    pair_rho_a = pairwise([c["_rho_after"] for c in clones], labels)
    pair_p1 = pairwise([c["_p1_after"] for c in clones], labels)
    pair_proj = pairwise([c["_projected"] for c in clones], labels)
    pair_st = pairwise([c["_stored"] for c in clones], labels)
    for c in clones:
        for k in ("_rho_before", "_rho_after", "_p1_after", "_projected", "_stored"):
            c.pop(k, None)
    n_unique_rho_before = len({c["rho_before"]["hash"] for c in clones})
    n_unique_rho_after = len({c["rho_after"]["hash"] for c in clones})
    n_unique_p1_after = len({c["p1_after"]["hash"] for c in clones if c["p1_after"]})
    n_unique_proj = len({c["projected"]["hash"] for c in clones})
    n_unique_stored = len({c["stored"]["hash"] for c in clones if c["stored"]})
    max_l2 = max((float(p["l2"] or 0.0) for p in pair_rho_a), default=0.0)
    rho_changed = n_unique_rho_after > 1 and max_l2 > float(EPISODE_MATCH_L2)
    n_ok_credit = int(sum(1 for c in clones if c["credit_ok"]))
    n_ok_proj = int(sum(1 for c in clones if c["projected_ok"]))
    n_ok_stored = int(sum(1 for c in clones if c["stored_ok"]))
    n_ok_ceil = int(sum(1 for c in clones if c["ceiling_ok"]))
    if n_unique_rho_before != 1:
        code = "setup_precondition_fail"
    elif n_unique_rho_after == 1 or max_l2 <= float(EPISODE_MATCH_L2):
        code = "credit_action_information_absent"
    elif n_ok_credit < len(handles):
        code = "credit_trace_present_not_decodable"
    elif n_ok_proj < len(handles) or n_ok_stored < len(handles):
        code = "value_projection_loss"
    else:
        code = "credit_information_pass"
    if any(bool(c["copied_action_into_s"]) for c in clones):
        raise RuntimeError("runner copied action into S")
    out = {
        "kind": "credit",
        "id": cell_id,
        "arm": "credit_split",
        "world": int(wi),
        "cue": cue,
        "handles": handles,
        "passed": code == "credit_information_pass",
        "cell_code": code,
        "n_actions": int(len(handles)),
        "n_ok_ceiling": n_ok_ceil,
        "n_ok_credit": n_ok_credit,
        "n_ok_projected": n_ok_proj,
        "n_ok_stored": n_ok_stored,
        "n_unique_rho_before": int(n_unique_rho_before),
        "n_unique_rho_after": int(n_unique_rho_after),
        "n_unique_p1_after": int(n_unique_p1_after),
        "n_unique_projected": int(n_unique_proj),
        "n_unique_stored": int(n_unique_stored),
        "max_pairwise_l2_rho_after": float(max_l2),
        "rho_changed_with_action": bool(rho_changed),
        "identical_body": len({tuple(c["body2"]) for c in clones}) == 1,
        "w_act_query_frozen": True,
        "copied_action_into_s": False,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "action_feedback_edited": False,
        "clones": clones,
        "pairwise_rho_before": pair_rho_b,
        "pairwise_rho_after": pair_rho_a,
        "pairwise_p1_after": pair_p1,
        "pairwise_projected": pair_proj,
        "pairwise_stored": pair_st,
    }
    assert_finite_record(out, ctx=cell_id)
    return out


def synthetic_grid(*, decoder_ok: bool = True, code: str = "credit_action_information_absent") -> list[dict[str, Any]]:
    cells = [
        {"id": f"decoder|w{wi}", "arm": "decoder", "kind": "decoder", "passed": bool(decoder_ok)}
        for wi in (0, 1)
    ]
    for wi in (0, 1):
        cells.append(
            {
                "id": f"credit|w{wi}",
                "arm": "credit_split",
                "kind": "credit",
                "passed": code == "credit_information_pass",
                "cell_code": code,
                "n_ok_credit": 4 if code in ("value_projection_loss", "credit_information_pass") else 1,
                "n_ok_projected": 4 if code == "credit_information_pass" else 1,
                "n_unique_rho_after": 1 if code == "credit_action_information_absent" else 4,
                "max_pairwise_l2_rho_after": 0.0 if code == "credit_action_information_absent" else 1.0,
                "rho_changed_with_action": code != "credit_action_information_absent",
            }
        )
    return cells


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "action_feedback_edited": False,
        "earned_action_feedback": False,
        "earned_kqv": False,
        "earned_value_decoder": False,
        "separate_candidate_review_open": False,
        "rho_changed_with_action": None,
        "n_unique_rho_after": None,
    }
    if any(f"decoder|w{wi}" not in by or not bool(by[f"decoder|w{wi}"].get("passed")) for wi in (0, 1)):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    credit = [by.get(f"credit|w{wi}") for wi in (0, 1)]
    if any(c is None for c in credit):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    flags["rho_changed_with_action"] = any(bool(c.get("rho_changed_with_action")) for c in credit)
    flags["n_unique_rho_after"] = max(int(c.get("n_unique_rho_after") or 0) for c in credit)
    codes = [str(c.get("cell_code") or "setup_precondition_fail") for c in credit]
    chosen = "credit_information_pass"
    for step in LADDER:
        if step == "credit_information_pass":
            continue
        if any(x == step for x in codes):
            chosen = step
            break
    if chosen == "credit_action_information_absent":
        flags["earned_action_feedback"] = True
    return chosen, chosen, flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "canonical_cue_probe"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM048 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py drifted")
    if sha_file(TM046_RUNNER) != p["tm046_runner_sha"]:
        raise RuntimeError("TM046 runner must stay frozen")
    if hashlib.sha256(TM046_DEV.read_bytes()).hexdigest() != p["tm046_dev_sha"]:
        raise RuntimeError("TM046 DEV lock must stay frozen")
    if hashlib.sha256(TM046_DEC.read_bytes()).hexdigest() != p["tm046_decision_sha"]:
        raise RuntimeError("TM046 decision lock must stay frozen")
    if hashlib.sha256(TM046_ADD.read_bytes()).hexdigest() != p["tm046_addendum_sha"]:
        raise RuntimeError("TM046 addendum must stay frozen")
    if sha_file(TM047_RUNNER) != p["tm047_runner_sha"]:
        raise RuntimeError("TM047 runner must stay frozen")
    if hashlib.sha256(TM047_DEV.read_bytes()).hexdigest() != p["tm047_dev_sha"]:
        raise RuntimeError("TM047 DEV lock must stay frozen")
    if hashlib.sha256(TM047_DEC.read_bytes()).hexdigest() != p["tm047_decision_sha"]:
        raise RuntimeError("TM047 decision lock must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("kqv_edit_authorized")) or bool(p.get("decoder_edit_authorized")):
        raise RuntimeError("TM048 must not tune K/Q/V or the decoder")
    if bool(p.get("action_feedback_edit_authorized")) or bool(p.get("neural_edit_authorized")):
        raise RuntimeError("TM048 must not edit action feedback")
    if "memproj_arm" in GenomeConfig().to_dict():
        raise RuntimeError("memproj must not be a GenomeConfig field")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="ci_dev_")
    try:
        commons = {wi: develop_with_refs(wi=int(wi), tmp=tmp.name) for wi in range(int(p["n_worlds"]))}
        for wi in range(int(p["n_worlds"])):
            cells.append(commons[wi]["decoder"])
        for wi in range(int(p["n_worlds"])):
            cells.append(eval_credit_cell(commons[int(wi)], wi=int(wi)))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    flags["kqv_edited"] = False
    flags["action_feedback_edited"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "action_feedback_edited": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "solver_edited": False,
        "tm046_runner_untouched": True,
        "tm047_runner_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


