def unit_or_zero(z: np.ndarray, n: int) -> np.ndarray:
    x = np.asarray(z, dtype=np.float64).reshape(-1)
    nrm = float(np.linalg.norm(x))
    if not np.isfinite(nrm) or nrm <= float(PROTO_EPS):
        return np.zeros(int(n), dtype=np.float64)
    return (x / nrm).astype(np.float64)


def query_scores(W: np.ndarray, x: np.ndarray, vocab: dict[str, np.ndarray]) -> dict[str, float]:
    r = np.asarray(x, dtype=np.float64).reshape(-1)
    rn = float(np.linalg.norm(r)) + 1e-12
    q = np.asarray(W, dtype=np.float64) @ r
    qn = float(np.linalg.norm(q)) + 1e-12
    out: dict[str, float] = {}
    for h, v in vocab.items():
        vv = np.asarray(v, dtype=np.float64).reshape(-1)
        out[str(h)] = float(np.dot(q, vv) / (qn * (float(np.linalg.norm(vv)) + 1e-12)))
    return out


def unique_act_winner(scores: dict[str, float]) -> str | None:
    if not scores:
        return None
    vals = [float(v) for v in scores.values()]
    if all(abs(s) <= float(TIE_EPS) for s in vals):
        return None
    mx = max(vals)
    wins = [h for h, v in scores.items() if abs(float(v) - mx) <= float(TIE_EPS)]
    return wins[0] if len(wins) == 1 else None


def geometric_margin(W: np.ndarray, x: np.ndarray, handle: str, vocab: dict[str, np.ndarray]) -> float:
    scores = query_scores(W, x, vocab)
    others = [h for h in scores if h != handle]
    if not others:
        return 0.0
    rival = max(others, key=lambda h: float(scores[h]))
    w_ch = np.asarray(W, dtype=np.float64).T @ np.asarray(vocab[handle], dtype=np.float64).reshape(-1)
    w_ot = np.asarray(W, dtype=np.float64).T @ np.asarray(vocab[rival], dtype=np.float64).reshape(-1)
    d = w_ch - w_ot
    xn = unit_or_zero(x, int(np.asarray(x).reshape(-1).shape[0]))
    dn = float(np.linalg.norm(d))
    if dn <= float(PROTO_EPS):
        return 0.0
    return float(np.dot(d, xn) / dn)


def organism_violation(W: np.ndarray, x: np.ndarray, handle: str, vocab: dict[str, np.ndarray]) -> bool:
    scores = query_scores(W, x, vocab)
    win = unique_act_winner(scores)
    if win != str(handle) or win is None:
        return True
    return geometric_margin(W, x, handle, vocab) < float(ACT_MARGIN_FLOOR)


def score_set(W: np.ndarray, pairs: list[tuple[str, np.ndarray]], vocab: dict[str, np.ndarray]) -> dict[str, Any]:
    hits = []
    n_ok = 0
    n_viol = 0
    for handle, x in pairs:
        sc = query_scores(W, x, vocab)
        win = unique_act_winner(sc)
        viol = organism_violation(W, x, handle, vocab)
        ok = (not viol) and win == handle
        if ok:
            n_ok += 1
        if viol:
            n_viol += 1
        hits.append({"handle": handle, "winner": win, "ok": bool(ok), "violation": bool(viol), "p1_hash": vec_hash(x)})
    return {"n_ok": int(n_ok), "n_need": len(pairs), "n_violations": int(n_viol), "handles": hits}


def socp_constraints(pairs: list[tuple[str, np.ndarray]], vocab: dict[str, np.ndarray], n: int) -> list[dict[str, np.ndarray]]:
    rivals = sorted(vocab)
    rows: list[dict[str, np.ndarray]] = []
    for i, (handle, x_raw) in enumerate(pairs):
        x = unit_or_zero(x_raw, n)
        if float(np.max(np.abs(x))) <= float(PROTO_EPS):
            continue
        v_h = np.asarray(vocab[handle], dtype=np.float64).reshape(-1)
        for rival in rivals:
            if rival == handle:
                continue
            v_r = np.asarray(vocab[rival], dtype=np.float64).reshape(-1)
            rows.append({"d": v_h - v_r, "x": x, "key": f"{i}|{handle}|{rival}"})
    return rows


def solve_ceiling(
    W0: np.ndarray,
    pairs: list[tuple[str, np.ndarray]],
    vocab: dict[str, np.ndarray],
) -> tuple[dict[str, Any], np.ndarray | None]:
    n = int(np.asarray(W0).shape[1])
    cons = socp_constraints(pairs, vocab, n)
    solved = solve_min_change_socp(W0, cons, float(ACT_MARGIN_FLOOR), float(PROTO_EPS))
    rec = {k: v for k, v in solved.items() if k != "W"}
    rec["applied"] = False
    rec["n_constraints"] = len(cons)
    rec["tau"] = float(ACT_MARGIN_FLOOR)
    W_star = solved.get("W")
    if W_star is None or str(solved.get("status")) != "optimal":
        rec["feasible"] = False
        rec["predicate"] = score_set(W0, pairs, vocab)
        rec["w_star_hash"] = rec.get("w_hash")
        return rec, None
    W_arr = np.asarray(W_star, dtype=np.float64)
    pred = score_set(W_arr, pairs, vocab)
    rec["predicate"] = pred
    rec["w_star_hash"] = weight_hash(W_arr)
    rec["feasible"] = bool(pred["n_violations"] == 0 and pred["n_ok"] == pred["n_need"])
    return rec, W_arr


def vocab_of(ag: NeuralCortex) -> dict[str, np.ndarray]:
    return {str(h): np.asarray(v, dtype=np.float64).copy() for h, v in ag.motor_vocab.items()}


def ordered_pairs(last_p1: dict[str, np.ndarray], handles: list[str]) -> list[tuple[str, np.ndarray]]:
    out: list[tuple[str, np.ndarray]] = []
    for h in handles:
        p1 = last_p1.get(h)
        if p1 is None:
            raise RuntimeError(f"missing state for {h}")
        out.append((str(h), np.asarray(p1, dtype=np.float64).copy()))
    return out


def heldout_pairs(common: dict[str, Any]) -> list[tuple[str, np.ndarray]]:
    world = common["world"]
    cue = str(common["hold_cue"])
    handles = list(common["handles"])
    parent = load_common(common)
    freeze_plasticity(parent)
    parent.set_action_feedback_enabled(True)
    parent.set_memproj_arm(MEMPROJ_NONE)
    parent.genome.act_recall_mode = ACT_RECALL_OFF
    reset_before_recall(parent)
    parent_h = w_act_hash(parent)
    out: list[tuple[str, np.ndarray]] = []
    for handle in handles:
        ag = load_common(common)
        freeze_plasticity(ag)
        ag.set_action_feedback_enabled(True)
        ag.set_memproj_arm(MEMPROJ_NONE)
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        reset_before_recall(ag)
        rec = credit_tagged(ag, world, handle, cue, tag=f"sf_hold_{handle}")
        if w_act_hash(ag) != parent_h:
            raise RuntimeError("W_act_query moved while collecting held-out wrap")
        p1 = rec["p1_feedback"]
        if p1 is None:
            raise RuntimeError("held-out wrap missing p1")
        out.append((str(handle), np.asarray(p1, dtype=np.float64).copy()))
    if w_act_hash(parent) != parent_h:
        raise RuntimeError("parent W_act_query moved")
    return out


