def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "new_decoder": False,
        "install_W_star": False,
        "socp_scored": False,
        "episode_match_l2_retuned": False,
        "force_cue_into_value": False,
        "setup_excluded_from_behavioral_first_match": True,
        "one_exemplar_grounding_earned": False,
        "genuine_coverage_curve_earned": False,
        "fix_future_probe_only": False,
    }
    if any(f"decoder|w{wi}" not in by or not bool(by[f"decoder|w{wi}"].get("passed")) for wi in (0, 1)):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    codes = [str(by[f"canonical|w{wi}"]["cell_code"]) for wi in (0, 1)]
    if any(c == "state_generator_mismatch" for c in codes):
        return "state_generator_mismatch", "state_generator_mismatch", flags
    if any(c == "runner_reset_sequence" for c in codes):
        flags["fix_future_probe_only"] = True
        return "runner_reset_sequence", "runner_reset_sequence", flags
    if all(c == "action_invariant_values" for c in codes):
        flags["one_exemplar_grounding_earned"] = True
        return "action_invariant_values", "action_invariant_values", flags
    if all(c == "context_varying_values" for c in codes):
        flags["genuine_coverage_curve_earned"] = True
        return "context_varying_values", "context_varying_values", flags
    return "state_generator_mismatch", "state_generator_mismatch", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "_run_joint_socp_consolidation", "solve_min_change_socp"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in ("W_act_query", "W_k", "W_q", "W_v"):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM054 runner SHA drifted after freeze push")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py must stay frozen")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if sha_file(TM053_RUNNER) != p["tm053_runner_sha"]:
        raise RuntimeError("TM053 runner must stay frozen")
    if hashlib.sha256(TM053_DEV.read_bytes()).hexdigest() != p["tm053_dev_sha"]:
        raise RuntimeError("TM053 DEV lock must stay frozen")
    if hashlib.sha256(TM053_DEC.read_bytes()).hexdigest() != p["tm053_decision_sha"]:
        raise RuntimeError("TM053 decision lock must stay frozen")
    if hashlib.sha256(TM053_ADD.read_bytes()).hexdigest() != p["tm053_addendum_sha"]:
        raise RuntimeError("TM053 addendum must stay frozen")
    if sha_file(TM052_RUNNER) != p["tm052_runner_sha"]:
        raise RuntimeError("TM052 runner must stay frozen")
    if hashlib.sha256(TM052_DEV.read_bytes()).hexdigest() != p["tm052_dev_sha"]:
        raise RuntimeError("TM052 DEV lock must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("socp_scoring_authorized")):
        raise RuntimeError("TM054 must not score SOCP")
    if int(p["n_dev_repeats"]) != 4:
        raise RuntimeError("n_dev_repeats must stay 4")
    if float(EPISODE_MATCH_L2) != 0.05:
        raise RuntimeError("do not retune EPISODE_MATCH_L2")
    add = json.loads(TM053_ADD.read_text(encoding="utf-8"))
    if add["interpretation"] != "invalidated_measurement__duplicate_state_support":
        raise RuntimeError("TM053 addendum interpretation must stay frozen")
    if add["historical_decision_code"] != "coverage_generalizes":
        raise RuntimeError("TM053 first-match must stay frozen")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="pv_dev_")
    try:
        bundles = [reconstruct(wi=int(wi), tmp=tmp.name) for wi in range(int(p["n_worlds"]))]
        for bundle in bundles:
            cells.append(bundle["decoder"])
        bounds = []
        for bundle in bundles:
            b = eval_boundary(bundle, wi=int(bundle["decoder"]["world"]))
            bounds.append(b)
            cells.append(b)
        for bundle, b in zip(bundles, bounds):
            cells.append(eval_canonical(bundle, b, wi=int(bundle["decoder"]["world"])))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["install_W_star"] = False
    flags["socp_scored"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "install_W_star": False,
        "socp_scored": False,
        "episode_match_l2_retuned": False,
        "new_decoder": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "tm053_runner_untouched": True,
        "neural_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.54.PROV.DECISION",
        "product": "0.0.004",
        "earned_next": False,
        "eligible_for_000005": False,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "candidate_v41_lock": False,
        "install_W_star": False,
        "socp_scored": False,
        "episode_match_l2_retuned": False,
        "architectural_conclusion": "none",
        "note": "TM054 provenance. Product remains 0.0.004. No coverage scoring. No cortex.candidate.v41.lock.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


