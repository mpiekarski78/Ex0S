def expected_cell_ids() -> list[str]:
    p = load_prereg()
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"{arm}|w{wi}" for arm in list(p["arms"]) for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM054 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM054 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS or len(setup) != N_SETUP_CELLS or len(scored) != N_SCORED_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def hvec(x: Any) -> str | None:
    if x is None:
        return None
    return vec_hash(np.asarray(x, dtype=np.float64))


def parent_snapshot(ag: NeuralCortex) -> dict[str, Any]:
    vocab = {str(k): vec_hash(v) for k, v in sorted(ag.motor_vocab.items())}
    return {
        "w_act": w_act_hash(ag),
        "rho": hvec(ag._from_t(ag.rho)),
        "v_end": hvec(ag.v_end),
        "seed_registry": int(ag.genome.seed_registry),
        "pending": ag._pending is not None,
        "prev_interaction": ag.prev_interaction,
        "last_p1": hvec(ag._last_p1),
        "vocab": hashlib.sha256(json.dumps(vocab, sort_keys=True).encode()).hexdigest(),
    }


def instrumented_credit(ag: NeuralCortex, world: dict[str, Any], handle: str, cue: str, *, tag: str) -> dict[str, Any]:
    ticks: list[dict[str, Any]] = []
    orig_sens = ag._sensory_tick
    orig_x = ag._x_tick

    def x_tick(injected: np.ndarray, body: np.ndarray, same_ix: float):
        x = orig_x(injected, body, same_ix)
        winx = ag._from_t(ag.W_in @ x)
        ticks.append(
            {
                "kind": "x_tick",
                "inj": hvec(injected),
                "body": hvec(body),
                "same_ix": float(same_ix),
                "x": hvec(ag._from_t(x)),
                "win_x": hvec(winx),
            }
        )
        return x

    def sens(injected: np.ndarray, body: np.ndarray, same_ix: float, *, record_sensory: bool = False) -> None:
        orig_sens(injected, body, same_ix, record_sensory=record_sensory)
        ticks.append(
            {
                "kind": "sensory",
                "inj": hvec(injected),
                "rho": hvec(ag._from_t(ag.rho)),
                "same_ix": float(same_ix),
                "record_sensory": bool(record_sensory),
                "last_p1": hvec(ag._last_p1),
            }
        )

    ag._x_tick = x_tick  # type: ignore[method-assign]
    ag._sensory_tick = sens  # type: ignore[method-assign]
    try:
        before = parent_snapshot(ag)
        rec = credit_tagged(ag, world, handle, cue, tag=tag)
        after = parent_snapshot(ag)
    finally:
        ag._x_tick = orig_x  # type: ignore[method-assign]
        ag._sensory_tick = orig_sens  # type: ignore[method-assign]
    motor = rec.get("motor")
    pending_after = ag._pending is not None
    v_end_ticks = [t for t in ticks if t.get("kind") == "sensory" and t.get("inj") == hvec(ag.v_end)]
    win_xs = [t.get("win_x") for t in ticks if t.get("kind") == "x_tick"]
    same_ixs = [t.get("same_ix") for t in ticks if t.get("kind") == "x_tick"]
    return {
        "handle": handle,
        "cue": cue,
        "before": before,
        "after": after,
        "p1_cue": hvec(rec["p1_cue"]),
        "rho_cue": hvec(rec["rho_cue"]),
        "p1_feedback": hvec(rec["p1_feedback"]),
        "rho_feedback": hvec(rec["rho_feedback"]),
        "stored": hvec(rec["stored"]),
        "motor_vec": hvec(motor),
        "body2": rec["body2"],
        "pending_consumed": pending_after is False,
        "n_ticks": len(ticks),
        "n_v_end_ticks": len(v_end_ticks),
        "rho_after_v_end": None if not v_end_ticks else v_end_ticks[-1]["rho"],
        "last_sensory_rho": None if not ticks else next((t["rho"] for t in reversed(ticks) if t.get("kind") == "sensory"), None),
        "first_win_x": None if not win_xs else win_xs[0],
        "same_ix_values": same_ixs,
    }


def frozen_probe(common: dict[str, Any], handle: str, cue: str, *, tag: str, reset: bool) -> dict[str, Any]:
    ag = load_common(common)
    freeze_plasticity(ag)
    ag.set_action_feedback_enabled(True)
    ag.set_memproj_arm(MEMPROJ_NONE)
    ag.genome.act_recall_mode = ACT_RECALL_OFF
    if reset:
        reset_before_recall(ag)
    parent_h = w_act_hash(ag)
    rec = instrumented_credit(ag, common["world"], handle, cue, tag=tag)
    if w_act_hash(ag) != parent_h:
        raise RuntimeError("W_act_query moved on provenance probe")
    rec["reset"] = bool(reset)
    rec["w_act"] = parent_h
    return rec


def reconstruct(*, wi: int, tmp: str) -> dict[str, Any]:
    p = load_prereg()
    bundle = collect_world(wi=int(wi), tmp=tmp)
    handles = list(bundle["handles"])
    train_h = [vec_hash(x) for _h, x in bundle["train_pairs"]]
    hold_h = [vec_hash(x) for _h, x in bundle["hold_pairs"]]
    pin_train = list(p["pinned_train_hashes"][f"w{wi}"])
    pin_hold = list(p["pinned_hold_hashes"][f"w{wi}"])
    pin_w0 = str(p["pinned_w0_hash"][f"w{wi}"])
    decoder = dict(bundle["decoder"])
    decoder["kind"] = "setup"
    decoder["excluded_from_behavioral_first_match"] = True
    decoder["tm052_train_hash_match"] = train_h == pin_train
    decoder["tm052_hold_hash_match"] = hold_h == pin_hold
    decoder["tm052_w0_hash_match"] = str(bundle["w0_hash"]) == pin_w0
    decoder["passed"] = bool(decoder["tm052_train_hash_match"] and decoder["tm052_hold_hash_match"] and decoder["tm052_w0_hash_match"] and decoder.get("passed"))
    bundle["decoder"] = decoder
    bundle["pin_train"] = pin_train
    bundle["pin_hold"] = pin_hold
    return bundle


def eval_boundary(bundle: dict[str, Any], *, wi: int) -> dict[str, Any]:
    gnd = bundle["gnd"]
    handles = list(bundle["handles"])
    world = gnd["world"]
    cues_dev = list(gnd["dev_cues"])
    hold_cue = str(gnd["hold_cue"])
    native_train = [vec_hash(x) for _h, x in bundle["train_pairs"]]
    native_hold = [vec_hash(x) for _h, x in bundle["hold_pairs"]]
    probe_train = []
    probe_hold = []
    alt_a = []
    alt_b = []
    no_reset_hold = []
    traces = []
    parent = parent_snapshot(bundle["ag_gnd"])
    for i, handle in enumerate(handles):
        tr = frozen_probe(gnd, handle, cues_dev[i], tag=f"pv_tr_{handle}", reset=True)
        ho = frozen_probe(gnd, handle, hold_cue, tag=f"pv_ho_{handle}", reset=True)
        a = frozen_probe(gnd, handle, f"s_alt_{wi}_{i}_a", tag=f"pv_a_{handle}", reset=True)
        b = frozen_probe(gnd, handle, f"s_alt_{wi}_{i}_b", tag=f"pv_b_{handle}", reset=True)
        nr = frozen_probe(gnd, handle, hold_cue, tag=f"pv_nr_{handle}", reset=False)
        probe_train.append(tr["p1_feedback"])
        probe_hold.append(ho["p1_feedback"])
        alt_a.append(a["p1_feedback"])
        alt_b.append(b["p1_feedback"])
        no_reset_hold.append(nr["p1_feedback"])
        if i == 0:
            traces.append({"train": tr, "hold": ho, "alt_a": a, "no_reset_hold": nr})
    mismatch: list[str] = []
    notes: list[str] = []
    if native_train != list(bundle["pin_train"]):
        mismatch.append("native_train_vs_pin")
    if native_hold != list(bundle["pin_hold"]):
        mismatch.append("native_hold_vs_pin")
    if probe_hold != native_hold:
        mismatch.append("frozen_hold_probe_vs_native_hold")
    if probe_train != native_train:
        mismatch.append("frozen_dev_probe_vs_write_last_p1")
    if probe_hold != no_reset_hold:
        mismatch.append("reset_before_recall")
    if alt_a != alt_b:
        notes.append("frozen_wrap_varies_by_cue")
    else:
        notes.append("frozen_wrap_action_invariant")
    if parent["pending"]:
        mismatch.append("parent_pending_not_consumed")
    first = mismatch[0] if mismatch else "no_divergence"
    out = {
        "kind": "scored",
        "id": f"boundary|w{wi}",
        "arm": "boundary",
        "world": int(wi),
        "passed": first not in ("native_train_vs_pin", "native_hold_vs_pin"),
        "cell_code": first,
        "first_mismatch_site": first,
        "mismatch_sites": mismatch,
        "notes": notes,
        "parent": parent,
        "native_train": native_train,
        "native_hold": native_hold,
        "probe_train": probe_train,
        "probe_hold": probe_hold,
        "alt_a": alt_a,
        "alt_b": alt_b,
        "no_reset_hold": no_reset_hold,
        "reset_changes_hold": probe_hold != no_reset_hold,
        "frozen_wrap_action_invariant": alt_a == alt_b,
        "write_equals_frozen_dev_probe": probe_train == native_train,
        "hold_equals_frozen_hold_probe": probe_hold == native_hold,
        "handles": handles,
        "dev_cues": cues_dev,
        "hold_cue": hold_cue,
        "trace0": traces[0] if traces else None,
        "scored_socp": False,
        "W_installed": False,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "floor": float(EPISODE_MATCH_L2),
    }
    assert_finite_record(out, ctx=out["id"])
    return out


