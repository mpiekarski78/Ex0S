def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    ids.extend(
        f"{cond}|{arm}|w{wi}"
        for cond in list(p["conditions"])
        for arm in list(p["arms"])
        for wi in range(int(p["n_worlds"]))
    )
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "arms": list(p["arms"]),
        "conditions": list(p["conditions"]),
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM046 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM046 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def reset_before_recall(ag: NeuralCortex) -> None:
    ag.reset_rho()
    ag._last_p1 = None
    ag.drop_actor_pending()


def w_act_hash(ag: NeuralCortex) -> str:
    return weight_hash(ag._from_t(ag.W_act_query))


def _fresh(tmp: str, tag: str, world: dict[str, Any], *, seed_registry: int) -> NeuralCortex:
    ag = make_cortex(Path(tmp) / tag, genome=genome_for_registry(seed_registry), device="cpu")
    ag.genome.episodic_act_recall = False
    ag.genome.act_score_mode = ACT_SCORE_QUERY
    ag.genome.act_recall_mode = ACT_RECALL_OFF
    ag.bind_actuators(list(world["handles"]))
    ag.set_act_socp_arm("off")
    ag.set_memproj_arm(MEMPROJ_OFF)
    return ag


def _configure(ag: NeuralCortex, arm: str) -> None:
    if arm == "symbolic_oracle":
        ag.genome.act_recall_mode = ACT_RECALL_RAW_P1
        ag.set_memproj_arm(MEMPROJ_OFF)
    elif arm == "opaque_projection":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_BIRTH)
    elif arm == "no_persistent_memory":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_NONE)
    elif arm == "slow_cortex_enabled":
        ag.genome.act_recall_mode = ACT_RECALL_OFF
        ag.set_memproj_arm(MEMPROJ_NONE)
    else:
        raise RuntimeError(arm)


def _other_handle(pairs: list[tuple[str, str]], handle: str) -> str:
    seen: list[str] = []
    for _cue, h in pairs:
        if h not in seen:
            seen.append(h)
    for h in seen:
        if h != handle:
            return h
    return handle


def _brief_meta(meta: dict[str, Any]) -> dict[str, Any]:
    return {
        "memory_path": meta.get("memory_path"),
        "motor_path": meta.get("motor_path"),
        "scoring_address_source": meta.get("scoring_address_source"),
        "retrieved": meta.get("retrieved"),
        "reject_reason": meta.get("reject_reason"),
        "slot": meta.get("slot"),
        "familiar": meta.get("familiar"),
        "scores_before_reinstatement": meta.get("scores_before_reinstatement"),
        "scores_after_reinstatement": meta.get("scores_after_reinstatement"),
    }


def organism_probe(
    ag: NeuralCortex,
    world: dict[str, Any],
    cue: str,
    *,
    tag: str,
    cond: str,
    n_delay: int,
    distractor: str | None,
) -> dict[str, Any]:
    probe = clone_frozen(ag)
    reset_before_recall(probe)
    if cond == "delayed":
        for i in range(int(n_delay)):
            empty_tick(probe, tag=f"{tag}_d{i}")
    elif cond == "distractor" and distractor is not None:
        observe_cue(probe, world, tag=f"{tag}_dist", body=list(MID_BODY), symbols=[distractor])
        probe.drop_actor_pending()
    observe_cue(probe, world, tag=tag, body=list(MID_BODY), symbols=[cue])
    scores, addr, meta = probe.event_memory_scores()
    winner = unique_winner(scores)
    return {
        "winner": winner,
        "scores": {k: float(v) for k, v in scores.items()},
        "addr_hash": hashlib.sha256(np.ascontiguousarray(addr).tobytes()).hexdigest(),
        "telemetry": _brief_meta(meta),
    }


def _score_reinstated(ag: NeuralCortex, p1: np.ndarray) -> tuple[str | None, dict[str, Any]]:
    probe = clone_frozen(ag)
    probe.genome.act_recall_mode = ACT_RECALL_OFF
    probe.set_memproj_arm(MEMPROJ_NONE)
    reset_before_recall(probe)
    probe._last_p1 = np.asarray(p1, dtype=np.float64).copy()
    scores, _addr, meta = probe.event_memory_scores()
    return unique_winner(scores), _brief_meta(meta)


def develop_common(*, wi: int, seed_registry: int, tmp: str, p: dict[str, Any]) -> dict[str, Any]:
    n_handles = int(p["n_handles"])
    n_facts = int(p["n_facts"])
    world = capacity_world(int(wi), DEV_DOMAIN, n_cues=int(n_facts), n_handles=int(n_handles))
    pairs = mapping_pairs(world, flip=False)
    ag = _fresh(tmp, f"common_w{wi}", world, seed_registry=seed_registry)
    handles = list(world["handles"])
    dev_cues = [f"s_dev_{wi}_{i}" for i in range(n_handles)]
    n_rep = int(p["n_dev_repeats"])
    for rep in range(n_rep):
        for i, handle in enumerate(handles):
            teach_one(ag, world, handle, tag=f"dev_w{wi}_{rep}_{i}", symbols=[dev_cues[i]])
    ag.rest_epoch(int(p["n_rest_ticks"]), body=np.asarray(MID_BODY, dtype=np.float64))
    last_p1: dict[str, np.ndarray] = {}
    for ep in ag._episodes:
        if not ep.get("valid"):
            continue
        last_p1[str(ep["handle"])] = np.asarray(ep["p1"], dtype=np.float64).copy()
    handle_hits = []
    all_ok = True
    for handle in handles:
        p1 = last_p1.get(handle)
        if p1 is None:
            all_ok = False
            handle_hits.append({"handle": handle, "ok": False, "winner": None, "reason": "missing_episode"})
            continue
        winner, tel = _score_reinstated(ag, p1)
        ok = winner == handle
        all_ok = all_ok and ok
        handle_hits.append({"handle": handle, "ok": bool(ok), "winner": winner, "telemetry": tel})
    n_ep = len(ag._episodes)
    ag._episodes = []
    ag.opaque.clear()
    reset_before_recall(ag)
    prep_eval(ag)
    snap = ag.checkpoint()
    if snap.get("episodes"):
        raise RuntimeError("common checkpoint still contains episodes")
    decoder = {
        "kind": "decoder",
        "id": f"decoder|w{wi}",
        "arm": "decoder",
        "world": int(wi),
        "passed": bool(all_ok),
        "n_ok": int(sum(1 for h in handle_hits if h["ok"])),
        "n_need": int(n_handles),
        "n_dev_episodes": int(n_ep),
        "handles": handle_hits,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "cell_code": "decoder_ok" if all_ok else "decoder_fail",
    }
    assert_finite_record(decoder, ctx=decoder["id"])
    return {
        "snap": snap,
        "genome": copy.deepcopy(ag.genome),
        "world": world,
        "pairs": pairs,
        "dev_cues": dev_cues,
        "decoder": decoder,
        "w_act_query_hash": w_act_hash(ag),
    }


def load_common(common: dict[str, Any]) -> NeuralCortex:
    ag = NeuralCortex(None, genome=copy.deepcopy(common["genome"]), device="cpu")
    ag.load_checkpoint(common["snap"])
    ag.set_act_socp_arm("off")
    prep_eval(ag)
    return ag


def eval_fact_cell(
    common: dict[str, Any],
    *,
    cond: str,
    arm: str,
    wi: int,
    n_delay: int,
) -> dict[str, Any]:
    cell_id = f"{cond}|{arm}|w{wi}"
    world = common["world"]
    pairs = list(common["pairs"])
    ag = load_common(common)
    parent_h = str(common["w_act_query_hash"])
    if arm in FROZEN_ARMS:
        freeze_plasticity(ag)
    _configure(ag, arm)
    d_w_q = []
    for i, (cue, handle) in enumerate(pairs):
        rec = teach_one(ag, world, handle, tag=f"{cell_id}_{i}", symbols=[cue])
        d_w_q.append(float(rec["d_w_q"]))
    want_pairs = list(pairs)
    if cond == "revision":
        cue0, h0 = pairs[0]
        h1 = _other_handle(pairs, h0)
        rec_r = teach_one(ag, world, h1, tag=f"{cell_id}_rev", symbols=[cue0])
        d_w_q.append(float(rec_r["d_w_q"]))
        want_pairs = [(cue0, h1)] + pairs[1:]
    child_h = w_act_hash(ag)
    frozen_ok = arm not in FROZEN_ARMS or child_h == parent_h
    if arm in FROZEN_ARMS and not frozen_ok:
        raise RuntimeError(f"W_act_query moved on frozen arm {cell_id}")
    dist = "s_dist_" + hashlib.sha256(cell_id.encode()).hexdigest()[:8]
    probe_cond = "immediate" if cond == "revision" else cond
    hits = []
    for i, (cue, handle) in enumerate(want_pairs):
        rec = organism_probe(
            ag,
            world,
            cue,
            tag=f"{cell_id}_p{i}",
            cond=probe_cond,
            n_delay=n_delay,
            distractor=dist if cond == "distractor" else None,
        )
        rec["want"] = handle
        rec["ok"] = rec["winner"] == handle
        hits.append(rec)
    n_ok = sum(1 for h in hits if h["ok"])
    passed = n_ok == len(want_pairs)
    out = {
        "kind": cond,
        "id": cell_id,
        "arm": arm,
        "world": int(wi),
        "passed": bool(passed),
        "n_ok": int(n_ok),
        "n_need": len(want_pairs),
        "n_opaque": len(ag.opaque.rows()),
        "n_episodes": len(ag._episodes),
        "d_w_q": d_w_q,
        "w_act_query_frozen": bool(child_h == parent_h),
        "reset_rho_before_recall": True,
        "probes": hits,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "cell_code": f"{cond}_ok" if passed else f"{cond}_fail",
    }
    assert_finite_record(out, ctx=cell_id)
    return out


def synthetic_grid(
    *,
    decoder_ok: bool = True,
    oracle_immediate_ok: bool = True,
    none_fail_id: str | None = None,
) -> list[dict[str, Any]]:
    cells: list[dict[str, Any]] = []
    for wi in (0, 1):
        cells.append({"id": f"decoder|w{wi}", "arm": "decoder", "kind": "decoder", "passed": bool(decoder_ok)})
    for cond in CONDS:
        for arm in ARMS:
            for wi in (0, 1):
                cid = f"{cond}|{arm}|w{wi}"
                passed = True
                if arm == "symbolic_oracle" and cond == "immediate" and not oracle_immediate_ok:
                    passed = False
                if none_fail_id is not None and cid == none_fail_id:
                    passed = False
                cells.append({"id": cid, "arm": arm, "kind": cond, "passed": passed})
    return cells


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    flags = {
        "n_cells": len(cells),
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "slow_cortex_enabled_is_observational": True,
        "opaque_projection_is_observational": True,
        "necessary_cell": None,
        "separate_candidate_review_open": False,
        "earned_interface": False,
        "earned_kqv": False,
    }
    dec_ids = [f"decoder|w{wi}" for wi in (0, 1)]
    if any(did not in by or not bool(by[did].get("passed")) for did in dec_ids):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    oracle_ids = [f"immediate|symbolic_oracle|w{wi}" for wi in (0, 1)]
    if any(oid not in by or not bool(by[oid].get("passed")) for oid in oracle_ids):
        flags["earned_interface"] = True
        return "generic_reinstatement_fail", "generic_reinstatement_fail", flags
    p = load_prereg()
    for cond in list(p["conditions"]):
        for wi in range(int(p["n_worlds"])):
            oid = f"{cond}|symbolic_oracle|w{wi}"
            nid = f"{cond}|no_persistent_memory|w{wi}"
            o = by.get(oid)
            none = by.get(nid)
            if o is None or none is None:
                return "setup_precondition_fail", "setup_precondition_fail", flags
            if bool(o.get("passed")) and not bool(none.get("passed")):
                flags["necessary_cell"] = nid
                flags["necessary_oracle_cell"] = oid
                flags["condition"] = str(cond)
                flags["world"] = int(wi)
                flags["earned_kqv"] = True
                return "memory_necessary_at", "memory_necessary_at", flags
    return "memory_never_necessary", "memory_never_necessary", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "canonical_cue_probe"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM046 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py drifted; TM046 does not tune K/Q/V")
    if sha_file(TM045_RUNNER) != p["tm045_runner_sha"]:
        raise RuntimeError("TM045 runner must stay frozen")
    if hashlib.sha256(TM045_DEV.read_bytes()).hexdigest() != p["tm045_dev_sha"]:
        raise RuntimeError("TM045 DEV lock must stay frozen")
    if hashlib.sha256(TM045_DEC.read_bytes()).hexdigest() != p["tm045_decision_sha"]:
        raise RuntimeError("TM045 decision lock must stay frozen")
    if sha_file(TM044_RUNNER) != p["tm044_runner_sha"]:
        raise RuntimeError("TM044 runner must stay frozen")
    if hashlib.sha256(TM044_DEC.read_bytes()).hexdigest() != p["tm044_decision_sha"]:
        raise RuntimeError("TM044 decision lock must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("kqv_edit_authorized")):
        raise RuntimeError("TM046 must not authorize K/Q/V edits")
    seed = int(p["seed_registry"])
    if seed in [int(x) for x in p["forbidden_seeds"]]:
        raise RuntimeError("seed collision")
    if "memproj_arm" in GenomeConfig().to_dict():
        raise RuntimeError("memproj must not be a GenomeConfig field")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="os_dev_")
    try:
        commons = {
            wi: develop_common(wi=int(wi), seed_registry=seed, tmp=tmp.name, p=p)
            for wi in range(int(p["n_worlds"]))
        }
        n_delay = int(p["n_delay_ticks"])
        for wi in range(int(p["n_worlds"])):
            cells.append(commons[wi]["decoder"])
        for cond in list(p["conditions"]):
            for arm in list(p["arms"]):
                for wi in range(int(p["n_worlds"])):
                    cells.append(
                        eval_fact_cell(
                            commons[int(wi)],
                            cond=str(cond),
                            arm=str(arm),
                            wi=int(wi),
                            n_delay=n_delay,
                        )
                    )
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    flags["kqv_edited"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "solver_edited": False,
        "tm045_runner_untouched": True,
        "tm044_runner_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


