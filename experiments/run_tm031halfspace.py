def registry_seeds() -> list[int]:
    seeds = [int(s) for s in load_prereg()["registry_seeds"]]
    if len(seeds) != 4:
        raise RuntimeError("need four registry seeds")
    if DEFAULT_SEED_REGISTRY in seeds:
        raise RuntimeError("default seed_registry is not a replicate")
    return seeds


def genome_for_registry(seed_registry: int) -> GenomeConfig:
    g = GenomeConfig()
    birth = g.to_dict()
    g.seed_registry = int(seed_registry)
    if int(seed_registry) == DEFAULT_SEED_REGISTRY:
        raise RuntimeError("default seed_registry forbidden")
    live = g.to_dict()
    for k, v in birth.items():
        if k == "seed_registry":
            continue
        if live.get(k) != v:
            raise RuntimeError(f"genome field {k} changed besides seed_registry")
    return g


def _fresh(
    tmp: str,
    tag: str,
    world: dict[str, Any],
    *,
    mode: str,
    seed_registry: int,
) -> NeuralCortex:
    root = Path(tmp) / tag
    ag = make_cortex(root, genome=genome_for_registry(seed_registry), device="cpu")
    ag.genome.act_recall_mode = str(mode)
    ag.genome.episodic_act_recall = False
    ag.bind_actuators(list(world["handles"]))
    if str(ag.genome.act_score_mode) != ACT_SCORE_QUERY:
        raise RuntimeError("scoring must remain query")
    if int(ag.genome.seed_registry) != int(seed_registry):
        raise RuntimeError("seed_registry did not bind")
    return ag


