def eval_eco(world: dict[str, Any], *, order: str, tag: str, cell_id: str, seed_registry: int) -> dict[str, Any]:
    cue = world["cue_handle"][0]["cue"]
    h1, h2 = world["handles"][0], world["handles"][1]
    if order == "B_then_A":
        h1, h2 = h2, h1
    p = load_prereg()
    with tempfile.TemporaryDirectory(prefix="hs_eco_") as tmp:
        ag = _fresh(tmp, "s", world, mode=TREATMENT_MODE, seed_registry=seed_registry)
