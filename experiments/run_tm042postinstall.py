def load_prereg() -> dict[str, Any]:
    return json.loads(PREREG.read_text(encoding="utf-8"))


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for wi in range(int(p["n_worlds"])):
        for order in list(p["orders"]):
            ids.append(f"natural|c8h2|{order}|w{wi}")
            ids.append(f"natural|c8h4|{order}|w{wi}")
    for ri in list(p["tm039_diagnostic_regs"]):
        for order in list(p["orders"]):
            ids.append(f"mech|tm039|reg{int(ri)}|{order}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM042 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def _seq(pairs: list[tuple[str, str]], order: str) -> list[tuple[str, str]]:
    return list(reversed(pairs)) if order == "B_then_A" else list(pairs)


def _margin() -> dict[str, Any]:
    return load_prereg()["margin"]


def _probe_pairs(ag: Any, world: dict[str, Any], pairs: list[tuple[str, str]], *, tag: str) -> dict[str, Any]:
    m = _margin()
    return canonical_probe_map(
        ag,
        world,
        pairs,
        tag=tag,
        domain=str(world["domain"]),
        geometric_min=float(m["geometric_min"]),
        sigma=float(m["rho_perturb_sigma"]),
        perturb_n=int(m["perturb_n"]),
        perturb_need=int(m["perturb_stable_min"]),
    )


def _other_handle(world: dict[str, Any], handle: str) -> str:
    hs = [str(h) for h in world["handles"]]
    return hs[(hs.index(str(handle)) + 1) % len(hs)]


def solver_handles_in_act(ag: Any, world: dict[str, Any]) -> list[str]:
    allowed = {str(h) for h in world["handles"]}
    leaked: list[str] = []
    for k in ag.motor_vocab:
        lk = str(k).lower()
        if str(k) not in allowed or any(b in lk for b in BANNED_SOLVER_TOKENS):
            leaked.append(str(k))
    return sorted(leaked)


def _solver_slice(rec: dict[str, Any] | None) -> dict[str, Any]:
    if not rec:
        return {"status": None, "applied": False}
    return {
        "status": rec.get("status"),
        "applied": bool(rec.get("applied")),
        "reject_reason": rec.get("reject_reason"),
        "objective": rec.get("objective"),
        "frobenius_delta": rec.get("frobenius_delta"),
        "frobenius_delta_after_clip": rec.get("frobenius_delta_after_clip"),
        "n_constraints": rec.get("n_constraints"),
        "violations_before": rec.get("violations_before"),
        "violations_after": rec.get("violations_after"),
        "solver_status": rec.get("solver_status"),
    }


def _atomic_ok(rows: list[dict[str, Any]]) -> bool:
    for r in rows:
        if bool(r.get("applied")):
            if int(r.get("violations_after") or 0) != 0:
                return False
        else:
            if r.get("w_hash_before") and r.get("w_hash_after") and r["w_hash_before"] != r["w_hash_after"]:
                return False
    return True


def extra_pair(tag: str, world: dict[str, Any]) -> tuple[str, str]:
    cue = "s_new_" + hashlib.sha256(tag.encode()).hexdigest()[:9]
    return cue, str(world["handles"][0])


def _continue_after_install(
    ag: Any,
    world: dict[str, Any],
    *,
    retain_pairs: list[tuple[str, str]],
    new_pairs: list[tuple[str, str]],
    slog: list[dict[str, Any]],
    n_log_at_install: int,
    tag: str,
    installed_w_hash: str,
    pre_install_w_hash: str,
    solver_rec: dict[str, Any] | None,
) -> dict[str, Any]:
    p = load_prereg()
    old = _probe_pairs(ag, world, retain_pairs, tag=f"{tag}_old") if retain_pairs else {
        "ranking_ok": True, "n_probe_correct": 0, "probes": []
    }
    fam_before = None
    if retain_pairs:
        fam_before = canonical_cue_probe(ag, world, retain_pairs[0][0], tag=f"{tag}_fam0", want=retain_pairs[0][1])
    if not new_pairs:
        new_pairs = [extra_pair(tag, world)]
    cue_n, h_n = new_pairs[0]
    teach_one(ag, world, h_n, tag=f"{tag}_new", symbols=[cue_n])
    post_credit = weight_hash(ag._from_t(ag.W_act_query))
    newp = canonical_cue_probe(ag, world, cue_n, tag=f"{tag}_newq", want=h_n)
    rev_cue, rev_old = retain_pairs[0]
    rev_new = _other_handle(world, rev_old)
    teach_one(ag, world, rev_new, tag=f"{tag}_rev", symbols=[rev_cue])
    revp = canonical_cue_probe(ag, world, rev_cue, tag=f"{tag}_revq", want=rev_new)
    rest = ag.rest_epoch(int(p["n_rest_ticks"]))
    later_log = slog[n_log_at_install:]
    novel = f"novel_{tag}"
    observe_cue(ag, world, tag=f"{tag}_nov", body=list(MID_BODY), symbols=[novel])
    nov = canonical_cue_probe(ag, world, novel, tag=f"{tag}_novq")
    fam_after = canonical_cue_probe(ag, world, retain_pairs[0][0], tag=f"{tag}_fam1", want=rev_new if retain_pairs[0][0] == rev_cue else retain_pairs[0][1])
    leaked = solver_handles_in_act(ag, world)
    retain_ok = bool(old["ranking_ok"]) and int(old["n_probe_correct"]) == len(retain_pairs)
    new_ok = bool(newp["winner"] == h_n)
    rev_ok = bool(revp["winner"] == rev_new)
    atomic = _atomic_ok(later_log)
    novelty_unfamiliar = bool(not nov.get("familiar"))
    fam_unchanged = True
    if fam_before is not None:
        fam_unchanged = bool(fam_before.get("familiar")) and bool(fam_after.get("familiar"))
    continuity_ok = bool(retain_ok and new_ok and rev_ok and atomic and novelty_unfamiliar and fam_unchanged and not leaked)
    return {
        "handoff": {
            "pre_install_w_hash": pre_install_w_hash,
            "solver": _solver_slice(solver_rec),
            "installed_w_hash": installed_w_hash,
            "later_credit": {"cue": cue_n, "handle": h_n, "w_hash_after": post_credit},
            "post_credit_w_hash": post_credit,
            "old_behavior": {
                "ranking_ok": retain_ok,
                "n_probe_correct": int(old["n_probe_correct"]),
                "n_need": len(retain_pairs),
            },
            "new_behavior": {
                "cue": cue_n,
                "want": h_n,
                "winner": newp["winner"],
                "ranking_ok": new_ok,
                "retrieval_path": newp["retrieval_path"],
                "retrieved_slot": newp["retrieved_slot"],
                "live_p1_hash": newp["live_p1_hash"],
                "scoring_address_hash": newp["scoring_address_hash"],
            },
        },
        "retain_ok": retain_ok,
        "new_mapping_ok": new_ok,
        "reversal_ok": rev_ok,
        "subsequent_fallback_atomic": atomic,
        "n_subsequent_socp_calls": len(later_log),
        "n_subsequent_applied": sum(1 for r in later_log if bool(r.get("applied"))),
        "novelty_unfamiliar": novelty_unfamiliar,
        "novelty_path": nov.get("retrieval_path"),
        "familiarity_unchanged": fam_unchanged,
        "solver_handles_in_act": leaked,
        "solver_handles_never_in_act": not leaked,
        "n_rest_replay": int((rest or {}).get("n_replay") or 0),
        "continuity_ok": continuity_ok,
        "old_probes": old.get("probes"),
        "reversal": {"cue": rev_cue, "want": rev_new, "winner": revp["winner"]},
    }


def eval_natural(
    *,
    world: dict[str, Any],
    order: str,
    wi: int,
    label: str,
    seed_registry: int,
    tmp: str,
) -> dict[str, Any]:
    cell_id = f"natural|{label}|{order}|w{wi}"
    pairs = mapping_pairs(world, flip=False)
    seq = _seq(pairs, order)
    ag = _fresh(tmp, cell_id, world, seed_registry=seed_registry)
    set_arm(ag, "fallback_joint")
    slog = bind_socp_logger(ag)
    taught: list[tuple[str, str]] = []
    install: dict[str, Any] | None = None
    for i, (cue, handle) in enumerate(seq):
        pre = weight_hash(ag._from_t(ag.W_act_query))
        n_before = len(slog)
        teach_one(ag, world, handle, tag=f"{cell_id}_{i}", symbols=[cue])
        taught.append((cue, handle))
        new_rows = slog[n_before:]
        applied = [r for r in new_rows if bool(r.get("applied"))]
        if applied:
            rec = applied[0]
            install = {
                "pre_install_w_hash": pre,
                "installed_w_hash": weight_hash(ag._from_t(ag.W_act_query)),
                "solver_rec": rec,
                "teach_index": int(i),
                "n_log": len(slog),
            }
            break
    out: dict[str, Any] = {
        "kind": "natural",
        "id": cell_id,
        "arm": "fallback_joint",
        "order": order,
        "world": int(wi),
        "label": label,
        "evidence": "untouched_fresh",
        "installed": bool(install),
        "n_store_violations": int(ag._count_store_violations()),
        "candidate_v40_lock": False,
        "not_an_exact_projector": True,
        "behavioral_scorer": "actuator_decision_scores",
    }
    if install is None:
        out["passed"] = False
        out["cell_code"] = "postinstall_not_exercised"
        out["continuity_ok"] = False
        out["handoff"] = None
        assert_finite_record(out, ctx=cell_id)
        return out
    remaining = seq[int(install["teach_index"]) + 1 :]
    cont = _continue_after_install(
        ag,
        world,
        retain_pairs=list(taught),
        new_pairs=remaining,
        slog=slog,
        n_log_at_install=int(install["n_log"]),
        tag=f"{cell_id}_c",
        installed_w_hash=str(install["installed_w_hash"]),
        pre_install_w_hash=str(install["pre_install_w_hash"]),
        solver_rec=install["solver_rec"],
    )
    out.update(cont)
    out["passed"] = bool(cont["continuity_ok"])
    out["cell_code"] = "postinstall_natural_ok" if out["passed"] else "postinstall_natural_later_fail"
    assert_finite_record(out, ctx=cell_id)
    return out


