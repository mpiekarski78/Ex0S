def smoke() -> dict[str, Any]:
    assert load_prereg()["manifest_sha"] == MANIFEST_SHA
    assert len(expected_cell_ids()) == EXPECTED_N_CELLS
    p = load_prereg()
    world = capacity_world(0, DEV_DOMAIN, n_cues=2, n_handles=2)
    with tempfile.TemporaryDirectory(prefix="pi_smk_") as tmp:
        rec = eval_natural(
            world=world,
            order="A_then_B",
            wi=0,
            label="smk",
            seed_registry=int(p["seed_registry"]),
            tmp=tmp,
        )
    return {
        "smoke_ok": True,
        "cell_code": rec.get("cell_code"),
        "installed": bool(rec.get("installed")),
        "raw_score_leak": refuse_raw_scores(THIS),
        "query_mode": ACT_SCORE_QUERY,
        "hard_budget": int(EPISODE_REPLAY_EPOCHS),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_results_md(out)
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "candidate_v40_lock": False,
                    "lineage_stop": out["lineage_stop"],
                    "n_natural_installed": out["phase_flags"]["n_natural_installed"],
                },
                indent=2,
            )
        )
        return
    ap.print_help()


if __name__ == "__main__":
    main()
