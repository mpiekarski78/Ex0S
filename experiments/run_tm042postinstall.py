def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    nat = [c for c in cells if c["kind"] == "natural"]
    mech = [c for c in cells if c["kind"] == "mechanistic"]
    nat_inst = [c for c in nat if bool(c.get("installed"))]
    mech_inst = [c for c in mech if bool(c.get("installed"))]
    flags = {
        "n_cells": len(cells),
        "n_natural": len(nat),
        "n_mechanistic": len(mech),
        "n_natural_installed": len(nat_inst),
        "n_mechanistic_installed": len(mech_inst),
        "natural_continuity_ok": bool(nat_inst) and all(bool(c.get("continuity_ok")) for c in nat_inst),
        "mechanistic_continuity_ok": bool(mech_inst) and all(bool(c.get("continuity_ok")) for c in mech_inst),
        "lineage_stop": "canonical_r2_later_learning_not_exercised",
        "candidate_v40_lock": False,
        "candidate_discussion_open": False,
        "mechanistic_is_not_untouched_generalization": True,
    }
    if not nat_inst:
        return "postinstall_not_exercised", "postinstall_not_exercised", flags
    if not flags["natural_continuity_ok"]:
        return "postinstall_natural_later_fail", "postinstall_natural_later_fail", flags
    if len(mech_inst) != len(mech):
        return "postinstall_mech_install_fail", "postinstall_mech_install_fail", flags
    if not flags["mechanistic_continuity_ok"]:
        return "postinstall_mech_later_fail", "postinstall_mech_later_fail", flags
    flags["candidate_discussion_open"] = True
    return "postinstall_continuity_pass", "postinstall_continuity_pass", flags


def refuse_raw_scores(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            if isinstance(func, ast.Attribute) and func.attr == "actuator_scores":
                bad.append(f"{path.name}:{node.lineno}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM042 runner SHA drifted after freeze push")
    if sha_file(NEURAL) != p["frozen_neural_sha"]:
        raise RuntimeError("neural_cortex.py must not change")
    if sha_file(SOLVER) != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if sha_file(CANONICAL) != p["canonical_probe_sha"]:
        raise RuntimeError("canonical_act_probe.py must not change")
    if hashlib.sha256(R2_DEC.read_bytes()).hexdigest() != p["r2_decision_sha"]:
        raise RuntimeError("R2 decision SHA drifted")
    if hashlib.sha256(R2_DEV.read_bytes()).hexdigest() != p["r2_dev_sha"]:
        raise RuntimeError("R2 DEV SHA drifted")
    if sha_file(R2_RUNNER) != p["r2_runner_sha"]:
        raise RuntimeError("R2 runner SHA drifted")
    if hashlib.sha256(TM039_DEC.read_bytes()).hexdigest() != p["tm039_decision_sha"]:
        raise RuntimeError("TM039 decision SHA drifted")
    if sha_file(TM039_RUNNER) != p["tm039_runner_sha"]:
        raise RuntimeError("TM039 runner SHA drifted")
    leak = refuse_raw_scores(THIS)
    if leak:
        raise RuntimeError(f"raw actuator_scores: {leak}")
    seed = int(p["seed_registry"])
    if seed in (
        int(p["default_seed_registry_forbidden"]),
        int(p["tm040_seed_registry_forbidden"]),
        int(p["r2_seed_registry_forbidden"]),
    ):
        raise RuntimeError("seed collision")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="pi_dev_")
    try:
        for wi in range(int(p["n_worlds"])):
            for order in list(p["orders"]):
                for spec in list(p["natural_scales"]):
                    world = capacity_world(wi, DEV_DOMAIN, n_cues=int(spec["n_cues"]), n_handles=int(spec["n_handles"]))
                    cells.append(
                        eval_natural(
                            world=world,
                            order=str(order),
                            wi=int(wi),
                            label=str(spec["label"]),
                            seed_registry=seed,
                            tmp=tmp.name,
                        )
                    )
        seeds = [int(s) for s in p["tm039_registry_seeds"]]
        for ri, seed_m in zip([int(x) for x in p["tm039_diagnostic_regs"]], seeds):
            for order in list(p["orders"]):
                cells.append(
                    eval_mech(order=str(order), reg=int(ri), seed_registry=int(seed_m), tmp=tmp.name)
                )
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v40_lock"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "lineage_stop": "canonical_r2_later_learning_not_exercised",
        "candidate_v40_lock": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "neural_edited": False,
        "solver_edited": False,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


