def synthetic_grid(*, decoder_ok: bool = True, code: str = "coverage_generalizes") -> list[dict[str, Any]]:
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    n_seeds = int(p["n_curve_seeds"])
    n_worlds = int(p["n_worlds"])
    cells: list[dict[str, Any]] = []
    for si in range(n_seeds):
        for wi in range(n_worlds):
            cells.append(
                {
                    "id": f"decoder|s{si}|w{wi}",
                    "arm": "decoder",
                    "kind": "setup",
                    "passed": bool(decoder_ok),
                    "excluded_from_behavioral_first_match": True,
                }
            )
    max_n = max(n_grid)
    for n in n_grid:
        for si in range(n_seeds):
            for wi in range(n_worlds):
                hold_perfect = False
                ref_ok = True
                feasible = True
                train_ok = True
                if code == "coverage_infeasible":
                    feasible = False
                    train_ok = False
                elif code == "reference_interference":
                    ref_ok = False
                elif code == "no_transfer":
                    hold_perfect = False
                elif code == "seed_dependent":
                    hold_perfect = n == max_n and si == 0
                elif code == "coverage_generalizes":
                    hold_perfect = n == max_n
                elif code == "setup_precondition_fail":
                    hold_perfect = False
                if not feasible:
                    cc = "n_infeasible"
                elif not ref_ok:
                    cc = "n_ref_break"
                elif train_ok and hold_perfect:
                    cc = "n_generalizes"
                elif train_ok:
                    cc = "n_train_only"
                else:
                    cc = "n_train_fail"
                n_hold_need = int(p["n_hold_contexts_per_action"]) * int(p["n_handles"])
                n_hold_ok = n_hold_need if hold_perfect else 1
                cells.append(
                    {
                        "id": f"n{n}|s{si}|w{wi}",
                        "arm": f"n{n}",
                        "kind": "scored",
                        "n": int(n),
                        "passed": bool(feasible and ref_ok and train_ok),
                        "cell_code": cc,
                        "feasible": bool(feasible),
                        "train": {"n_ok": int(n) * int(p["n_handles"]) if train_ok else 0, "n_need": int(n) * int(p["n_handles"])},
                        "hold": {"n_ok": int(n_hold_ok), "n_need": int(n_hold_need)},
                        "reference": {"n_ok": int(p["n_handles"]) if ref_ok else 0, "n_need": int(p["n_handles"])},
                    }
                )
    return cells


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    by = {c["id"]: c for c in cells}
    p = load_prereg()
    n_grid = [int(x) for x in p["n_grid"]]
    n_seeds = int(p["n_curve_seeds"])
    n_worlds = int(p["n_worlds"])
    max_n = max(n_grid)
    flags = {
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
        "earned_kqv": False,
        "earned_learned_addressing": False,
        "earned_second_decoder": False,
        "install_W_star": False,
        "socp_extended": False,
        "n_dev_repeats_increased": False,
        "n_fitted_as_organism_constant": False,
        "episodic_loop_complete": False,
        "setup_excluded_from_behavioral_first_match": True,
        "held_out_never_in_constraints": True,
        "investigate_representation_invariance": False,
        "generic_consolidation_plausible": False,
    }
    for si in range(n_seeds):
        for wi in range(n_worlds):
            dec = by.get(f"decoder|s{si}|w{wi}")
            if dec is None or not bool(dec.get("passed")):
                return "setup_precondition_fail", "setup_precondition_fail", flags

    def scored(n: int) -> list[dict[str, Any]]:
        return [by[f"n{n}|s{si}|w{wi}"] for si in range(n_seeds) for wi in range(n_worlds)]

    all_scored = [c for n in n_grid for c in scored(n)]
    if any(not bool(c.get("feasible")) for c in all_scored):
        return "coverage_infeasible", "coverage_infeasible", flags
    if any(int((c.get("reference") or {}).get("n_ok") or 0) < int((c.get("reference") or {}).get("n_need") or 1) for c in all_scored):
        return "reference_interference", "reference_interference", flags
    top = scored(max_n)
    hold_perfect = [
        int((c.get("hold") or {}).get("n_ok") or 0) == int((c.get("hold") or {}).get("n_need") or 1) for c in top
    ]
    train_perfect = [
        int((c.get("train") or {}).get("n_ok") or 0) == int((c.get("train") or {}).get("n_need") or 1) for c in top
    ]
    if all(hold_perfect) and all(train_perfect):
        flags["generic_consolidation_plausible"] = True
        return "coverage_generalizes", "coverage_generalizes", flags
    if any(hold_perfect) and not all(hold_perfect):
        return "seed_dependent", "seed_dependent", flags
    flags["investigate_representation_invariance"] = True
    return "no_transfer", "no_transfer", flags


def refuse_runner_leaks(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    bad: list[str] = []

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name in ("retrieve", "retrieve_by_query", "actuator_scores", "_run_joint_socp_consolidation"):
                bad.append(f"{path.name}:{node.lineno}:{name}")
            self.generic_visit(node)

        def visit_Assign(self, node: ast.Assign) -> None:
            for t in node.targets:
                if isinstance(t, ast.Attribute) and t.attr in (
                    "_last_p1",
                    "_last_key_rho",
                    "W_k",
                    "W_q",
                    "W_v",
                    "W_act_query",
                ):
                    bad.append(f"{path.name}:{t.lineno}:assign_{t.attr}")
            self.generic_visit(node)

    V().visit(tree)
    return bad


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and frozen != "PLACEHOLDER" and sha_file(THIS) != frozen:
        raise RuntimeError("TM053 runner SHA drifted after freeze push")
    if hashlib.sha256(SOLVER.read_bytes()).hexdigest() != p["joint_socp_sha"]:
        raise RuntimeError("joint_socp.py must not change")
    if hashlib.sha256(NEURAL.read_bytes()).hexdigest() != p["neural_cortex_sha"]:
        raise RuntimeError("neural_cortex.py must stay frozen")
    if sha_file(TM052_RUNNER) != p["tm052_runner_sha"]:
        raise RuntimeError("TM052 runner must stay frozen")
    if hashlib.sha256(TM052_DEV.read_bytes()).hexdigest() != p["tm052_dev_sha"]:
        raise RuntimeError("TM052 DEV lock must stay frozen")
    if hashlib.sha256(TM052_DEC.read_bytes()).hexdigest() != p["tm052_decision_sha"]:
        raise RuntimeError("TM052 decision lock must stay frozen")
    if hashlib.sha256(TM052_PREREG.read_bytes()).hexdigest() != p["tm052_prereg_sha"]:
        raise RuntimeError("TM052 prereg must stay frozen")
    if hashlib.sha256(TM052_ADD.read_bytes()).hexdigest() != p["tm052_addendum_sha"]:
        raise RuntimeError("TM052 addendum must stay frozen")
    if sha_file(TM051_RUNNER) != p["tm051_runner_sha"]:
        raise RuntimeError("TM051 runner must stay frozen")
    if sha_file(TM049_RUNNER) != p["tm049_runner_sha"]:
        raise RuntimeError("TM049 runner must stay frozen")
    if sha_file(TM046_RUNNER) != p["tm046_runner_sha"]:
        raise RuntimeError("TM046 runner must stay frozen")
    leak = refuse_runner_leaks(THIS)
    if leak:
        raise RuntimeError(f"runner leak: {leak}")
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    if bool(p.get("neural_edit_authorized")) or bool(p.get("decoder_edit_authorized")):
        raise RuntimeError("TM053 must not edit neural or train a new decoder")
    if bool(p.get("solver_edit_authorized")) or bool(p.get("install_oracle_authorized")):
        raise RuntimeError("TM053 must not extend or install SOCP")
    if bool(p.get("n_dev_repeats_increase_authorized")) or bool(p.get("n_as_organism_constant_authorized")):
        raise RuntimeError("TM053 must not increase n_dev_repeats or fit N")
    if int(p["n_dev_repeats"]) != 4:
        raise RuntimeError("n_dev_repeats must stay 4")
    if [int(x) for x in p["n_grid"]] != list(N_GRID):
        raise RuntimeError("N grid drifted")
    if "action_feedback_enabled" in GenomeConfig().to_dict():
        raise RuntimeError("action_feedback must not be a GenomeConfig field")
    if "action_feedback" in ACT_RECALL_MODES:
        raise RuntimeError("action_feedback must not be an ACT_RECALL_MODE")
    dec052 = json.loads(TM052_DEC.read_text(encoding="utf-8"))
    add052 = json.loads(TM052_ADD.read_text(encoding="utf-8"))
    if dec052["decision"]["code"] != "shared_W_star_satisfies":
        raise RuntimeError("TM052 first-match must stay frozen")
    if add052["interpretation"] != "sampled_capacity_without_generalizable_grounding":
        raise RuntimeError("TM052 addendum interpretation must stay frozen")
    if bool(add052.get("install_socp_not_licensed")) is not True:
        raise RuntimeError("TM052 must not license installing SOCP")
    ids = expected_cell_ids()
    cells: list[dict[str, Any]] = []
    tmp = tempfile.TemporaryDirectory(prefix="cv_dev_")
    try:
        bundles = []
        seeds = [int(s) for s in p["curve_seeds"]]
        for si, seed in enumerate(seeds):
            for wi in range(int(p["n_worlds"])):
                bundles.append(collect_bundle(si=int(si), wi=int(wi), seed=int(seed), tmp=tmp.name))
        for bundle in bundles:
            cells.append(bundle["decoder"])
        for n in [int(x) for x in p["n_grid"]]:
            for bundle in bundles:
                cells.append(eval_n(bundle, n=int(n)))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    code, then, flags = _decision(cells)
    flags["candidate_v41_lock"] = False
    flags["new_decoder"] = False
    flags["install_W_star"] = False
    flags["n_fitted_as_organism_constant"] = False
    clean, status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_setup_cells": N_SETUP_CELLS,
        "n_scored_cells": N_SCORED_CELLS,
        "cells": cells,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "candidate_v41_lock": False,
        "kqv_edited": False,
        "decoder_retrained": False,
        "new_decoder": False,
        "install_W_star": False,
        "socp_extended": False,
        "n_fitted_as_organism_constant": False,
        "clean_tree": bool(clean),
        "clean_tree_status": status,
        "solver_edited": False,
        "tm052_runner_untouched": True,
        "neural_untouched": True,
    }


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    if CANDIDATE.exists():
        raise RuntimeError("refuse cortex.candidate.v41.lock")
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


