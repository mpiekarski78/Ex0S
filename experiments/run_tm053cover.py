def write_results_md(out: dict[str, Any]) -> None:
    p = load_prereg()
    cells = {c["id"]: c for c in out["cells"]}
    n_grid = [int(x) for x in p["n_grid"]]
    n_seeds = int(p["n_curve_seeds"])
    n_worlds = int(p["n_worlds"])
    lines = [
        "# TM.0.53.COVER results",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        "Product **0.0.004**. No v41 lock. W* not installed. Existing joint SOCP only. N is not an organism constant.",
        "TM052 first-match `shared_W_star_satisfies` unchanged. Held-out contexts were never constraints.",
        "",
        "## Curve (mean across seeds × worlds)",
        "",
        "| N | Train | Hold | Hold4 | Refs | Feasible |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for n in n_grid:
        recs = [cells[f"n{n}|s{si}|w{wi}"] for si in range(n_seeds) for wi in range(n_worlds)]
        def avg(key: str, field: str) -> str:
            vals = [int(r[key]["n_ok"]) / max(int(r[key]["n_need"]), 1) for r in recs]
            return f"{sum(vals)/len(vals):.2f}"
        feas = sum(1 for r in recs if r.get("feasible"))
        lines.append(
            f"| {n} | {avg('train','n_ok')} | {avg('hold','n_ok')} | {avg('hold4','n_ok')} | {avg('reference','n_ok')} | {feas}/{len(recs)} |"
        )
    lines.extend(["", "## What this is not", "", "Not an installed oracle, not a fitted N, not a second decoder, not a v41 candidate.", ""])
    RESULT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


