def mean_or_none(xs: list[float]) -> float | None:
    return None if not xs else float(sum(xs) / len(xs))


def min_or_none(xs: list[float]) -> float | None:
    return None if not xs else float(min(xs))


def action_geometry(pairs: list[tuple[str, np.ndarray]]) -> dict[str, Any]:
    xs = [(str(h), unit_or_zero(x, int(np.asarray(x).reshape(-1).shape[0]))) for h, x in pairs]
    within: list[float] = []
    between: list[float] = []
    for i in range(len(xs)):
        for j in range(i + 1, len(xs)):
            d = float(np.linalg.norm(xs[i][1] - xs[j][1]))
            if xs[i][0] == xs[j][0]:
                within.append(d)
            else:
                between.append(d)
    return {
        "within_l2_mean": mean_or_none(within),
        "within_l2_min": min_or_none(within),
        "between_l2_mean": mean_or_none(between),
        "between_l2_min": min_or_none(between),
        "n_within": len(within),
        "n_between": len(between),
    }


def score_eval(W: np.ndarray, pairs: list[tuple[str, np.ndarray]], vocab: dict[str, np.ndarray]) -> dict[str, Any]:
    rec = score_set(W, pairs, vocab)
    margins = [float(geometric_margin(W, x, h, vocab)) for h, x in pairs]
    rec["min_margin"] = min_or_none(margins)
    rec["mean_margin"] = mean_or_none(margins)
    rec["n_ok_over_need"] = f"{rec['n_ok']}/{rec['n_need']}"
    return rec


def collect_wraps(
    common: dict[str, Any],
    cues_by_handle: dict[str, list[str]],
    *,
    tag: str,
) -> list[tuple[str, np.ndarray, str]]:
    world = common["world"]
    handles = list(common["handles"])
    parent = load_common(common)
    freeze_plasticity(parent)
    parent.set_action_feedback_enabled(True)
    parent.set_memproj_arm(MEMPROJ_NONE)
    parent.genome.act_recall_mode = ACT_RECALL_OFF
    reset_before_recall(parent)
    parent_h = w_act_hash(parent)
    out: list[tuple[str, np.ndarray, str]] = []
    for handle in handles:
        for cue in cues_by_handle[handle]:
            ag = load_common(common)
            freeze_plasticity(ag)
            ag.set_action_feedback_enabled(True)
            ag.set_memproj_arm(MEMPROJ_NONE)
            ag.genome.act_recall_mode = ACT_RECALL_OFF
            reset_before_recall(ag)
            rec = credit_tagged(ag, world, handle, cue, tag=f"{tag}_{handle}_{cue}")
            if w_act_hash(ag) != parent_h:
                raise RuntimeError("W_act_query moved while collecting wraps")
            p1 = rec["p1_feedback"]
            if p1 is None:
                raise RuntimeError(f"missing wrap p1 for {handle} {cue}")
            out.append((str(handle), np.asarray(p1, dtype=np.float64).copy(), str(cue)))
    if w_act_hash(parent) != parent_h:
        raise RuntimeError("parent W_act_query moved")
    return out


