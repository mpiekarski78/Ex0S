    train_pairs: list[tuple[str, np.ndarray]] = []
    for h in handles:
        rows = bundle["train_by_h"][h]
        if len(rows) < n:
            raise RuntimeError(f"train pool shorter than N={n}")
        train_pairs.extend(rows[:n])
    cons_pairs = list(bundle["ref_pairs"]) + list(train_pairs)
    parent_h = str(bundle["w0_hash"])
    rec, W_star = solve_ceiling(bundle["W0"], cons_pairs, bundle["vocab"])
    if w_act_hash(bundle["ag_ref"]) != parent_h:
        raise RuntimeError("W_act_query installed or moved")
    feasible = bool(rec.get("feasible"))
    if W_star is None:
        W_use = bundle["W0"]
        train_sc = score_eval(W_use, train_pairs, bundle["vocab"])
        hold_sc = score_eval(W_use, list(bundle["hold_pairs"]), bundle["vocab"])
        hold4_sc = score_eval(W_use, list(bundle["hold4_pairs"]), bundle["vocab"])
        ref_sc = score_eval(W_use, list(bundle["ref_pairs"]), bundle["vocab"])
