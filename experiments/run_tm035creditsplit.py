def identity_sha(payload: dict[str, Any]) -> str:
    blob = json.dumps(payload, sort_keys=True, default=_json_default).encode()
    return hashlib.sha256(blob).hexdigest()


def identities_match(a: dict[str, Any], b: dict[str, Any]) -> bool:
    return identity_sha(a) == identity_sha(b)


def newest_slot(ag: NeuralCortex) -> int | None:
    best_i: int | None = None
    best_age = -1
    for i, ep in enumerate(ag._episodes):
        if not ep.get("valid"):
            continue
        age = int(ep["age"])
        if age > best_age:
            best_age = age
            best_i = int(i)
    return best_i


def protected_slots(parent_rows: list[dict[str, Any]]) -> list[int]:
    return [int(r["slot"]) for r in parent_rows if not bool(r["store_violation"])]


def broke_protected(
    *,
    protected: list[int],
    new_slot: int | None,
    after_rows: list[dict[str, Any]],
) -> tuple[bool, list[int]]:
    by_slot = {int(r["slot"]): r for r in after_rows}
    broke: list[int] = []
    for slot in protected:
        if new_slot is not None and int(slot) == int(new_slot):
            continue
        row = by_slot.get(int(slot))
        if row is None:
            continue
        if bool(row["store_violation"]):
            broke.append(int(slot))
    return bool(broke), broke


def bind_component(ag: NeuralCortex, arm: str) -> None:
    if arm == "complete":
        return
    if arm not in ARMS:
        raise ValueError(arm)

    def wrapped(
        p1: np.ndarray,
        handle: str,
        adv: float,
        eta_a: float,
        *,
        event_key: np.ndarray | None = None,
        key_rho: np.ndarray | None = None,
    ) -> dict[str, Any] | None:
        if float(np.max(np.abs(p1))) <= ELIG_EPS or ag._resting:
            return None
        ag._episode_write(p1, handle, adv, event_key=event_key, key_rho=key_rho)
        if arm == "write_only":
            return None
        if arm == "oneshot_only":
            if ag._act_ranking_error(p1, handle, adv):
                ag._apply_act_query_update(p1, handle, adv, eta_a, mix_slow=False)
            return None
        if arm == "burst_only":
            return ag._run_v37_awake_rehearsal_burst(skip_p1=p1, skip_handle=handle)
        raise RuntimeError(arm)

    ag._credit_act_p1_episode = wrapped  # type: ignore[method-assign]


def uses_native_credit(ag: NeuralCortex) -> bool:
    fn = getattr(ag._credit_act_p1_episode, "__func__", ag._credit_act_p1_episode)
    return fn is NeuralCortex._credit_act_p1_episode


def classify_world(arm_broke: dict[str, bool]) -> str:
    complete_broke = bool(arm_broke["complete"])
    if not complete_broke:
        return "no_rebreak"
    write_broke = bool(arm_broke["write_only"])
    shot_broke = bool(arm_broke["oneshot_only"])
    burst_broke = bool(arm_broke["burst_only"])
    if write_broke:
        return "write_causal"
    if shot_broke and burst_broke:
        return "mixed_oneshot_and_burst"
    if shot_broke and not burst_broke:
        return "oneshot_causal"
    if burst_broke and not shot_broke:
        return "burst_causal"
    return "interaction_only"


def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids: list[str] = []
    for ri, _s in enumerate(p["registry_seeds"]):
        for order in list(p["orders"]):
            for arm in ARMS:
                ids.append(f"split|c8|{order}|reg{ri}|{arm}")
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "registry_seeds": list(p["registry_seeds"]),
        "arms": list(ARMS),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM035 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def _teach_prefix(
    ag: NeuralCortex,
    world: dict[str, Any],
    seq: list[tuple[str, str]],
    *,
    tag: str,
) -> list[dict[str, Any]]:
    taught: list[dict[str, Any]] = []
    for i, (cue, handle) in enumerate(seq):
        t = teach_one(ag, world, handle, tag=f"{tag}_{i}", symbols=[cue])
        taught.append(
            {
                "cue": cue,
                "handle": handle,
                "adv": float(t["adv"]),
                "n_episodes": len(ag._episodes),
            }
        )
    return taught


def _score_arm(
    *,
    twin: NeuralCortex,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    taught: list[dict[str, Any]],
    parent_rows: list[dict[str, Any]],
    protected: list[int],
    tag: str,
) -> dict[str, Any]:
    new_slot = newest_slot(twin)
    rows = stored_rows(twin)
    broke, broke_slots = broke_protected(protected=protected, new_slot=new_slot, after_rows=rows)
    measured_before = clone_identity(twin)
    probe_ag = clone_plastic(twin.checkpoint(), copy.deepcopy(twin.genome))
    live = live_probes(probe_ag, world, pairs, taught, tag=tag)
    if not identities_match(measured_before, clone_identity(twin)):
        raise RuntimeError(f"measured arm mutated by probes {tag}")
    rec = {
        "new_slot": new_slot,
        "protected_slots": list(protected),
        "previously_correct_broke": bool(broke),
        "broke_slots": broke_slots,
        "n_store_violations": int(twin._count_store_violations()),
        "n_episodes": len(twin._episodes),
        "stored_rows": rows,
        "parent_rows": parent_rows,
        "live_ranking_ok": bool(live["ranking_ok"]),
        "n_probe_correct": int(live["n_probe_correct"]),
        "min_normalized_geometric_margin": float(live["min_normalized_geometric_margin"]),
        "probes": live["probes"],
        "probes_on_another_clone": True,
        "measured_unchanged_after_probes": True,
    }
    return rec


def eval_world(
    *,
    world: dict[str, Any],
    pairs: list[tuple[str, str]],
    order: str,
    seed_registry: int,
    reg: int,
    tmp: str,
) -> tuple[list[dict[str, Any]], str]:
    seq = list(reversed(pairs)) if order == "B_then_A" else list(pairs)
    if len(seq) < 2:
        raise RuntimeError("need at least two credits")
    prefix, last = seq[:-1], seq[-1]
    parent = _fresh(tmp, f"p_{order}_reg{reg}", world, seed_registry=seed_registry)
    taught_prefix = _teach_prefix(parent, world, prefix, tag=f"pre_{order}_reg{reg}")
    parent_rows = stored_rows(parent)
    protected = protected_slots(parent_rows)
    parent_n_viol = int(parent._count_store_violations())
    snap = parent.checkpoint()
    genome = copy.deepcopy(parent.genome)
    parent_id = clone_identity(parent)
    parent_sha = identity_sha(parent_id)
    cells: list[dict[str, Any]] = []
    arm_broke: dict[str, bool] = {}
    complete_bytes: str | None = None
    for arm in ARMS:
        twin = clone_plastic(snap, genome)
        pre_id = clone_identity(twin)
        if not identities_match(parent_id, pre_id):
            raise RuntimeError(f"clone identity mismatch before {arm} {order} reg{reg}")
        if arm == "complete" and not uses_native_credit(twin):
            raise RuntimeError("complete must use native _credit_act_p1_episode")
        bind_component(twin, arm)
        if arm == "complete" and not uses_native_credit(twin):
            raise RuntimeError("complete wrapping is forbidden")
        cue, handle = last
        t = teach_one(twin, world, handle, tag=f"{arm}_{order}_reg{reg}_c7", symbols=[cue])
        taught = list(taught_prefix) + [
            {
                "cue": cue,
                "handle": handle,
                "adv": float(t["adv"]),
                "n_episodes": len(twin._episodes),
            }
        ]
        scored = _score_arm(
            twin=twin,
            world=world,
            pairs=pairs,
            taught=taught,
            parent_rows=parent_rows,
            protected=protected,
            tag=f"{arm}_{order}_reg{reg}",
        )
        if arm == "complete":
            replica = clone_plastic(snap, genome)
            if not uses_native_credit(replica):
                raise RuntimeError("complete replica must stay native")
            teach_one(replica, world, handle, tag=f"complete_eq_{order}_reg{reg}_c7", symbols=[cue])
            if identity_sha(clone_identity(twin)) != identity_sha(clone_identity(replica)):
                raise RuntimeError("complete is not byte-equivalent across native clones")
            complete_bytes = identity_sha(clone_identity(twin))
        rec = {
            "kind": "split",
            "arm": arm,
            "id": f"split|c8|{order}|reg{reg}|{arm}",
            "order": order,
            "reg": int(reg),
            "seed_registry": int(seed_registry),
            "n_cues": 8,
            "act_recall_mode": TREATMENT_MODE,
            "taught": taught,
            "parent_n_violations": int(parent_n_viol),
            "parent_store_zero": bool(parent_n_viol == 0),
            "parent_identity_sha": parent_sha,
            "clone_matched_parent": True,
            "complete_uses_native_credit_act_p1_episode": bool(arm == "complete"),
            "n_awake_updates": int((t.get("rehearsal_burst") or {}).get("total_updates") or 0),
            "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
            **scored,
        }
        rec["passed"] = not bool(rec["previously_correct_broke"])
        rec["behavioral_pass"] = bool(rec["passed"])
        assert_finite_record(rec, ctx=rec["id"])
        cells.append(rec)
        arm_broke[arm] = bool(rec["previously_correct_broke"])
    if complete_bytes is None:
        raise RuntimeError("complete arm missing")
    if not identities_match(parent_id, clone_identity(parent)):
        raise RuntimeError(f"parent mutated {order} reg{reg}")
    route = classify_world(arm_broke)
    for rec in cells:
        rec["world_route"] = route
        rec["parent_unchanged"] = True
        rec["complete_native_replica_sha"] = complete_bytes
    return cells, route


def _decision(world_routes: list[str]) -> tuple[str, str, dict[str, Any]]:
    diagnostic = [r for r in world_routes if r != "no_rebreak"]
    flags = {
        "n_worlds": len(world_routes),
        "n_diagnostic": len(diagnostic),
        "n_no_rebreak": sum(1 for r in world_routes if r == "no_rebreak"),
        "routes": list(world_routes),
        "diagnostic_routes": list(diagnostic),
        "v39_gate_open": bool(diagnostic) and set(diagnostic) == {"oneshot_causal"},
    }
    if not diagnostic:
        return "creditsplit_no_diagnostic", "creditsplit_no_diagnostic", flags
    uniq = set(diagnostic)
    if uniq == {"write_causal"}:
        code = "creditsplit_write_causal"
    elif uniq == {"oneshot_causal"}:
        code = "creditsplit_oneshot_causal"
    elif uniq == {"burst_causal"}:
        code = "creditsplit_burst_causal"
    elif uniq == {"interaction_only"}:
        code = "creditsplit_interaction_only"
    else:
        code = "creditsplit_mixed_oneshot_and_burst"
    return code, code, flags


def _git_head() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()


def _git_clean() -> tuple[bool, str]:
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip()
    return (status == ""), ("clean" if status == "" else status)


def eval_dev_battery() -> dict[str, Any]:
    p = load_prereg()
    frozen = str(p.get("frozen_runner_sha") or "")
    if frozen and sha_file(THIS) != frozen:
        raise RuntimeError("TM035 runner SHA drifted after freeze push")
    if sha_file(TM032_RUNNER) != p["tm032_runner_sha"]:
        raise RuntimeError("TM032 runner SHA drifted")
    if sha_file(TM034_RUNNER) != p["tm034_runner_sha"]:
        raise RuntimeError("TM034 runner SHA drifted")
    if hashlib.sha256(TM032_DEV.read_bytes()).hexdigest() != p["tm032_dev_sha"]:
        raise RuntimeError("TM032 DEV SHA drifted")
    if hashlib.sha256(TM032_DEC.read_bytes()).hexdigest() != p["tm032_decision_sha"]:
        raise RuntimeError("TM032 decision SHA drifted")
    if hashlib.sha256(TM034_DEV.read_bytes()).hexdigest() != p["tm034_dev_sha"]:
        raise RuntimeError("TM034 DEV SHA drifted")
    if hashlib.sha256(TM034_DEC.read_bytes()).hexdigest() != p["tm034_decision_sha"]:
        raise RuntimeError("TM034 decision SHA drifted")
    if int(EPISODE_REPLAY_EPOCHS) != int(p["hard_budget_passes"]):
        raise RuntimeError("hard budget must remain 16")
    ids = expected_cell_ids()
    wi = int(p.get("world_index") or 0)
    world = capacity_world(wi, DEV_DOMAIN, n_cues=8, n_handles=2)
    pairs = mapping_pairs(world, flip=False)
    import tempfile

    cells: list[dict[str, Any]] = []
    world_routes: list[str] = []
    tmp = tempfile.TemporaryDirectory(prefix="cs_dev_")
    try:
        for ri, seed in enumerate(registry_seeds()):
            for order in list(p["orders"]):
                recs, route = eval_world(
                    world=world,
                    pairs=pairs,
                    order=order,
                    seed_registry=int(seed),
                    reg=ri,
                    tmp=tmp.name,
                )
                cells.extend(recs)
                world_routes.append(str(route))
    finally:
        tmp.cleanup()
    if [c["id"] for c in cells] != ids:
        raise RuntimeError("cell id order drifted")
    if len(world_routes) != EXPECTED_N_WORLDS:
        raise RuntimeError("world count drifted")
    code, then, flags = _decision(world_routes)
    clean, clean_status = _git_clean()
    return {
        "lab": LAB,
        "n_cells": len(cells),
        "n_worlds": len(world_routes),
        "cells": cells,
        "world_routes": world_routes,
        "decision_code": code,
        "decision_then": then,
        "phase_flags": flags,
        "git_head": _git_head(),
        "frozen_runner_sha": frozen,
        "manifest_sha": MANIFEST_SHA,
        "domain": DEV_DOMAIN,
        "hard_budget_passes": int(EPISODE_REPLAY_EPOCHS),
        "fit_44_row_updates": False,
        "plateau_relaxed": False,
        "v38_repair": False,
        "v39_freeze": False,
        "clean_tree": bool(clean),
        "clean_tree_status": clean_status,
    }


def refuse_dev_lock() -> None:
    if DEV_LOCK.exists():
        raise RuntimeError(f"refuse overwrite {DEV_LOCK}")


def run_dev() -> dict[str, Any]:
    refuse_dev_lock()
    return eval_dev_battery()


def _json_default(o: Any) -> Any:
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    raise TypeError(type(o))


def write_dev_lock(out: dict[str, Any]) -> None:
    refuse_dev_lock()
    DEV_LOCK.write_text(json.dumps(out, indent=2, default=_json_default) + "\n", encoding="utf-8")


def write_decision(out: dict[str, Any]) -> None:
    if not DEV_LOCK.exists():
        raise RuntimeError("write DEV lock before decision lock")
    dec = {
        "version": "TM.0.35.CREDITSPLIT.DECISION",
        "product": "0.0.004",
        "manifest_sha": MANIFEST_SHA,
        "decision": {"code": out["decision_code"], "then": out["decision_then"], "phase_flags": out["phase_flags"]},
        "dev_lock_sha": hashlib.sha256(DEV_LOCK.read_bytes()).hexdigest(),
        "git_head": out.get("git_head"),
        "frozen_runner_sha": out.get("frozen_runner_sha"),
        "hard_budget_passes": out.get("hard_budget_passes"),
        "fit_44_row_updates": False,
        "plateau_relaxed": False,
        "v38_repair": False,
        "v39_freeze": False,
        "v39_gate_open": bool((out.get("phase_flags") or {}).get("v39_gate_open")),
        "note": "TM035 credit-7 component-split decision. Product remains 0.0.004.",
    }
    DECISION.write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")


