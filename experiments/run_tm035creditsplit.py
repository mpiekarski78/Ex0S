        "",
        "Credit-7 write / one-shot / burst / complete split after TM034. Product **0.0.004**.",
        "",
        f"## Decision: `{out['decision_code']}`",
        "",
        "No neural edit. v38 unchanged. 16-pass cap unchanged. 44 not installed. v39 not frozen.",
        "",
