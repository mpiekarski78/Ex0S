def fit_time_decoder(bundle: dict[str, Any], rows: list[dict[str, Any]]) -> tuple[np.ndarray, bool]:
    parent_h = str(bundle["w0_hash"])
    cons = list(bundle["ref_pairs"]) + pairs_of(rows)
    rec, W_star = solve_ceiling(bundle["W0"], cons, bundle["vocab"])
    parent_hash_unchanged(bundle["ag"], parent_h)
    W_use = bundle["W0"] if W_star is None else W_star
    del W_star
    return W_use, bool(rec.get("feasible"))


def score_map(
    bundle: dict[str, Any],
    *,
    spec: dict[str, Any],
    pairs: list[dict[str, Any]],
    W_prefix: np.ndarray,
    W_later: np.ndarray,
) -> dict[str, Any]:
    n = int(bundle["n"])
    later_mapped = [(str(r["handle"]), apply_later_to_prefix(r["b"], spec, n)) for r in pairs]
    prefix_mapped = [(str(r["handle"]), apply_prefix_to_later(r["a"], spec, n)) for r in pairs]
    prefix_on_later = score_eval(W_prefix, later_mapped, bundle["vocab"])
    later_on_prefix = score_eval(W_later, prefix_mapped, bundle["vocab"])
    parent_hash_unchanged(bundle["ag"], str(bundle["w0_hash"]))
    restored = bool(
        prefix_on_later["n_ok"] == prefix_on_later["n_need"]
        and later_on_prefix["n_ok"] == later_on_prefix["n_need"]
    )
    err_fwd = mean_l2([x[1] for x in prefix_mapped], [r["b"] for r in pairs], n)
    err_back = mean_l2([x[1] for x in later_mapped], [r["a"] for r in pairs], n)
    return {
        "restored": restored,
        "prefix_on_mapped_later": prefix_on_later,
        "later_on_mapped_prefix": later_on_prefix,
        "held_out_error_prefix_to_later": err_fwd,
        "held_out_error_later_to_prefix": err_back,
    }


