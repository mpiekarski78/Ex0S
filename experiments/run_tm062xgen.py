    n = int(bundle["n"])
    W_prefix, p_ok = fit_time_decoder(bundle, bundle["prefix_rows"])
    W_later, l_ok = fit_time_decoder(bundle, bundle["later_rows"])
    prefix_sc = score_eval(W_prefix, pairs_of(bundle["prefix_rows"]), bundle["vocab"])
