def expected_cell_ids() -> list[str]:
    p = load_prereg()
    probes = [str(x) for x in p["probes"]]
    setup = [f"decoder|w{wi}" for wi in range(int(p["n_worlds"]))]
    scored = [f"{probe}|w{wi}" for probe in probes for wi in range(int(p["n_worlds"]))]
    ids = setup + scored
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "setup_cell_ids": sorted(setup),
        "scored_cell_ids": sorted(scored),
        "cell_ids": sorted(ids),
        "probes": probes,
    }
    got = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if got != MANIFEST_SHA:
        raise RuntimeError("TM062 manifest drifted")
    frozen = str(p.get("manifest_sha") or "")
    if frozen not in ("PLACEHOLDER_MANIFEST", MANIFEST_SHA) and got != frozen:
        raise RuntimeError("TM062 prereg manifest drifted")
    if len(ids) != EXPECTED_N_CELLS or len(setup) != N_SETUP_CELLS or len(scored) != N_SCORED_CELLS:
        raise RuntimeError("cell count drifted")
    return ids


def aligned_pairs(
    prefix_rows: list[dict[str, Any]],
    later_rows: list[dict[str, Any]],
    handles: list[str],
    n: int,
) -> list[dict[str, Any]]:
    p_by: dict[str, list[np.ndarray]] = defaultdict(list)
    l_by: dict[str, list[np.ndarray]] = defaultdict(list)
    for r in prefix_rows:
        p_by[str(r["handle"])].append(np.asarray(r["p1"], dtype=np.float64).reshape(-1))
    for r in later_rows:
        l_by[str(r["handle"])].append(np.asarray(r["p1"], dtype=np.float64).reshape(-1))
    if any(len(p_by[h]) < 1 or len(l_by[h]) < 1 for h in handles):
        raise RuntimeError("transport alignment missing an action role")
    n_occ = min(min(len(p_by[h]) for h in handles), min(len(l_by[h]) for h in handles))
    out: list[dict[str, Any]] = []
    for occ in range(int(n_occ)):
        for h in handles:
            out.append(
                {
                    "handle": str(h),
                    "occ": int(occ),
                    "a": unit_or_zero(p_by[h][occ], n),
                    "b": unit_or_zero(l_by[h][occ], n),
                    "correspondence": "organism_emitted_action_and_occurrence",
                }
            )
    return out


def stacks_of(pairs: list[dict[str, Any]]) -> tuple[np.ndarray, np.ndarray]:
    return np.stack([p["a"] for p in pairs], axis=0), np.stack([p["b"] for p in pairs], axis=0)


def design_stats(A: np.ndarray, *, ridge_l2: float | None = None) -> dict[str, Any]:
    s = np.linalg.svd(np.asarray(A, dtype=np.float64), compute_uv=False)
    eps = 1e-9
    pos = s[s > eps]
    rank = int(pos.size)
    cond = float(pos[0] / pos[-1]) if rank >= 1 else float("inf")
    if ridge_l2 is None:
        dof = float(rank)
    else:
        lam = float(ridge_l2)
        dof = float(np.sum((s * s) / (s * s + lam)))
    return {
        "rank_A": rank,
        "cond_A": cond,
        "effective_dof": dof,
        "n_fit": int(A.shape[0]),
        "n_dim": int(A.shape[1]),
    }


def mean_l2(mapped: list[np.ndarray], targets: list[np.ndarray], n: int) -> float:
    if not mapped:
        return float("nan")
    errs = [
        float(np.linalg.norm(unit_or_zero(m, n) - unit_or_zero(t, n)))
        for m, t in zip(mapped, targets)
    ]
    return float(np.mean(errs))


def fit_diagonal(A: np.ndarray, B: np.ndarray) -> np.ndarray:
    s = np.zeros(int(A.shape[1]), dtype=np.float64)
    for j in range(int(A.shape[1])):
        aj = A[:, j]
        denom = float(np.dot(aj, aj))
        s[j] = float(np.dot(aj, B[:, j]) / denom) if denom > 1e-12 else 1.0
    return s


def fit_affine(A: np.ndarray, B: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    n = int(A.shape[1])
    scale = np.zeros(n, dtype=np.float64)
    bias = np.zeros(n, dtype=np.float64)
    ones = np.ones((int(A.shape[0]), 1), dtype=np.float64)
    for j in range(n):
        x = np.concatenate([A[:, j : j + 1], ones], axis=1)
        coef, *_ = np.linalg.lstsq(x, B[:, j], rcond=None)
        scale[j] = float(coef[0])
        bias[j] = float(coef[1])
    return scale, bias


def fit_ridge(A: np.ndarray, B: np.ndarray, lam: float) -> np.ndarray:
    n = int(A.shape[1])
    ata = A.T @ A + float(lam) * np.eye(n)
    return np.linalg.solve(ata, A.T @ B)


def fit_low_rank(A: np.ndarray, B: np.ndarray, rank: int) -> np.ndarray:
    q = fit_linear(A, B)
    u, s, vt = np.linalg.svd(q, full_matrices=False)
    r = min(int(rank), int(s.size))
    return (u[:, :r] * s[:r]) @ vt[:r]


def apply_prefix_to_later(x: np.ndarray, spec: dict[str, Any], n: int) -> np.ndarray:
    v = np.asarray(x, dtype=np.float64).reshape(-1)
    kind = str(spec["kind"])
    if kind in ("diagonal", "affine"):
        y = spec["scale"] * v
        if kind == "affine":
            y = y + spec["bias"]
        return unit_or_zero(y, n)
    return map_prefix_to_later(v, spec["Q"], orthogonal=bool(spec.get("orthogonal")))


def apply_later_to_prefix(x: np.ndarray, spec: dict[str, Any], n: int) -> np.ndarray:
    v = np.asarray(x, dtype=np.float64).reshape(-1)
    kind = str(spec["kind"])
    if kind in ("diagonal", "affine"):
        s = np.asarray(spec["scale"], dtype=np.float64)
        y = v.copy()
        if kind == "affine":
            y = y - spec["bias"]
        denom = np.where(np.abs(s) > 1e-12, s, 1.0)
        y = y / denom
        return unit_or_zero(y, n)
    return map_later_to_prefix(v, spec["Q"], orthogonal=bool(spec.get("orthogonal")))


def fit_spec(kind: str, A: np.ndarray, B: np.ndarray, p: dict[str, Any]) -> dict[str, Any]:
    n = int(A.shape[1])
    if kind == "identity":
        return {"kind": kind, "Q": np.eye(n), "orthogonal": True}
    if kind == "orthogonal":
        return {"kind": kind, "Q": fit_orthogonal(A, B), "orthogonal": True}
    if kind == "diagonal":
        return {"kind": kind, "scale": fit_diagonal(A, B), "orthogonal": False}
    if kind == "affine":
        scale, bias = fit_affine(A, B)
        return {"kind": kind, "scale": scale, "bias": bias, "orthogonal": False}
    if kind == "low_rank":
        return {"kind": kind, "Q": fit_low_rank(A, B, int(p["low_rank"])), "orthogonal": False}
    if kind == "ridge":
        return {"kind": kind, "Q": fit_ridge(A, B, float(p["ridge_l2"])), "orthogonal": False}
    if kind in ("min_norm", "in_sample_linear"):
        return {"kind": kind, "Q": fit_linear(A, B), "orthogonal": False}
    raise RuntimeError(kind)


