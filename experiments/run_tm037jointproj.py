def valid_episodes(ag: NeuralCortex) -> list[tuple[int, dict[str, Any]]]:
    return [(i, ep) for i, ep in enumerate(ag._episodes) if ep.get("valid")]


def ranking_inner(W: np.ndarray, d: np.ndarray, x: np.ndarray) -> float:
    return float(np.dot(d, W @ x))


def geometric_gamma(W: np.ndarray, d: np.ndarray, x: np.ndarray) -> float:
    row = W.T @ d
    dn = float(np.linalg.norm(row))
    if dn <= PROTO_EPS:
        return 0.0
    return float(np.dot(row, x) / dn)


def pa_project_W(W: np.ndarray, d: np.ndarray, x: np.ndarray, b: float) -> tuple[np.ndarray, bool]:
    inner = ranking_inner(W, d, x)
    a_f2 = float(np.dot(d, d) * np.dot(x, x))
    if a_f2 <= PROTO_EPS:
        return W, False
    if inner >= b:
        return W, False
    step = (b - inner) / a_f2
    return W + step * np.outer(d, x), True


def supporting_constraints(ag: NeuralCortex, W_ref: np.ndarray) -> list[dict[str, Any]]:
    """Linearized supporting halfspaces of γ≥τ, one per (episode, rival), b frozen at W_ref."""
    rows: list[dict[str, Any]] = []
    rivals = sorted(str(h) for h in ag.motor_vocab)
    tau = float(ACT_MARGIN_FLOOR)
    for slot, ep in valid_episodes(ag):
        if float(ep["adv"]) <= ELIG_EPS:
            continue
        handle = str(ep["handle"])
        if handle not in ag.motor_vocab:
            continue
        x = ag._unit_or_zero(np.asarray(ep["p1"], dtype=np.float64))
        if float(np.max(np.abs(x))) <= ELIG_EPS:
            continue
        v_h = np.asarray(ag.motor_vocab[handle], dtype=np.float64).reshape(-1)
        for rival in rivals:
            if rival == handle:
                continue
            v_r = np.asarray(ag.motor_vocab[rival], dtype=np.float64).reshape(-1)
            d = v_h - v_r
            if float(np.linalg.norm(d)) <= PROTO_EPS:
                continue
            b = tau * float(np.linalg.norm(W_ref.T @ d))
            rows.append(
                {
                    "key": f"{int(slot)}|{handle}|{rival}",
                    "slot": int(slot),
                    "handle": handle,
                    "rival": rival,
                    "d": d,
                    "x": x,
                    "b": float(b),
                }
            )
    return rows


def run_joint_projection(ag: NeuralCortex, *, corrections: bool) -> dict[str, Any]:
    W0 = ag._from_t(ag.W_act_query)
    corrections_state: dict[str, np.ndarray] = {}
    if corrections:
        raw = getattr(ag, "_act_proj_corrections", None) or {}
        for k, v in raw.items():
            corrections_state[str(k)] = np.asarray(v, dtype=np.float64).copy()
    W = W0.copy()
    passes: list[dict[str, Any]] = []
    total_proj = 0
    first: int | None = None
    exhausted = False
    n_constraints = 0
    for idx in range(1, EPISODE_REPLAY_EPOCHS + 1):
        n_before = int(ag._count_store_violations())
        cons = supporting_constraints(ag, W)
        n_constraints = len(cons)
        n_hit = 0
        for c in cons:
            key = str(c["key"])
            if corrections:
                I = corrections_state.get(key)
                if I is None:
                    I = np.zeros_like(W)
                y = W - I
                Wp, hit = pa_project_W(y, c["d"], c["x"], float(c["b"]))
                corrections_state[key] = Wp - y
                W = Wp
            else:
                W, hit = pa_project_W(W, c["d"], c["x"], float(c["b"]))
            n_hit += int(hit)
            total_proj += int(hit)
        ag.W_act_query = ag._to_t(W)
        ag._clip_and_consolidate({"W_act_query"}, mix_slow=False)
        W = ag._from_t(ag.W_act_query)
        n_after = int(ag._count_store_violations())
        passes.append(
            {
                "pass_index": int(idx),
                "n_projections": int(n_hit),
                "n_constraints": int(n_constraints),
                "violations_before": int(n_before),
                "violations_after": int(n_after),
            }
        )
        if n_after == 0:
            first = idx
            break
    else:
        exhausted = True
    if corrections:
        ag._act_proj_corrections = {k: v.copy() for k, v in corrections_state.items()}
    delta = float(np.linalg.norm(W - W0))
    return {
        "n_awake_updates": int(total_proj),
        "n_projections": int(total_proj),
        "n_passes": len(passes),
        "n_constraints": int(n_constraints),
        "budget_exhausted": bool(exhausted),
        "first_converged_pass": first,
        "corrections": bool(corrections),
        "b_frozen_per_cycle": True,
        "clip_at_end_of_pass": True,
        "mix_slow": False,
        "fitted_learning_rate": False,
        "frobenius_delta": delta,
        "passes": passes,
    }


