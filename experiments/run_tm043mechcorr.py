def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dev", action="store_true")
    ap.add_argument("--run-dev", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        print(json.dumps(smoke(), indent=2, default=_json_default))
        return
    if args.dev or args.run_dev:
        out = run_dev()
        write_dev_lock(out)
        write_decision(out)
        write_candidate_review(out)
        write_results_md(out)
        refuse_candidate_lock()
        print(
            json.dumps(
                {
                    "decision_code": out["decision_code"],
                    "n_cells": out["n_cells"],
                    "candidate_v40_lock": False,
                    "separate_candidate_review_open": out["phase_flags"]["separate_candidate_review_open"],
                    "lineage_stop": out["lineage_stop"],
                    "n_setup_ok": out["phase_flags"]["n_setup_ok"],
                    "n_continuity_ok": out["phase_flags"]["n_continuity_ok"],
                },
                indent=2,
            )
        )
        return
    ap.print_help()


if __name__ == "__main__":
    main()
