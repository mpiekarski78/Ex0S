def expected_cell_ids() -> list[str]:
    p = load_prereg()
    ids = [f"mechcorr|tm039|reg1|{order}" for order in list(p["orders"])]
    payload = {
        "lab": LAB,
        "domains": sorted(p["domains"].items()),
        "cell_ids": sorted(ids),
        "pinned_tm039_ids": sorted(p["pinned_tm039_ids"]),
    }
    if hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() != MANIFEST_SHA:
        raise RuntimeError("TM043 manifest drifted")
    if len(ids) != EXPECTED_N_CELLS:
        raise RuntimeError("cell count drifted")
    if list(p["pinned_tm039_ids"]) != list(PINNED_TM039_IDS):
        raise RuntimeError("pinned TM039 ids drifted")
    return ids


def setup_precondition_reasons(
    *,
    violations_after_v37: int,
    fallback_invoked: bool,
    solver_installed: bool,
    parent_identity_sha: str,
    v37_w_hash: str,
    installed_w_hash: str,
    pin: dict[str, Any],
) -> list[str]:
    reasons: list[str] = []
    if int(violations_after_v37) <= 0:
        reasons.append("violations_after_v37")
    if not bool(fallback_invoked):
        reasons.append("fallback_invoked")
    if not bool(solver_installed):
        reasons.append("solver_installed")
    if str(parent_identity_sha) != str(pin["parent_identity_sha"]):
        reasons.append("parent_identity_sha")
    if str(v37_w_hash) != str(pin["v37_w_hash"]):
        reasons.append("v37_w_hash")
    if str(installed_w_hash) != str(pin["installed_w_hash"]):
        reasons.append("installed_w_hash")
    return reasons


def eval_mechcorr(
    *,
    order: str,
    tmp: str,
) -> dict[str, Any]:
    p = load_prereg()
    pin = p["pinned_cells"][order]
    cell_id = f"mechcorr|tm039|reg1|{order}"
    world = capacity_world(int(p["world_index"]), MECH_DOMAIN, n_cues=int(p["n_cues"]), n_handles=int(p["n_handles"]))
    pairs = mapping_pairs(world, flip=False)
    seq = list(reversed(pairs)) if order == "B_then_A" else list(pairs)
    geo = geometry_parent(
        world=world,
        pairs=pairs,
        order=order,
        seed_registry=int(p["tm039_registry_seed"]),
        reg=int(p["tm039_diagnostic_reg"]),
        tmp=tmp,
    )
    ag = clone_plastic(geo["ag"].checkpoint(), copy.deepcopy(geo["ag"].genome))
    set_arm(ag, "fallback_joint")
    slog = bind_socp_logger(ag)
    eta = eta_act(ag)
    apply_native(ag, new_ep=geo["new_ep"], eta=eta)
    n_after_v37 = int(ag._count_store_violations())
    pre = weight_hash(ag._from_t(ag.W_act_query))
    fallback_invoked = bool(n_after_v37 > 0)
    socp: dict[str, Any] = {}
    if fallback_invoked:
        socp = try_install_socp(ag)
    solver_installed = bool(socp.get("applied"))
    installed_hash = weight_hash(ag._from_t(ag.W_act_query))
    reasons = setup_precondition_reasons(
        violations_after_v37=n_after_v37,
        fallback_invoked=fallback_invoked,
        solver_installed=solver_installed,
        parent_identity_sha=str(geo["identity_sha"]),
        v37_w_hash=pre,
        installed_w_hash=installed_hash,
        pin=pin,
    )
    out: dict[str, Any] = {
        "kind": "mechanistic_correction",
        "id": cell_id,
        "arm": "fallback_joint",
        "order": order,
        "reg": int(p["tm039_diagnostic_reg"]),
        "seed_registry": int(p["tm039_registry_seed"]),
        "pinned_tm039_id": pin["tm039_id_fallback"],
        "evidence": "mechanistic_tm039_reg1_diagnostic_not_untouched_generalization",
        "installed": solver_installed,
        "setup_precondition_ok": not reasons,
        "setup_precondition_reasons": reasons,
        "organism_failure": False,
        "process": {
            "violations_after_v37": n_after_v37,
            "fallback_invoked": fallback_invoked,
            "solver_installed": solver_installed,
            "socp_invoked": fallback_invoked,
            "parent_identity_sha": geo["identity_sha"],
            "v37_w_hash": pre,
            "installed_w_hash": installed_hash,
            "socp": _solver_slice(socp if socp else None),
        },
        "n_store_violations": int(ag._count_store_violations()),
        "candidate_v40_lock": False,
        "not_an_exact_projector": True,
        "behavioral_scorer": "actuator_decision_scores",
    }
    if reasons:
        out["passed"] = False
        out["cell_code"] = "setup_precondition_fail"
        out["continuity_ok"] = False
        out["handoff"] = None
        assert_finite_record(out, ctx=cell_id)
        return out
    cont = _continue_after_install(
        ag,
        world,
        retain_pairs=list(seq),
        new_pairs=[],
        slog=slog,
        n_log_at_install=len(slog),
        tag=f"{cell_id}_c",
        installed_w_hash=installed_hash,
        pre_install_w_hash=pre,
        solver_rec=socp,
    )
    out.update(cont)
    out["passed"] = bool(cont["continuity_ok"])
    out["cell_code"] = "mechcorr_ok" if out["passed"] else "mechcorr_later_fail"
    if not out["passed"]:
        out["organism_failure"] = True
    assert_finite_record(out, ctx=cell_id)
    return out


def _decision(cells: list[dict[str, Any]]) -> tuple[str, str, dict[str, Any]]:
    flags = {
        "n_cells": len(cells),
        "n_setup_ok": sum(1 for c in cells if bool(c.get("setup_precondition_ok"))),
        "n_installed": sum(1 for c in cells if bool(c.get("installed"))),
        "n_continuity_ok": sum(1 for c in cells if bool(c.get("continuity_ok"))),
        "lineage_stop": "canonical_r2_later_learning_not_exercised",
        "candidate_v40_lock": False,
        "candidate_discussion_open_on_frozen_tm042_ladder": False,
        "separate_candidate_review_open": False,
        "mechanistic_is_not_untouched_generalization": True,
        "rerun_natural_cells": False,
        "philosophical_boundary_open": False,
    }
    if any(c.get("cell_code") == "setup_precondition_fail" for c in cells):
        return "setup_precondition_fail", "setup_precondition_fail", flags
    if not all(bool(c.get("continuity_ok")) for c in cells):
        return "mechcorr_later_fail", "mechcorr_later_fail", flags
    flags["separate_candidate_review_open"] = True
    flags["philosophical_boundary_open"] = True
    return "mechcorr_continuity_pass", "mechcorr_continuity_pass", flags


def refuse_eval_natural(path: Path) -> None:
    tree = ast.parse(path.read_text(encoding="utf-8"))

    class V(ast.NodeVisitor):
        def visit_Call(self, node: ast.Call) -> None:
            func = node.func
            name = ""
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            if name == "eval_natural":
                raise RuntimeError(f"TM043 must not rerun natural cells:{path.name}:{node.lineno}")
            self.generic_visit(node)

    V().visit(tree)


